/** Thai (as on the page) → English */
export const SMART_DOC_EN: Readonly<Record<string, string>> = (() => {
  const all: Record<string, string> = { ...WORDS };
  for (const [th, en] of DOCS) {
    all[`บันทึก${th}เรียบร้อย`] = `${en} saved`;
    all[`พิมพ์${th}`] = `Print ${en.toLowerCase()}`;
    all[`${th} (${prefixOf(en)})`] = `${en} (${prefixOf(en)})`;
  }
  return all;
})();

function prefixOf(en: string): string {
  return { Quotation: 'QT', Booking: 'SO', 'Delivery Note': 'DO', Receipt: 'RV' }[en] ?? '';
}

