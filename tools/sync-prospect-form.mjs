// project_root.css: rules whose selector is only an attribute selector — `[role="combobox"] { … }` (the inputs and the labels of the PrimeFaces selects / date pickers),
// `[type="text"] { padding: 10px }` and `.title-text-value, [role="radio"] > label { … }` (the class part is above; the radio labels break a Thai word anywhere with
// overflow-wrap / word-break: break-word). globalClassRules leaves every selector with an attribute out; these are what the page relies on.
{
  const css = read('css/project_root.css');
  const vars = new Map();
  for (const m of css.matchAll(/:root\s*\{([^}]*)\}/g)) for (const d of m[1].matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) vars.set(d[1], d[2].trim());
  const resolve = (v, depth = 0) => (depth > 5 ? v : v.replace(/var\((--[\w-]+)\s*(?:,\s*([^)]*))?\)/g, (all, name, fallback) => (vars.has(name) ? resolve(vars.get(name), depth + 1) : fallback !== undefined ? fallback.trim() : all)));
  const ATTR_ONLY = /^\[(?:role|type)="[\w-]+"\](?: > label)?$/;
  const kept = [];
  postcss.parse(css, { from: 'css/project_root.css' }).walkRules((rule) => {
    const sels = rule.selectors.map((x) => x.trim()).filter((x) => ATTR_ONLY.test(x));
    if (!sels.length) return;
    const body = rule.nodes.filter((n) => n.type === 'decl').map((d) => `${d.prop}: ${resolve(d.value).replace(/NotoSansThai/g, "'Noto Sans Thai'")}${d.important ? ' !important' : ''};`).join(' ');
    kept.push(`${sels.map((x) => `${ADAPT_SCOPE} ${x}`).join(', ')} { ${body} }  /* css/project_root.css */`);
  });
  if (kept.length !== 3) throw new Error(`project_root.css: expected 3 attribute-only rules ([role=radio] > label, [role=combobox], [type=text]), found ${kept.length}`);
  adapted += kept.join('\n') + '\n';
}
