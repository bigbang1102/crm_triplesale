function renderMarkup(updateTargets) {
  const r = createRenderer({
    mode: 'ng',
    read,
    vars: { contractView: new Dyn('bean') },
    formAction: '#',
    pfStrict: true,
    updateTargets,
    linkTarget: () => {
      throw new Error('contracts_master_data: an h:link / p:linkButton (not expected on this page)');
    },
    rewriteAttr: (elName, name, raw) => {
      const nav = /^window\.location\.href = '([^']+)';$/.exec(raw);
      if (name === 'onclick' && nav) return `ptNavigate('${navigateOf(nav[1])}');`;
      if (elName === 'a' && name === 'href' && /\.face\?/.test(raw)) {
        // a link to another page of the Java app, with the id of the record in it: the route of this app (the EL of the id stays)
        const masked = raw.replace(/#\{[^}]*\}/g, (m) => `ZZEL${[...m].length}ZZ`);
        const els = [...raw.matchAll(/#\{[^}]*\}/g)].map((m) => m[0]);
        const route = javaLinkToRoute(masked);
        if (!route) throw new Error(`java-links.ts has no rule for ${raw}`);
        return route.replace(/ZZEL\d+ZZ/g, () => els.shift());
      }
      return raw;
    },
    viewDate: (v) => v,
  });
  const markup = r.renderFile(FILE, 'content');
  return { r, markup };
}
