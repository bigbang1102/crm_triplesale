/** the text of a script as the browser got it from the server: a script without CDATA is XML text (&amp; &lt; &gt; are decoded), the CDATA wrappers of the others go */
const asServed = (text) => {
  const cdata = text.includes('<![CDATA[');
  let t = cdata ? text : text.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
  t = t.replace(/^\s*\/\/<!\[CDATA\[\n/, '\n').replace(/\n\s*\/\/\]\]>\s*$/, '\n');
  return t;
};
