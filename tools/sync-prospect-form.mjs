  const host = new RegExp(`^${HOST} \\{ display: contents; (font-size: [^;]+; color: [^;]+;) \\}$`, 'm').exec(adapted);
  const dark = new RegExp(`^html\\[data-theme='dark'\\] ${HOST} \\{ (color: [^;]+;) \\}$`, 'm').exec(adapted);
  if (!host || !dark) throw new Error('the host rule of the adaptation was not found');
  adapted += `:where(.cl-modal-overlay) { ${host[1]} }  /* (the modals of the page, moved into <body>: the text of the Java <body>) */\nhtml[data-theme='dark'] :where(.cl-modal-overlay) { ${dark[1]} }\n`;
