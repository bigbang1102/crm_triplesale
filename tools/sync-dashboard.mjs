#!/usr/bin/env node
/**
 * Regenerates the Dashboard page ("แดชบอร์ด", route /dashboard — 10 tabs) from the Java original so the two can never drift
 * while both exist:
 *
 *   npm run dashboard:sync          (Java project = ../triple_sale_main, or set TS_JAVA_ROOT)
 *
 *   Java  web/pages/dashboard.xhtml          <style>   ->  src/app/features/dashboard/dashboard.scss   (+ Angular adaptation block)
 *   Java  web/pages/dashboard_company.xhtml  markup    ->  src/app/features/dashboard/dashboard.html
 *   Java  web/pages/dashboard_company.xhtml  <script>  ->  src/app/features/dashboard/dashboard.engine.ts
 *
 * dashboard.xhtml is the shell of the page (title, ECharts, the big stylesheet, one <ui:include>) and dashboard_company.xhtml
 * is its body: the header filter bar, the ten tab panes and ~6,500 lines of client logic. The two iframes of the page
 * (ปฏิทินงาน, KPI-EventMovement) are separate documents: tools/sync-dashboard-frames.mjs.
 *
 * The Java files are only READ. The outputs carry a "GENERATED" header — change this script (the swap() list / the
 * adaptation block), never the output. A swap() that no longer matches stops the run on purpose: the original changed in a
 * place the port depends on.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { between, darkPort, editor, markupToTemplate, reader, undeclaredNames } from './lib/port.mjs';
import { adaptation, engineScaffold } from './lib/port-kit.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const java = resolve(process.env.TS_JAVA_ROOT ?? join(root, '..', 'triple_sale_main'), 'web');
const out = join(root, 'src/app/features/dashboard');
mkdirSync(out, { recursive: true });

const read = reader(java);
const GENERATED = `GENERATED by tools/sync-dashboard.mjs from web/pages/dashboard.xhtml + dashboard_company.xhtml — do not edit; change the script and run \`npm run dashboard:sync\`.`;
const shell = read('pages/dashboard.xhtml');
const company = read('pages/dashboard_company.xhtml');
const SCOPE = ':where(.dbsun-root)';

/* ================================================================================== markup */
const mFrom = company.indexOf('<div class="dbsun-root">');
const mTo = company.indexOf('<script>', mFrom);
if (mFrom < 0 || mTo < 0) throw new Error('dashboard_company.xhtml: markup boundaries not found');
const markup = editor('dashboard_company.xhtml markup', company.slice(mFrom, mTo).replace(/\s+$/, ''));

// the one <style> inside a tab pane (the "status block" toggle) is part of the page stylesheet
const STYLE_OPEN = '    <style>\n      .dbsun-root .status-block-toggle{';
const sFrom = markup.text.indexOf(STYLE_OPEN);
const sTo = markup.text.indexOf('</style>', sFrom);
if (sFrom < 0 || sTo < 0) throw new Error('dashboard_company.xhtml: the status-block <style> was not found');
const inner = markup.text.slice(sFrom + '    <style>\n'.length, sTo).replace(/\s+$/, '');
markup.text = markup.text.slice(0, sFrom) + markup.text.slice(sTo + '</style>'.length).replace(/^\n/, '');
if (/<style/.test(markup.text.replace(/<!--[\s\S]*?-->/g, ''))) throw new Error('dashboard_company.xhtml markup: another <style> is left');

// values the server rendered into the text (DashboardView getters) -> the host's initial data
const TEXT_EL = ['kpiTotalFmt', 'kpiCountries', 'kpiTopCountry', 'sourceFunnelSubtitle', 'csFunnelSubtitle', 'countryFunnelSubtitle'];
for (const n of TEXT_EL) markup.swap(`#{dashboardView.${n}}`, `ZZEL_${n}_ZZ`);
let tpl = markupToTemplate(markup.text, 'dashboard_company.xhtml markup');
for (const n of TEXT_EL) tpl = tpl.replace(`ZZEL_${n}_ZZ`, `{{ ini.${n} }}`);
if (/ZZEL_/.test(tpl)) throw new Error('dashboard_company.xhtml markup: an EL placeholder is left');
tpl = tpl.replace(/^ {0}/gm, '').replace(/^\n+/, '');
writeFileSync(
  join(out, 'dashboard.html'),
  `<!-- ${GENERATED}
     The markup of dashboard_company.xhtml (its <style> is in dashboard.scss); #{commonBean.msg[…]} -> t('…') ·
     #{dashboardView.kpiTotalFmt …} -> ini.* (the initial data the host passes to the engine too) · everything else is verbatim -->\n` +
    tpl.replace(/\s+$/, '\n'),
);

/* ================================================================================== stylesheet */
const css = editor('dashboard.xhtml style', between(shell, 'dashboard.xhtml', '/*<![CDATA[*/', '</style>'));
css.swap('/*]]>*/', ''); // the CDATA wrapper of Facelets (its end marker sits mid-file in the original)
css.swapAll('body[data-theme="dark"]', "html[data-theme='dark']");
css.swapAll('var(--fs-adj,0px)', 'var(--ts-fs-adj,0px)');
if (/--fs-adj/.test(css.text.replace(/--ts-fs-adj/g, ''))) throw new Error('dashboard css: --fs-adj left over');

/* the GLOBAL rules of the Java stylesheet stack that reach this page (template.xhtml, layout-modify.css, project_root.css, PrimeFlex) —
   read from the originals by tools/lib/port-kit.mjs */
const makeAdaptation = () => adaptation({ read, scope: SCOPE, host: 'ts-dashboard-view', text: tpl + '\n' + js.text });

const scssHeader = `/* Dashboard stylesheet. ${GENERATED}
   The <style> of dashboard.xhtml (ui:define "head") + the small <style> of the status tab, copied verbatim, except:
     body[data-theme="dark"] -> html[data-theme='dark']       (the Angular shell puts the theme on <html>; same specificity)
     --fs-adj                -> --ts-fs-adj                   (A A A font scale token of the Angular shell)
   Loaded with ViewEncapsulation.None: the engine writes HTML strings that need global selectors. */

`;

/* ================================================================================== engine */
const scriptRaw = between(company.slice(mTo), 'dashboard_company.xhtml', '//<![CDATA[', '//]]>');
const js = editor('dashboard_company.xhtml script', scriptRaw.replace(/^\n/, ''));

/* ---- environment: what Facelets / the session / the browser gave the page ---- */
js.swap(`var SUN_API = '#{dashboardView.dashboardSunUrl}';`, `var SUN_API = env.sunApi;`);
js.swap(`var DB_API_BASE = '#{request.contextPath}/dashboard';`, `var DB_API_BASE = env.dbApiBase;`);
js.swap(`var DB_GGWBRANCH = '#{sessionScope.ss_branch_code}';`, `var DB_GGWBRANCH = env.ggwBranch;`);
// every message: #{commonBean.msg["label.x"]} inside a '…' string
js.text = js.text.replace(/'#\{commonBean\.msg\["([\w.]+)"\]\}'/g, (_m, k) => `env.t(${JSON.stringify(k)})`);
// the JSON the server spliced into the source -> the initial data
const JSON_EL = [...js.text.matchAll(/#\{dashboardView\.(\w+Json)\}/g)].map((m) => m[1]);
if (JSON_EL.length !== 24) throw new Error(`dashboard_company.xhtml script: expected 24 dashboardView JSON values, found ${JSON_EL.length}`);
js.text = js.text.replace(/#\{dashboardView\.(\w+Json)\}/g, (_m, n) => `env.initial(${JSON.stringify(n)})`);
js.swapAll(`#{request.contextPath}`, `' + env.ctx + '`, 2); // handled below (frames)
js.text = js.text.replace(/#\{'\$'\}/g, '$');

/* ---- the global "fetch in flight" bar patched window.fetch; here it wraps the injected fetch ---- */
js.swapBlock(
  `(function _setupGlobalApiLoadingTracker() {`,
  `  var _origFetch = window.fetch.bind(window);`,
  `(function _setupGlobalApiLoadingTracker() {
  var _inFlightCount = 0;
  var _hideTimer = null;

  function _refreshLoadingUI() {
    var el = document.getElementById('globalApiLoading');
    if (!el) return;
    if (_inFlightCount > 0) {
      if (_hideTimer) { clearTimeout(_hideTimer); _hideTimer = null; }
      el.classList.add('is-loading');
      el.setAttribute('aria-hidden', 'false');
    } else {
      // debounce ซ่อน 180ms — กัน flicker ระหว่าง chain ของ fetch ต่อเนื่อง
      if (_hideTimer) clearTimeout(_hideTimer);
      _hideTimer = tmo(function () {
        el.classList.remove('is-loading');
        el.setAttribute('aria-hidden', 'true');
      }, 180);
    }
  }

`,
);
js.swap(`  var _origFetch = window.fetch.bind(window);
  window.fetch = function () {`, `  var _origFetch = env.fetch;
  env = Object.assign({}, env, { fetch: function () {`);
js.swap(`    p.then(done, done);
    return p;
  };
  console.log('[Dashboard] global fetch loading tracker installed');`, `    p.then(done, done);
    return p;
  } });
  console.log('[Dashboard] global fetch loading tracker installed');`);
js.text = js.text.replace(/(^|[^.\w$])fetch\(/gm, '$1env.fetch(');
js.swap(`_origFetch.apply(this, arguments)`, `_origFetch.apply(null, arguments)`);

/* ---- ECharts is a module here ---- */
js.swap(`typeof echarts === 'undefined'`, `typeof env.echarts === 'undefined'`);
js.swap(`echarts.init(el, null`, `env.echarts.init(el, null`);
js.swap(`new echarts.graphic.LinearGradient(`, `new env.echarts.graphic.LinearGradient(`);

/* ---- the theme lives on <html> in the Angular shell ---- */
js.swap(`document.body.getAttribute('data-theme') === 'dark'`, `document.documentElement.getAttribute('data-theme') === 'dark'`);
js.swap(
  `new MutationObserver(function () {
  if (typeof renderAllCharts === 'function') renderAllCharts();
}).observe(document.body, { attributes: true, attributeFilter: ['data-theme'] });`,
  `track(new MutationObserver(function () {
  if (typeof renderAllCharts === 'function') renderAllCharts();
})).observe(document.documentElement, { attributes: true, attributeFilter: ['data-theme'] });`,
);

/* ---- URLs built from the Java page address (dead code in the original: the endpoints use DB_API_BASE) ---- */
js.swapAll(`var basePath = (window.location.pathname.replace(/\\/index\\.(xhtml|face)?$/, '').replace(/\\/$/, ''));`, `var basePath = '';`, 9);

/* ---- refresh (the "reload" button) and the legacy "apply filters = reload with a query string" ---- */
js.swap(`setTimeout(() => { location.reload(); }, 200);`, `setTimeout(() => { env.reload(); }, 200);`);
js.swap(`        var url = window.location.pathname + '?' + qs.join('&');`, `        var url = env.pagePath + '?' + qs.join('&');`);
js.swap(`        window.location.href = url;`, `        env.navigate(url);`);

/* ---- the two iframes: the page fetched dashboard_calendar_frame.xhtml / dashboard_kpi_frame.xhtml as HTML text (the
        server had rendered their EL) and put it in srcdoc; here the generated frame modules build that text (env.frame) ---- */
js.swapBlock(
  `  var ctx = '' + env.ctx + '';
  _calFrameFetch = env.fetch(ctx + '/pages/dashboard_calendar_frame.xhtml', { headers: { 'Accept': 'text/html' } })
    .then(function (r) { if (!r.ok) throw new Error('HTTP ' + r.status); return r.text(); })
`,
  `    .catch(function (err) {
      _calFrameFetch = null;`,
  `  _calFrameFetch = env.frame('calendar')
`,
);
js.swap(
  `      env.fetch(_kpiCtx + '/pages/dashboard_kpi_frame.xhtml', { headers: { 'Accept': 'text/html' } })
        .then(function (r) { if (!r.ok) throw new Error('HTTP ' + r.status); return r.text(); })
        .then(function (html) {`,
  `      env.frame('kpi')
        .then(function (html) {`,
);
js.swap(`html = html.replace(/__GOLDAPI__/g, _kpiCtx + '/goldapi');`, `html = html.replace(/__GOLDAPI__/g, env.goldApi);`);
js.swap(`                  _kpiCtx + '/pages/dashboard_kpi_frame.xhtml',`, `                  'dashboard_kpi_frame (generated: tools/sync-dashboard-frames.mjs)',`);

/* ---- window.* functions are global in Java: other code calls them by bare name, the inline handlers by name. Here the
        script is a function, so each is also a local variable (the bare calls) and a property of window (the handlers). ---- */
const WINDOW_FNS = [...new Set([...js.text.matchAll(/^[ \t]*window\.([A-Za-z_]\w*)\s*=\s*function/gm)].map((m) => m[1]))];
if (WINDOW_FNS.length < 12) throw new Error('dashboard_company.xhtml script: expected the window.* functions, found ' + WINDOW_FNS.length);
js.text = js.text.replace(/^([ \t]*)window\.([A-Za-z_]\w*)(\s*=\s*function)/gm, (m, ws, n, rest) => (WINDOW_FNS.includes(n) ? `${ws}${n} = window.${n}${rest}` : m));
js.text = `var ${WINDOW_FNS.join(', ')};\n` + js.text;

/* ---- global listeners and timers are registered through listen() / tmo() so that destroy() can remove them ---- */
js.text = js.text.replace(/\b(document|window)\.addEventListener\(/g, 'listen($1, ');
js.text = js.text.replace(/(^|[^.\w$])setTimeout\(/gm, '$1tmo(');

/* ---- the page script ran while the Java document was still parsing: document.readyState was "loading", so its entry points
        waited for DOMContentLoaded (= after the whole script had run, every var / const assigned) and window "load". Here the
        document finished long ago: the engine plays the same two events itself, at the end of the script (see engineFooter). ---- */
js.swapAll(`listen(document, 'DOMContentLoaded', `, `onReady(`, 6);
js.swapAll(`listen(window, 'load', `, `onLoad(`, 1);
js.text = js.text.replace(/\bdocument\.readyState\b/g, 'readyState');

/* ---- inline handlers (onclick="…") of the markup call functions by name ---- */
const HANDLER_CALLS = new Set(
  [...markup.text.matchAll(/\bon[a-z]+="([^"]*)"/g)].flatMap((h) => [...h[1].matchAll(/(?<![.\w$])([A-Za-z_]\w*)\s*\(/g)].map((x) => x[1])).filter((n) => !['if', 'function', 'return'].includes(n)),
);
const HANDLERS_EXTRA = [...HANDLER_CALLS].filter((n) => !WINDOW_FNS.includes(n));
for (const n of HANDLERS_EXTRA) {
  if (!new RegExp(`(^|\\n)\\s*function ${n}\\b`).test(js.text)) throw new Error(`markup calls ${n}() but the script does not declare it`);
}
const EXPORTED = [...new Set([...WINDOW_FNS, ...HANDLERS_EXTRA])];

/* ---- nothing may reach the page address, the document cookies or global state the shell owns ---- */
{
  const code = js.text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '').replace(/\s\/\/[^\n'"]*$/gm, '');
  if (/#\{/.test(code)) throw new Error('dashboard script: EL left over in code: ' + code.match(/.{0,40}#\{.{0,40}/)[0]);
  if (/\b(setInterval|XMLHttpRequest|localStorage|sessionStorage|document\.cookie)\b/.test(code)) throw new Error('dashboard script: unexpected timer / XHR / storage (add it to destroy())');
  const rest = code.match(/.{0,40}\b(window\.location|location\.(href|pathname|reload)|window\.open|\.face\b|\.xhtml\b).{0,40}/);
  if (rest) throw new Error('dashboard script: a URL read / Java page link is left: ' + rest[0]);
  const bare = code.match(/(^|[^.\w$'"])(fetch|echarts)\(/m);
  if (bare) throw new Error('dashboard script: a bare fetch / echarts call is left: ' + bare[0]);
}

const scaffold = engineScaffold({
  header: `
 * Dashboard page engine. ${GENERATED}
 *
 * The page script of the Java screen, same behaviour line by line: the filter bar (year, month, date range, date basis, the
 * header dropdowns and the filter modal), the ten tabs — ภาพรวม with its widget edit mode and the progressive chart loading
 * (ECharts), Lead, กลุ่มขั้นตอน, Pipeline, สถานะตามกลุ่มขั้นตอน, ลูกค้าตามกลุ่มขั้นตอน, สถานะตามลูกค้า, ตารางลีดทั้งหมด, and the two
 * iframes (ปฏิทินงาน, KPI-EventMovement).
 *
 * WHY it is imperative DOM code and not Angular components: the Java page is a data-driven DOM application whose HTML is
 * drawn from API data as strings. Porting it 1:1 is what guarantees the screen, texts and states are identical to the
 * production system; the template (dashboard.html) and stylesheet (dashboard.scss) are the Java markup / CSS verbatim and the
 * engine binds to them through the same ids / data-* contract as before.
 * "@ts-nocheck": the source is ES5/ES2015 written for a browser global scope; typing it would change it, not port it.
 *
 * What changed versus the Java file (all of it lives in tools/sync-dashboard.mjs):
 *   - the environment is injected (DashboardEnv): messages, fetch, ECharts, the initial JSON the server rendered with EL
 *     (DashboardView), the branch, the HTML of the two frames, navigation — in Java these were EL expressions and the URL;
 *   - the global "request in flight" bar wraps env.fetch instead of patching window.fetch;
 *   - the window.* functions are also local variables; global listeners, timers, the theme observer, the charts, the modal host
 *     and the classes put on <body> are removed by the function returned from startDashboard();
 *   - the theme attribute is read from <html> (the Angular shell) instead of <body>.`,
  envType: 'DashboardEnv',
  envBody: `  /** commonBean.msg['key'] in the active language */
  t: (key: string) => string;
  /** the BFF contract of the page: /dashboard/chart-single, /months, /masterdata-all … and /dashboard/api/v1/sundashboard/* */
  fetch: (input: string, init?: RequestInit) => Promise<Response>;
  /** the ECharts module (Java: <script src="js/echarts-5.6.0/echarts.min.js">) */
  echarts: any;
  /** the JSON values DashboardView rendered into the page with EL (trendJson, groupJson, yearsJson …) */
  initial: (name: string) => any;
  /** #{request.contextPath} — only shown in log lines */
  ctx: string;
  /** DB_API_BASE: where the contract above is served ("/dashboard") */
  dbApiBase: string;
  /** SUN_API: base of the SUN dashboard API (dashboardView.dashboardSunUrl) */
  sunApi: string;
  /** __GOLDAPI__ of the KPI frame */
  goldApi: string;
  /** DB_GGWBRANCH: the branch code of the signed-in user (ss_branch_code) */
  ggwBranch: string;
  /** the SPA path of this page, "/dashboard" */
  pagePath: string;
  /** the HTML (srcdoc) of an iframe tab, placeholders resolved */
  frame: (kind: 'calendar' | 'kpi') => Promise<string>;
  /** window.location.href = url */
  navigate: (url: string) => void;
  /** location.reload(): the host starts the page again with fresh initial data */
  reload: () => void;`,
  fn: 'startDashboard',
  guardExtra: '  var rawFrame = env.frame;',
  envOverrides: `    frame: function (kind) {
      return rawFrame(kind).then(function (v) { return destroyed ? never() : v; });
    }`,
  guardTail: `  var __initial = env.initial;
  env.initial = function (name) { return JSON.parse(JSON.stringify(__initial(name))); };`,
  handlers: HANDLERS_EXTRA,
  exported: EXPORTED,
  cleanup: `    try { Object.keys(echartsInstances).forEach(function (k) { try { echartsInstances[k].dispose(); } catch (e) {} }); } catch (e) {}
`,
  cleanupAfter: `    var host = document.getElementById('dbsunModalHost');
    if (host && host.parentNode) host.parentNode.removeChild(host);
    ['tab-pipeline-active', 'tab-status-active', 'tab-steps-active', 'tab-customer-group-active', 'tab-status-by-customer-active']
      .forEach(function (c) { document.body.classList.remove(c); });
    delete document.body.dataset.bpDdBound;
    delete document.body.dataset.bpEscBound;
`,
});
const engineHeader = scaffold.header;
const engineGuard = scaffold.guard;
const engineFooter = scaffold.footer();
// the engine function body is indented by two spaces like the header
const body = js.text.replace(/\s+$/, '\n');
const engineText = engineHeader + engineGuard + body + engineFooter;
// strict mode (an ES module) vs the sloppy script of Java: no undeclared name may be left, except the three that the original does
// not define either — they are declared inside a block of fireRender() (Annex B hoists them only to that function) and every
// use outside it is behind `typeof x === 'function'` (closeChangelog does not exist at all)
const UNDEFINED_IN_JAVA_TOO = ['closeChangelog', 'refreshMonthsDropdown', '_dbSkel'];
const undeclared = await undeclaredNames(engineText.replace(/^\/\/ @ts-nocheck\n/, ''), UNDEFINED_IN_JAVA_TOO);
if (undeclared.length) throw new Error('dashboard engine: names that are not declared (a ReferenceError in strict mode): ' + undeclared.join(', '));
writeFileSync(join(out, 'dashboard.engine.ts'), engineText);

/* ================================================================================== stylesheet (written last: the dark port reads the script) */
const pageText = tpl + '\n' + css.text + '\n' + inner + '\n' + js.text;
const dark = darkPort(read('resources/support/dark_mode.css'), pageText, SCOPE, 1);
const DARK_PORT = `\n/* ───── dark_mode.css of the Java app, scoped to the page (${dark.kept} rules that can match it, of ${dark.seen} selectors) ───── */\n${dark.css}\n`;
const dedent = (s) => s.replace(/^ {8}/gm, '').replace(/\s+$/, '\n');
writeFileSync(
  join(out, 'dashboard.scss'),
  scssHeader + makeAdaptation() + '\n' + dedent(css.text) + '\n/* ───── <style> of the status tab (dashboard_company.xhtml) ───── */\n' + inner.replace(/^ {6}/gm, '') + '\n' + DARK_PORT,
);

console.log(`Dashboard synced from ${java}: ${EXPORTED.length} window handlers, ${dark.kept} dark rules; markup ${tpl.length} chars, css ${css.text.length}, script ${js.text.length}`);
