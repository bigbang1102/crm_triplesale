#!/usr/bin/env node
/**
 * Regenerates the list of the sales documents ("เอกสารงานขาย": quotation · booking · delivery note · auto-dealer quotation · auto-dealer booking,
 * route /sales/docs/:type) from the Java original so the two can never drift while both exist:
 *
 *   npm run sales-doc-list:sync          (Java project = ../triple_sale_main, or set TS_JAVA_ROOT)
 *
 *   Java  web/pages/sales_doc_type_list.xhtml (+ components/sales_doc_list_mockup.xhtml for the five types, components/sales_doc_list_legacy.xhtml
 *         for an unknown type) markup   ->  src/app/features/sales-docs/list/sales-doc-list.html      (one @case per type, @default = the legacy list)
 *   Java  resources/support/sd2_list.css + sales_doc_list_mockup.css  ->  .../sales-doc-list.scss   (+ Angular adaptation block)
 *   Java  the inline scripts + sales_doc_list_mockup.js               ->  .../sales-doc-list.engine.ts
 *   Java  web/images/icon/fi_search.svg   ->  public/assets/images/icon/fi_search.svg   (byte for byte)
 *
 * The page is read with tools/lib/facelets.mjs (the same reading the comparison harness uses for the Java replica) — one evaluation per type,
 * because the type decides which labels and which columns the table has. The Java files are only READ. The outputs carry a "GENERATED"
 * header — change this script (the swap() list), never the output. A swap() that no longer matches stops the run on purpose: the
 * original changed in a place the port depends on.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { darkPort, editor, reader, undeclaredNames } from './lib/port.mjs';
import { adaptation, engineScaffold } from './lib/port-kit.mjs';
import { CTX_MARK } from './lib/facelets.mjs';
import { checkSaleTabs, elToEnv, msgKey, stripIife } from './lib/sales-doc.mjs';
import { bundles, checkMarkupMessages, checkScriptMessages, dedent, loadSalesPage, messageContexts, portCss, routeOf, toAngularTemplate } from './lib/sales-doc-forms.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const javaRoot = resolve(process.env.TS_JAVA_ROOT ?? join(root, '..', 'triple_sale_main'));
const java = join(javaRoot, 'web');
const out = join(root, 'src/app/features/sales-docs/list');
mkdirSync(out, { recursive: true });

const read = reader(java);
const FILE = 'pages/sales_doc_type_list.xhtml';
const GENERATED = `GENERATED by tools/sync-sales-doc-list.mjs from web/pages/sales_doc_type_list.xhtml + components/sales_doc_list_{mockup,legacy}.xhtml — do not edit; change the script and run \`npm run sales-doc-list:sync\`.`;
const SCOPE = ':where(ts-sales-doc-list-view)';
const { th, en } = bundles(root);
const TYPES = ['qt', 'bk', 'ob', 'aq', 'ad'];

/* ================================================================================== the Facelets page, once per type */
const variants = Object.fromEntries([...TYPES.map((t) => [t, { doc: t }]), ['', { doc: '' }]].map(([k, params]) => [k, loadSalesPage(read, FILE, params)]));
const legacy = variants[''];
const expectHead = (v, mockup) => {
  const links = ['#{request.contextPath}/resources/support/drag_scroll.css?v=20260911a', '#{request.contextPath}/resources/support/sd2_list.css?v=20260930a'];
  if (mockup) links.push('#{request.contextPath}/resources/support/sales_doc_list_mockup.css?v=20261019b');
  const want = links.map((l) => l.replace('#{request.contextPath}', CTX_MARK));
  if (JSON.stringify(v.head.links) !== JSON.stringify(want)) throw new Error(`${FILE}: the stylesheets of the head changed: ${v.head.links.join(' ')}`);
  const s = v.head.scripts;
  const okDrag = s[0] && /resources\/support\/drag_scroll\.js/.test(s[0].src) && s[0].targets === '.sd2-table-wrap';
  const okMock = !mockup || (s.length === 2 && /resources\/support\/sales_doc_list_mockup\.js/.test(s[1].src));
  if (!okDrag || !okMock || s.length !== (mockup ? 2 : 1)) throw new Error(`${FILE}: the head scripts changed: ${JSON.stringify(s)}`);
};
for (const t of TYPES) expectHead(variants[t], true);
expectHead(legacy, false);
// the tab strip is drawn by the Angular shell (nav.config.ts → sale); the page only says which tab is active
for (const [k, v] of Object.entries(variants)) {
  if (v.tabs.active !== k) throw new Error(`${FILE} [${k}]: the active tab is "${v.tabs.active}", expected "${k}"`);
  if (v.styles.length) throw new Error(`${FILE} [${k}]: the content has an inline <style> (not expected)`);
}
for (const n of checkSaleTabs(variants.qt.tabs, readFileSync(join(root, 'src/app/core/navigation/nav.config.ts'), 'utf8'), th)) console.warn('  ! top bar (shared file nav.config.ts, see INTEGRATION.md): ' + n);

/* ================================================================================== markup */
const SEARCH_ICON = `${CTX_MARK}/images/icon/fi_search.svg`;
const markupCtx = { text: new Set(), attr: new Set() };
const tpl = (v, what) => {
  const m = editor(what, v.markup.replace(/^\s+/, '').replace(/\s+$/, ''));
  // the link to the form of the type is the route of this app (core/navigation/java-links.ts)
  m.text = m.text.replace(/href="([^"#]*\.xhtml\?[^"]*)"/g, (_x, link) => `href="${routeOf(link.replace(/&amp;/g, '&'), what)}"`);
  if (m.text.includes(SEARCH_ICON)) m.swap(SEARCH_ICON, 'assets/images/icon/fi_search.svg');
  if (m.text.includes(CTX_MARK)) throw new Error(`${what}: #{request.contextPath} left in the markup: ${m.text.match(/.{0,40}@@CTX@@.{0,40}/)[0]}`);
  const t = toAngularTemplate(m.text, what);
  const c = messageContexts(t);
  c.text.forEach((k) => markupCtx.text.add(k));
  c.attr.forEach((k) => markupCtx.attr.add(k));
  if (/\bon[a-z]+="/.test(t)) throw new Error(`${what}: an inline handler appeared — export its function (see sync-dashboard.mjs HANDLERS_EXTRA)`);
  return t;
};
const indent = (s, n) => s.split('\n').map((l) => (l.trim() ? ' '.repeat(n) + l : l)).join('\n');
const cases = TYPES.map((t) => `  @case ('${t}') {\n${indent(tpl(variants[t], `sales_doc_type_list.xhtml markup [${t}]`).replace(/\s+$/, ''), 4)}\n  }`);
const dflt = `  @default {\n${indent(tpl(legacy, 'sales_doc_type_list.xhtml markup [legacy]').replace(/\s+$/, ''), 4)}\n  }`;
checkMarkupMessages(markupCtx, th, en, 'sales_doc_type_list.xhtml markup');
writeFileSync(
  join(out, 'sales-doc-list.html'),
  `<!-- ${GENERATED}
     The markup of sales_doc_type_list.xhtml, evaluated for each type (docKey): the five types include components/sales_doc_list_mockup.xhtml with
     their own parameters, anything else is components/sales_doc_list_legacy.xhtml (@default). #{commonBean.msg[…]} -> t('…') ·
     hasFeature(…) -> can('…') · #{request.contextPath}/images/… -> assets/images/… · the link to the form is its route · the rest is verbatim -->
@switch (docKey()) {
${cases.join('\n')}
${dflt}
}
`,
);
mkdirSync(join(root, 'public/assets/images/icon'), { recursive: true });
copyFileSync(join(java, 'images/icon/fi_search.svg'), join(root, 'public/assets/images/icon/fi_search.svg'));

/* ================================================================================== engine */
// ---- the library of the mockup list (resources/support/sales_doc_list_mockup.js): kept as it is (an IIFE that publishes window.SalesDocListMockup)
const lib = editor('sales_doc_list_mockup.js', read('resources/support/sales_doc_list_mockup.js').replace(/^\/\*[\s\S]*?\*\/\n/, '').replace(/\s+$/, '\n'));
if (/\b(fetch|XMLHttpRequest|localStorage|sessionStorage|setTimeout|setInterval|location\.|window\.open|document\.cookie)\b/.test(lib.text)) throw new Error('sales_doc_list_mockup.js: a global the engine environment has to provide');
// the page script calls `SalesDocListMockup.init(…)` and the engine publishes / removes exactly this name: the library must still be an IIFE that publishes it (and only it)
if (!/^\(function \(\) \{\n[\s\S]*\}\)\(\);\n$/.test(lib.text)) throw new Error('sales_doc_list_mockup.js is no longer a (function () { … })(); script');
const publishedNames = [...lib.text.matchAll(/^\s*window\.(\w+)\s*=/gm)].map((m) => m[1]);
if (publishedNames.join() !== 'SalesDocListMockup') throw new Error(`sales_doc_list_mockup.js publishes ${publishedNames.join(', ') || 'nothing'} on window (expected SalesDocListMockup)`);
if (!/\bSalesDocListMockup\.init\(/.test(read('pages/components/sales_doc_list_mockup.xhtml'))) throw new Error('components/sales_doc_list_mockup.xhtml no longer calls SalesDocListMockup.init(…)');
lib.text = lib.text.replace(/\n$/, '');

// ---- the inline script of the mockup list: the five types differ in `cols` and `withRef` only
const qmlOf = (t) => {
  const s = variants[t].scripts;
  if (s.length !== 1) throw new Error(`sales_doc_list_mockup.xhtml script [${t}]: expected one inline script, found ${s.length}`);
  const m = /cols: (\d+),\s*withRef: (true|false),/.exec(s[0]);
  if (!m) throw new Error(`sales_doc_list_mockup.xhtml script [${t}]: cols / withRef not found`);
  return { cols: +m[1], withRef: m[2] === 'true', text: s[0].replace(/cols: \d+,(\s*)withRef: (?:true|false),/, 'cols: @COLS@,$1withRef: @REF@,') };
};
const qml = Object.fromEntries(TYPES.map((t) => [t, qmlOf(t)]));
for (const t of TYPES) if (qml[t].text !== qml.qt.text) throw new Error(`sales_doc_list_mockup.xhtml script [${t}] differs from the quotation list beyond cols / withRef`);
const qmlJs = editor('sales_doc_list_mockup.xhtml script', stripIife(qml.qt.text, 'sales_doc_list_mockup.xhtml script').replace(/^\n/, ''));
qmlJs.swap('cols: @COLS@,', 'cols: QML_VARIANTS[env.docKey].cols,');
qmlJs.swap('withRef: @REF@,', 'withRef: QML_VARIANTS[env.docKey].withRef,');
// the Java page has no API for the list yet: it renders no rows. The host hands the rows over (always [] in this phase — see sales-doc-list-backend.ts)
qmlJs.swap('list.render([]);', 'list.render(env.rows);');

// ---- the inline script of the legacy list
if (legacy.scripts.length !== 1) throw new Error(`sales_doc_list_legacy.xhtml: expected one inline script, found ${legacy.scripts.length}`);
const legacyJs = editor('sales_doc_list_legacy.xhtml script', stripIife(legacy.scripts[0], 'sales_doc_list_legacy.xhtml script').replace(/^\n/, ''));
legacyJs.swapAll(`document.addEventListener('click', closeAll);`, `listen(document, 'click', closeAll);`, 1);
// the form of the document type: the route of this app
{
  let n = 0;
  legacyJs.text = legacyJs.text.replace(/'(sales_doc_(?:qt|bk|ob|aq|ad)_form\.xhtml\?[^']*)'/g, (_m, link) => (n++, `'${routeOf(link, 'sales_doc_list_legacy.xhtml script')}'`));
  if (n !== 5) throw new Error(`sales_doc_list_legacy.xhtml script: expected 5 links to the forms, found ${n}`);
  legacyJs.swap('window.location.href = ADD_FORM_BY_DOC[DOC_KEY];', 'env.navigate(ADD_FORM_BY_DOC[DOC_KEY]);');
}
legacyJs.swap('swal({ title:', 'env.swal({ title:');
// window.sdtApplyFilters is published by the script (nothing calls it by name; it is kept and taken off again by destroy())

const js = { qml: qmlJs, legacy: legacyJs };
const used = new Set();
const uses = [];
for (const [name, e] of Object.entries(js)) {
  e.text = await elToEnv(e.text, `${name} script`, (expr, quote) => {
    const k = msgKey(expr);
    if (k) {
      used.add(k);
      uses.push({ key: k, quote });
      return `env.t(${JSON.stringify(k)})`;
    }
    throw new Error(`${name} script: EL not understood: #{${expr}}`);
  });
}
checkScriptMessages(uses, th, en, 'the list scripts');
for (const [name, e] of Object.entries(js)) {
  const code = e.text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
  if (/#\{/.test(code)) throw new Error(`${name} script: EL left over in code: ` + code.match(/.{0,40}#\{.{0,40}/)[0]);
  if (/\b(setInterval|setTimeout|XMLHttpRequest|fetch|localStorage|sessionStorage|document\.cookie|window\.open|window\.location|location\.(href|reload))\b/.test(code)) throw new Error(`${name} script: unexpected timer / XHR / storage / navigation (add it to destroy() / the host)`);
  if (/(^|[^.\w$'"])swal\(/m.test(code)) throw new Error(`${name} script: a bare swal call is left`);
}
// (DOC_KEY of the legacy list is '' — the page is the @default of an unknown type — so the add button always answers with the "not ready" alert)
if (!/var DOC_KEY = '';/.test(legacyJs.text)) throw new Error("sales_doc_list_legacy.xhtml script: DOC_KEY is no longer ''");

const variantsTable = `  var QML_VARIANTS = ${JSON.stringify(Object.fromEntries(TYPES.map((t) => [t, { cols: qml[t].cols, withRef: qml[t].withRef }])))};\n`;
const scaffold = engineScaffold({
  header: `
 * Sales-document list engine. ${GENERATED}
 *
 * The inline scripts of the Java list pages, same behaviour line by line: the table of the five document types (resources/support/
 * sales_doc_list_mockup.js — no API yet, so no rows: "ไม่พบข้อมูล") and, for an unknown type, the legacy list (search pill, product / status
 * menus, add button).
 *
 * WHY it is imperative DOM code and not Angular components: the Java page draws its HTML from data as strings. Porting it 1:1 is what
 * guarantees the screen, texts and states are identical to the production system.
 * "@ts-nocheck": the source is ES5 written for a browser global scope; typing it would change it, not port it.
 *
 * What changed versus the Java files (all of it lives in tools/sync-sales-doc-list.mjs):
 *   - the environment is injected (SalesDocListEnv): messages, SweetAlert, navigation, the key of the type — in Java these were EL, the URL and globals;
 *   - the five \`SalesDocListMockup.init({ cols, withRef })\` calls of the five pages are one call with the values of the type (QML_VARIANTS);
 *   - \`list.render([])\` is \`list.render(env.rows)\`: the host hands the rows over (the Java page has no list API yet: always none);
 *   - the strip of tabs that sales_doc_tabs.xhtml injects into the Java top bar is drawn by the Angular shell (nav.config.ts);
 *   - the links to the forms are their routes; the document listener is added through listen() and removed by destroy().`,
  envType: 'SalesDocListEnv',
  envBody: `  /** commonBean.msg['key'] in the active language */
  t: (key: string) => string;
  /** SweetAlert v2 (js/sweetalert/sweetalertv1.min.js) */
  swal: (options: Record<string, unknown>) => Promise<unknown>;
  /** window.location.href = … : the route of this app */
  navigate: (route: string) => void;
  /** the validated document type of the address: qt | bk | ob | aq | ad, or '' (unknown = the legacy list) */
  docKey: string;
  /** the rows of the table: { no, date: 'yyyy-MM-dd', customer, ref (bookings), employee, total, status, isNew } — none until the API exists */
  rows: { no: string; date: string; customer: string; ref?: string; employee: string; total: number | string; status: string; isNew?: boolean }[];`,
  fn: 'startSalesDocList',
  handlers: [],
  exported: ['SalesDocListMockup', 'sdtApplyFilters'],
});
const body =
  `  /* ---- resources/support/sales_doc_list_mockup.js ---- */\n` +
  lib.text.replace(/^/gm, '  ').replace(/\s+$/, '\n') +
  variantsTable +
  `\n  if (env.docKey) {\n    /* ---- components/sales_doc_list_mockup.xhtml (one of the five types) ---- */\n` +
  qmlJs.text.replace(/\s+$/, '').replace(/^/gm, '  ') +
  `\n  } else {\n    /* ---- components/sales_doc_list_legacy.xhtml (no / unknown type) ---- */\n` +
  legacyJs.text.replace(/\s+$/, '').replace(/^/gm, '  ') +
  `\n  }\n`;
const engineText = scaffold.header + scaffold.guard + body + scaffold.footer();
const undeclared = await undeclaredNames(engineText.replace(/^\/\/ @ts-nocheck\n/, ''), ['SalesDocListMockup']);
if (undeclared.length) throw new Error('sales-doc-list engine: names that are not declared (a ReferenceError in strict mode): ' + undeclared.join(', '));
writeFileSync(join(out, 'sales-doc-list.engine.ts'), engineText);

/* ================================================================================== stylesheet (written last: the dark port reads the markup and the scripts) */
const sd2 = editor('sd2_list.css', read('resources/support/sd2_list.css').replace(/\s+$/, ''));
// the first two rules style elements of the Java template; the Angular shell has the same box: #crm_main_body_page
sd2.swap(
  `            #crm_main_body_page { padding: 0 !important; background: #F0F2FF !important; }
            .layout-main .layout-content { padding: 0 !important; }
`,
  `            /* (Java: #crm_main_body_page / .layout-main .layout-content — see the Angular adaptation block) */
`,
);
// `#12966` is not a colour (5 hex digits): browsers drop the declaration, Sass refuses to compile it — the rule stays, without it
sd2.swap(
  `.sd2-dialog-confirm:hover { background: #12966; }`,
  `.sd2-dialog-confirm:hover { /* background: #12966 — not a colour (5 hex digits); a browser drops the declaration, so the hover keeps the normal background */ }`,
);
const mockCss = read('resources/support/sales_doc_list_mockup.css').replace(/\s+$/, '');
const cssText = portCss(sd2.text, 'sd2_list.css') + '\n' + portCss(mockCss, 'sales_doc_list_mockup.css');
const allMarkup = Object.values(variants).map((v) => v.markup).join('\n');
const pageText = allMarkup + '\n' + cssText + '\n' + js.qml.text + '\n' + js.legacy.text;
const dark = darkPort(read('resources/support/dark_mode.css'), pageText, SCOPE, 1);
const adapted = adaptation({ read, scope: SCOPE, host: 'ts-sales-doc-list-view', text: allMarkup + '\n' + js.qml.text + '\n' + js.legacy.text });
const SHELL_BOX = `/* the two rules sd2_list.css sets on the Java template's boxes (#crm_main_body_page, .layout-main .layout-content) — the Angular shell's content box has the same id.
   The Java page loads the stylesheet for every type (the table of the five types as well as the legacy list), so the rule is not limited to .sd2-root. */
#crm_main_body_page:has(ts-sales-doc-list-view) { padding: 0 !important; background: #F0F2FF !important; }
`;
const header = (name) => `/* Sales-document list stylesheet. ${GENERATED}
   ${name} copied verbatim, except:
     the two rules on #crm_main_body_page / .layout-main .layout-content -> Angular adaptation block
     body[data-theme="dark"] -> html[data-theme='dark']       (the Angular shell puts the theme on <html>; same specificity)
     --fs-adj                -> --ts-fs-adj                   (A A A font scale token of the Angular shell)
   Loaded with ViewEncapsulation.None: the engine writes HTML strings that need global selectors. */

`;
writeFileSync(
  join(out, 'sales-doc-list.scss'),
  header('resources/support/sd2_list.css + sales_doc_list_mockup.css (the Java head loads both for the five types, only sd2_list.css for the legacy list — the .qml-* rules cannot match the legacy markup)') +
    adapted +
    SHELL_BOX +
    '\n' +
    dedent(cssText) +
    `\n/* ───── dark_mode.css of the Java app, scoped to the page (${dark.kept} rules that can match it, of ${dark.seen} selectors) ───── */\n${dark.css}\n`,
);

console.log(`Sales-document list synced from ${java}: ${used.size} script messages, ${markupCtx.text.size + markupCtx.attr.size} markup messages, ${dark.kept} dark rules; css ${cssText.length}`);
