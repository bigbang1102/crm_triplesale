#!/usr/bin/env node
/**
 * Regenerates the "เอกสารประกอบ" tab of the prospect detail page from the GENERATED prospect form (run `npm run prospect-form:sync` first):
 *
 *   npm run prospect-docs:sync
 *
 *   features/prospects/form/prospect-form.html    (the pane `form:ctPane3`: upload button, the list of documents, download / delete)
 *   features/prospects/form/prospect-form.engine.ts (the functions ctMdPickFiles · ctMdOnFilePicked · ctMdDeleteDoc · ctMdDownloadDoc … of the page script)
 *   features/prospects/form/prospect-form.scss    (the rules of the classes the pane uses: panel-text-toggle · togglepanel-container · btn-master · ct-doc-* …)
 *     ->  features/prospects/detail/docs/prospect-docs.{html,scss,engine.ts}
 *
 * Same idea as tools/sync-prospect-extra.mjs: the form's generator already holds every swap of the port, the tab is the same markup and the same script, so it is
 * derived from the generated form and the two can never drift. Change this file (or the form's generator), never the outputs. What this file changes is listed in CHANGES.
 */
import postcss from 'postcss';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { engineScaffold } from './lib/port-kit.mjs';
import { undeclaredNames } from './lib/port.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const form = join(root, 'src/app/features/prospects/form');
const out = join(root, 'src/app/features/prospects/detail/docs');
mkdirSync(out, { recursive: true });
const GENERATED = 'GENERATED by tools/sync-prospect-docs.mjs from the generated prospect form (prospect-form.{html,engine.ts,scss}) — do not edit; change the generator and run `npm run prospect-docs:sync`';
const HOST = 'ts-prospect-docs';

function between(text, start, end, what) {
  const a = text.indexOf(start);
  if (a < 0) throw new Error(`prospect-docs: ${what}: start marker not found: ${start}`);
  const b = text.indexOf(end, a + start.length);
  if (b < 0) throw new Error(`prospect-docs: ${what}: end marker not found: ${end}`);
  return [a, b];
}
function replaceOnce(text, from, to, what) {
  const n = text.split(from).length - 1;
  if (n !== 1) throw new Error(`prospect-docs: ${what}: expected 1 occurrence, found ${n}: ${from}`);
  return text.replace(from, () => to);
}

/* ================================================================================================ markup */
const formHtml = readFileSync(join(form, 'prospect-form.html'), 'utf8');
{
  const [a, b] = between(formHtml, '<div id="form:ctPane3"', '</span>\n\n\n                <span id="form:panel-button-data2"', 'pane');
  let pane = formHtml.slice(a, b).trimEnd();
  // the wrapper of the pane (`ct-pane`, hidden until its tab is open) goes: the detail page shows the pane when its tab is open
  pane = pane.replace(/^<div id="form:ctPane3"[^>]*>/, '').replace(/<\/div>\s*$/, '');
  // CHANGES (1): the detail page is the edit look of the pane — the upload button is the "edit" one (PL-PR-DT-02), the trash is a role check (Attachment_Delete), the list comes from the host
  pane = replaceOnce(pane, `access(bean.action_type === 'add' ? 'PL-PR-CR-03' : 'PL-PR-DT-02')`, `access('PL-PR-DT-02')`, 'upload button');
  pane = replaceOnce(pane, `[attr.accept]="env.uploadAcceptExt"`, `[attr.accept]="uploadAcceptExt()"`, 'accept');
  pane = replaceOnce(pane, `@for (_k of [upd('ctMdDocPanel')]; track _k) {`, `@if (true) {`, 'update wrapper');
  pane = replaceOnce(pane, `@if ((bean.action_type !== 'view') && can('Pipeline_Prospect_Attachment_Delete')) {`, `@if (can('Pipeline_Prospect_Attachment_Delete')) {`, 'delete icon');
  pane = pane.split('bean.prospectDocs').join('docs()');
  if (/\bbean\.|\bupd\(|\bsnap\(|\bvd\(|\benv\./.test(pane)) throw new Error('prospect-docs: the pane reads something of the form host that this file does not give');
  writeFileSync(
    join(out, 'prospect-docs.html'),
    `<!-- ${GENERATED}
     The pane "เอกสารประกอบ" of contracts_master_data.xhtml as the form renders it (edit look). The host gives: t(), can(), access(), docs(), uploadAcceptExt() — see prospect-docs-view.ts -->
${pane.trim()}
`,
  );
}

/* ================================================================================================ engine */
const formEngine = readFileSync(join(form, 'prospect-form.engine.ts'), 'utf8');
let body;
{
  const [a, b] = between(formEngine, '/* ===== เอกสารประกอบ (Tab 3)', '/* ===== แท็บบนสุด', 'documents script');
  body = formEngine.slice(a, b).trimEnd();
  if (!body.includes('function ctMdDownloadDoc')) throw new Error('prospect-docs: the documents script has no ctMdDownloadDoc');
}
const HANDLERS = ['ctMdPickFiles', 'ctMdOnFilePicked', 'ctMdDeleteDoc', 'ctMdDownloadDoc', 'ctMdSetBusy', 'ctMdShowProgress', 'ctMdClearProgress'];
const header = ` Prospect documents engine. ${GENERATED}
 *
 * The documents part of the page script of contracts_master_data.xhtml, same code as the form's engine: upload (POST /board/prospect/attachments), download (through
 * /docproxy), delete (confirm, then the host's \`rc_deleteProspectDoc\`). The list itself is drawn by the template; \`rc_reloadProspectDocs\` / \`rc_deleteProspectDoc\`
 * are the p:remoteCommand functions the host defines (as PrimeFaces did for the form).`;
const envBody = `  /** commonBean.msg['key'] in the active language */
  t: (key: string) => string;
  /** SweetAlert (the library of the Java page) */
  swal: (options: Record<string, unknown>) => Promise<unknown>;
  /** the id of the prospect (the script reads it as window._contractId) */
  contractId: string;
  /** the browser's own requests (/board/prospect/attachments · /docproxy) */
  fetch: (input: string, init?: RequestInit) => Promise<Response>;`;
const scaffold = engineScaffold({ header, envType: 'ProspectDocsEnv', envBody, fn: 'startProspectDocs', handlers: HANDLERS, exported: [...HANDLERS, '_contractId'] });
const ENGINE_BODY = `  /* the global the script reads: the id of the record */
  window._contractId = env.contractId;

  ${body.replace(/\n/g, '\n  ')}
`;
const engineText = scaffold.header + scaffold.guard + ENGINE_BODY + '\n' + scaffold.footer();
const undeclared = await undeclaredNames(engineText.replace(/^\/\/ @ts-nocheck\n/, ''), ['TsAttachTypes', 'rc_reloadProspectDocs', 'rc_deleteProspectDoc', 'ctMdRenderDocList']);
if (undeclared.length) throw new Error(`prospect-docs engine: names that are not declared (a ReferenceError in strict mode): ${undeclared.join(', ')}`);
writeFileSync(join(out, 'prospect-docs.engine.ts'), engineText);

/* ================================================================================================ styles */
{
  const css = postcss.parse(readFileSync(join(form, 'prospect-form.scss'), 'utf8'));
  // the classes the pane uses (`.btn-master` is not `.btn-master-save`)
  const USES = /\.(?:panel-text-toggle|togglepanel-container|title-header-text|ct-doc-[\w-]+|btn-master)(?![\w-])/;
  const SKIP = /\.btn-master-(?:save|secondary|fit)/;
  // every selector ends up under the host (the form's global rules would leak into other pages: the sheet is not encapsulated), keeping the specificity of the original
  const scope = (sel) => {
    const s = sel.replace(/:where\(ts-prospect-form-view[^)]*\)/g, `:where(${HOST})`).replace(/#form\b/g, HOST);
    if (s.includes(HOST)) return s;
    const html = /^(html\[[^\]]*\])\s+(.*)$/s.exec(s);
    return html ? `${html[1]} :where(${HOST}) ${html[2]}` : `:where(${HOST}) ${s}`;
  };
  const kept = [];
  const walk = (node, into) => {
    node.each((child) => {
      if (child.type === 'rule') {
        const sels = child.selectors.filter((s) => USES.test(s) && !SKIP.test(s) && !s.includes(':has(')).map(scope);
        if (sels.length) kept.push(`${sels.join(',\n')} {${child.nodes.map((n) => n.toString()).join(';')}}`);
      } else if (child.type === 'atrule' && /^(media|supports)$/.test(child.name)) {
        const before = kept.length;
        walk(child, into);
        if (kept.length > before) {
          const inner = kept.splice(before);
          kept.push(`@${child.name} ${child.params} {\n${inner.join('\n')}\n}`);
        }
      }
    });
  };
  walk(css, kept);
  if (!kept.length) throw new Error('prospect-docs: no style rule found for the classes of the pane');
  writeFileSync(
    join(out, 'prospect-docs.scss'),
    `/* ${GENERATED} */
/* the Java page's base: the form controls keep the browser's own look unless a rule below says otherwise (prospect-form.scss does the same for its host) */
:where(${HOST}) :is(button, input, select, textarea) { font: revert; letter-spacing: revert; color: revert; }
:where(${HOST}) button { padding: revert; border: revert; background: revert; cursor: revert; text-align: revert; }
${HOST} { display: block; font-size: 13px; color: #191a1c; }
html[data-theme='dark'] ${HOST} { color: #E5E7EB; }

${kept.join('\n')}
`,
  );
}
console.log('prospect-docs synced: features/prospects/detail/docs/prospect-docs.{html,engine.ts,scss}');
