const HELP_ELEMENT = (start) =>
  new RegExp(
    `<(p|span|div) class="hint"[^>]*>${start.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[^<]*</\\1>`,
  );
function dropHelp(text, what, starts) {
  return starts.reduce((out, start) => {
    const found = out.match(new RegExp(HELP_ELEMENT(start), 'g')) ?? [];
    if (found.length !== 1) fail(`${what}: expected 1 help line "${start}", found ${found.length}`);
    return out.replace(HELP_ELEMENT(start), '');
  }, text);
}

