/** top-level blocks of a stylesheet (braces inside strings ignored) */
function blocks(text) {
  const found = [];
  let depth = 0;
  let quote = '';
  let from = 0;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quote) {
      if (c === '\\') i++;
      else if (c === quote) quote = '';
    } else if (c === '"' || c === "'") quote = c;
    else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) {
      found.push(text.slice(from, i + 1).trim());
      from = i + 1;
    }
  }
  if (
    text
      .slice(from)
      .replace(/\/\*[\s\S]*?\*\//g, '')
      .trim()
  )
    fail('CSS: text after the last block');
  return found;
}

/** a selector list split at the top-level commas */
function selectors(list) {
  const parts = [];
  let depth = 0;
  let cur = '';
  for (const c of list) {
    if (c === '(' || c === '[') depth++;
    if (c === ')' || c === ']') depth--;
    if (c === ',' && depth === 0) {
      parts.push(cur.trim());
      cur = '';
    } else cur += c;
  }
  parts.push(cur.trim());
  return parts.filter(Boolean);
}

