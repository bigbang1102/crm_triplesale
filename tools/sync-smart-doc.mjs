/** one selector of the prototype under .smd-root (the page's :root / html / body become the root of the feature) */
function scopeSelector(sel) {
  let m = ROOT.exec(sel);
  if (m) {
    const head = m[1] ? `:root${m[1]} ${SCOPE}` : SCOPE;
    return m[2].trim() ? `${head}${/^[>+~]/.test(m[2].trim()) ? '' : ' '}${m[2].trim()}` : head;
  }
  m = BODY.exec(sel);
  if (m) {
    // body.printmode … = the page's state class (the script still sets it on <body>)
    const head = m[1] ? `body${m[1]} ${SCOPE}` : SCOPE;
    const rest = m[2].trim();
    return rest ? `${head}${/^[>+~]/.test(rest) ? '' : ' '}${rest}` : head;
  }
  return `${SCOPE} ${sel}`;
}

function scopeBlock(block) {
  if (block.startsWith('@')) {
    const open = block.indexOf('{');
    const prelude = block.slice(0, open).trim();
    if (/^@(media|supports|container)\b/.test(prelude)) {
      return `${prelude}{\n${blocks(block.slice(open + 1, -1))
        .map((b) => `  ${scopeBlock(b)}`)
        .join('\n')}\n}`;
    }
    return block; // @keyframes, @page, @font-face: as written
  }
  const open = block.indexOf('{');
  return `${selectors(block.slice(0, open)).map(scopeSelector).join(',')}${block.slice(open)}`;
}

