const between = (text, open, close, what) => {
  const a = text.indexOf(open);
  const b = text.indexOf(close, a + open.length);
  if (a < 0 || b < 0) fail(`${what}: "${open}" … "${close}" not found`);
  return text.slice(a + open.length, b);
};

/** one exact replacement (the prototype changed there = stop) */
function swap(text, what, find, repl, count = 1) {
  const n = text.split(find).length - 1;
  if (n !== count)
    fail(`${what}: expected ${count} × ${JSON.stringify(find.slice(0, 80))}, found ${n}`);
  return text.split(find).join(repl);
}

/** the text from `from` up to (not including) `to` replaced */
function swapBlock(text, what, from, to, repl) {
  const a = text.indexOf(from);
  const b = text.indexOf(to, a + from.length);
  if (a < 0 || b < 0)
    fail(`${what}: block "${from.slice(0, 60)}" … "${to.slice(0, 60)}" not found`);
  return text.slice(0, a) + repl + text.slice(b);
}

