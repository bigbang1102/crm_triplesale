#!/usr/bin/env node
/**
 * Regenerates the receipt list ("ใบรับเงิน (RV)", route /sales/receipts) from the Java original so the two can never drift while both
 * exist:
 *
 *   npm run receipts:sync          (Java project = ../triple_sale_main, or set TS_JAVA_ROOT)
 *
 *   Java  web/resources/support/sd2_list.css          ->  src/app/features/receipts/receipts.scss   (+ Angular adaptation block)
 *   Java  web/pages/sales_doc_rv_list.xhtml markup    ->  src/app/features/receipts/receipts.html
 *   Java  web/pages/sales_doc_rv_list.xhtml <script>  ->  src/app/features/receipts/receipts.engine.ts
 *   Java  web/images/icon/fi_search.svg               ->  public/assets/images/icon/fi_search.svg   (byte for byte)
 *
 * The pieces every page of the menu group "งานขาย" shares (taking the Facelets page apart, the tab strip, EL inside JS strings) are in
 * tools/lib/sales-doc.mjs. The Java files are only READ. The outputs carry a "GENERATED" header — change this script (the swap() list),
 * never the output. A swap() that no longer matches stops the run on purpose: the original changed in a place the port depends on.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { javaLinkToRoute } from '../src/app/core/navigation/java-links.ts'; // (Node strips the types; the file has no Angular imports)
import { darkPort, editor, markupToTemplate, reader, undeclaredNames } from './lib/port.mjs';
import { adaptation, engineScaffold } from './lib/port-kit.mjs';
import { checkMessages, checkSaleTabs, elToEnv, msgKey, salesPage, stripIife } from './lib/sales-doc.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const javaRoot = resolve(process.env.TS_JAVA_ROOT ?? join(root, '..', 'triple_sale_main'));
const java = join(javaRoot, 'web');
const out = join(root, 'src/app/features/receipts');
mkdirSync(out, { recursive: true });

const read = reader(java);
const FILE = 'pages/sales_doc_rv_list.xhtml';
const GENERATED = `GENERATED by tools/sync-receipts.mjs from web/pages/sales_doc_rv_list.xhtml + web/resources/support/sd2_list.css — do not edit; change the script and run \`npm run receipts:sync\`.`;
// the overlays of the page are moved to <body> by its script (out of the transformed .layout-main), so the global rules of the Java stylesheet
// stack must reach them there too: the scope is the host element AND those two boxes
const SCOPE = ':where(ts-receipts-view, .sd2-dt-overlay, .sd2-overlay)';
const th = JSON.parse(readFileSync(join(root, 'public/assets/i18n/th.json'), 'utf8'));
const en = JSON.parse(readFileSync(join(root, 'public/assets/i18n/en.json'), 'utf8'));

/* ================================================================================== the Facelets page */
const page = salesPage(read, FILE);
if (page.styles.length || page.headStyles.length) throw new Error(`${FILE}: the page has an inline <style> (the stylesheet is expected in sd2_list.css)`);
const expectLinks = ['#{request.contextPath}/resources/support/drag_scroll.css?v=20260911a', '#{request.contextPath}/resources/support/sd2_list.css?v=20260928a'];
if (JSON.stringify(page.headLinks) !== JSON.stringify(expectLinks)) throw new Error(`${FILE}: the stylesheets of the head changed: ${page.headLinks.join(' ')}`);
// drag_scroll.css is global in the Angular shell (styles/_drag-scroll.scss); drag_scroll.js is core/dom/drag-scroll.ts — the host starts it for these targets
if (page.headScripts.length !== 1 || !/resources\/support\/drag_scroll\.js/.test(page.headScripts[0].src) || page.headScripts[0].targets !== '.sd2-table-wrap') {
  throw new Error(`${FILE}: the head scripts changed: ${JSON.stringify(page.headScripts)}`);
}
if (page.tabs.active !== 'rv') throw new Error(`${FILE}: the active tab is no longer "rv": ${page.tabs.active}`);
// the strip of tabs the page injects into the Java top bar is drawn by the Angular shell (nav.config.ts → sale)
const tabNotes = checkSaleTabs(page.tabs, readFileSync(join(root, 'src/app/core/navigation/nav.config.ts'), 'utf8'), th);
for (const n of tabNotes) console.warn('  ! top bar (shared file nav.config.ts, see INTEGRATION.md): ' + n);

/* ================================================================================== markup */
const markup = editor('sales_doc_rv_list.xhtml markup', page.markup.replace(/^\s+/, '').replace(/\s+$/, ''));
markup.swap('#{request.contextPath}/images/icon/fi_search.svg', 'assets/images/icon/fi_search.svg');
let tpl = markupToTemplate(markup.text, 'sales_doc_rv_list.xhtml markup');
tpl = tpl.replace(/^ {8}/gm, '').replace(/^\n+/, '');
writeFileSync(
  join(out, 'receipts.html'),
  `<!-- ${GENERATED}
     The markup of sales_doc_rv_list.xhtml (its stylesheet is receipts.scss); #{commonBean.msg[…]} -> t('…') · hasFeature(…) -> can('…') ·
     #{request.contextPath}/images/… -> assets/images/… · everything else is verbatim -->\n` + tpl.replace(/\s+$/, '\n'),
);
// byte-identical copy of the image the page shows (the mirror layout: web/images/<path> -> public/assets/images/<path>)
mkdirSync(join(root, 'public/assets/images/icon'), { recursive: true });
copyFileSync(join(java, 'images/icon/fi_search.svg'), join(root, 'public/assets/images/icon/fi_search.svg'));

/* ================================================================================== stylesheet */
const css = editor('sd2_list.css', read('resources/support/sd2_list.css').replace(/\s+$/, ''));
// the first two rules style elements of the Java template; the Angular shell has the same box: #crm_main_body_page
css.swap(
  `            #crm_main_body_page { padding: 0 !important; background: #F0F2FF !important; }
            .layout-main .layout-content { padding: 0 !important; }
`,
  `            /* (Java: #crm_main_body_page / .layout-main .layout-content — see the Angular adaptation block) */
`,
);
// `#12966` is not a colour (5 hex digits): browsers drop the declaration, Sass refuses to compile it — the rule stays, without it
css.swap(
  `.sd2-dialog-confirm:hover { background: #12966; }`,
  `.sd2-dialog-confirm:hover { /* background: #12966 — not a colour (5 hex digits); a browser drops the declaration, so the hover keeps the normal background */ }`,
);
css.swapAll('body[data-theme="dark"]', "html[data-theme='dark']");
css.swapAll('var(--fs-adj,0px)', 'var(--ts-fs-adj,0px)');
if (/--fs-adj/.test(css.text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/--ts-fs-adj/g, ''))) throw new Error('sd2_list.css: --fs-adj left over');

/* ================================================================================== engine */
const js = editor('sales_doc_rv_list.xhtml script', stripIife(page.pageScript, 'sales_doc_rv_list.xhtml script').replace(/^\n/, ''));

/* ---- environment: what Facelets / the session / the browser gave the page ---- */
js.swap(
  `var RV_CAN_APPROVE = #{commonBean.hasFeature('CRM_RV_View,CRM_RV_Edit,FEATURE_CRM_Document') ? 'true' : 'false'};`,
  `var RV_CAN_APPROVE = env.can('CRM_RV_View,CRM_RV_Edit,FEATURE_CRM_Document');`,
);
// every message and the context path inside a string literal (found with the TypeScript parser)
const used = new Set();
js.text = await elToEnv(js.text, 'sales_doc_rv_list.xhtml script', (expr) => {
  const k = msgKey(expr);
  if (k) {
    used.add(k);
    return `env.t(${JSON.stringify(k)})`;
  }
  if (expr === 'request.contextPath') return 'env.ctx';
  throw new Error(`sales_doc_rv_list.xhtml script: EL not understood: #{${expr}}`);
});
checkMessages(used, th, en, 'sales_doc_rv_list.xhtml script');
js.text = js.text.replace(/var\(--fs-adj,0px\)/g, 'var(--ts-fs-adj,0px)');

/* ---- the BFF: the page called '../rvapi' (relative to /pages/); the engine asks the host for '/rvapi' (below the context path) ---- */
if ((js.text.match(/'\.\.\/rv(api|report|receipt)/g) ?? []).length !== 10) throw new Error('sales_doc_rv_list.xhtml script: expected 10 addresses of /rvapi · /rvreport · /rvreceipt');
js.text = js.text.replace(/'\.\.\/rv(api|report|receipt)/g, "'/rv$1");
js.text = js.text.replace(/(^|[^.\w$])fetch\(/gm, '$1env.fetch(');
// window.open(…) -> env.open(…) (a report address or the blob of the canvas image)
js.text = js.text.replace(/\bwindow\.open\(/g, 'env.open(');
// the next page: location.href = 'sales_doc_rv.xhtml?…' -> the route of this app (core/navigation/java-links.ts)
{
  let n = 0;
  js.text = js.text.replace(/window\.location\.href = '([^']+\.xhtml[^']*)';/g, (_m, link) => {
    const route = javaLinkToRoute(link);
    if (!route) throw new Error(`sales_doc_rv_list.xhtml script: no route for the Java link ${link}`);
    n++;
    return `env.navigate(${JSON.stringify(route)});`;
  });
  if (n !== 3) throw new Error(`sales_doc_rv_list.xhtml script: expected 3 links to the form, found ${n}`);
}
// TS_PREF (resources/js/ui_pref.js): localStorage + a cookie fallback — the host gives the same two calls
js.swap(`function sd2SaveMt(v) { if (window.TS_PREF) { TS_PREF.set(SD2_MT_STORAGE_KEY, v || ''); } }`, `function sd2SaveMt(v) { env.pref.set(SD2_MT_STORAGE_KEY, v || ''); }`);
js.swap(`function sd2LoadSavedMt() { return window.TS_PREF ? TS_PREF.get(SD2_MT_STORAGE_KEY) : ''; }`, `function sd2LoadSavedMt() { return env.pref.get(SD2_MT_STORAGE_KEY); }`);
// the SweetAlert of template.xhtml (the real library, see the host)
{
  const before = js.text;
  js.text = js.text.replace(/if \(window\.swal\) \{\s*swal\((\{[^}]*\})\);\s*\}/, 'env.swal($1);');
  if (js.text === before) throw new Error('sales_doc_rv_list.xhtml script: toast() changed');
}
// The customer suggestions under the search field (odsProspectSuggest of core/dom/open-down-select.ts). In Java they NEVER attach:
// template.xhtml loads open_down_select.js at the end of <body>, after this inline script ran, so `window.odsProspectSuggest` is still
// undefined at that moment and the guard below is false (the replica of the harness has the same load order and shows it). The port keeps
// that behaviour (env.suggestCustomers = false) and keeps the code path, ready for the day the load order is fixed in Java.
js.swap(`if (window.odsProspectSuggest) {`, `if (env.suggestCustomers && window.odsProspectSuggest) {`);
// its request goes through the host
js.swap(`contextPath: env.ctx,`, `contextPath: env.ctx,\n                            fetch: env.fetch,`);
js.text = js.text.replace(/(^|[^.\w$])odsProspectSuggest\(/gm, '$1window.odsProspectSuggest(');
// the blob URL of the canvas image is revoked a minute later even when the screen was left meanwhile (the new tab still shows it)
js.swap(`setTimeout(function () { URL.revokeObjectURL(url); }, 60000);`, `window.setTimeout(function () { URL.revokeObjectURL(url); }, 60000);`);

/* ---- global listeners and timers are registered through listen() / tmo() so that destroy() can remove them ---- */
js.text = js.text.replace(/\b(document|window)\.addEventListener\(/g, 'listen($1, ');
js.text = js.text.replace(/(^|[^.\w$])setTimeout\(/gm, '$1tmo(');

/* ---- nothing may reach the page address, the document cookies or global state the shell owns ---- */
{
  const code = js.text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '').replace(/\s\/\/[^\n'"]*$/gm, '');
  if (/#\{/.test(code)) throw new Error('receipts script: EL left over in code: ' + code.match(/.{0,40}#\{.{0,40}/)[0]);
  if (/\b(setInterval|XMLHttpRequest|localStorage|sessionStorage|document\.cookie|TS_PREF)\b/.test(code)) throw new Error('receipts script: unexpected timer / XHR / storage (add it to destroy() / the host)');
  const rest = code.match(/.{0,40}\b(window\.location|location\.(href|pathname|reload)|\.face\b|\.xhtml\b).{0,40}/);
  if (rest) throw new Error('receipts script: a URL read / Java page link is left: ' + rest[0]);
  const bare = code.match(/(^|[^.\w$'"])(fetch|swal|window\.open)\(/m);
  if (bare) throw new Error('receipts script: a bare fetch / swal / window.open call is left: ' + bare[0]);
  if (/\bon[a-z]+="/.test(tpl)) throw new Error('receipts markup: an inline handler appeared — export its function (see sync-dashboard.mjs HANDLERS_EXTRA)');
}

const scaffold = engineScaffold({
  header: `
 * Receipt list engine. ${GENERATED}
 *
 * The page script of the Java screen, same behaviour line by line: the table of receipts (loaded once, 500 rows; search, status filter,
 * product filter and sorting happen on the client), the customer suggestions under the search field, the approve dialog and its POST, the
 * report popover (the ERP form RV-01 as PDF / PNG, or the preview made from the CRM data) and the detail modal.
 *
 * WHY it is imperative DOM code and not Angular components: the Java page draws its HTML from API data as strings. Porting it 1:1 is what
 * guarantees the screen, texts and states are identical to the production system.
 * "@ts-nocheck": the source is ES5 written for a browser global scope; typing it would change it, not port it.
 *
 * What changed versus the Java file (all of it lives in tools/sync-receipts.mjs):
 *   - the environment is injected (ReceiptsEnv): messages, permissions, fetch (the BFF contract of receipts-backend.ts), window.open,
 *     navigation to the form, SweetAlert, the stored product filter (TS_PREF), the context path — in Java these were EL, the URL and globals;
 *   - the strip of tabs that sales_doc_tabs.xhtml injects into the Java top bar is drawn by the Angular shell (nav.config.ts);
 *   - the addresses '../rvapi…' are '/rvapi…' (below the context path); the link to the form is its route;
 *   - global listeners and timers added through listen() / tmo(), the two overlays the script moves to <body>, and the response guard are
 *     removed by the function returned from startReceipts().`,
  envType: 'ReceiptsEnv',
  envBody: `  /** commonBean.msg['key'] in the active language */
  t: (key: string) => string;
  /** commonBean.hasFeature('A,B') of the signed-in user (OR of the keys) */
  can: (features: string) => boolean;
  /** the BFF contract of the page: /rvapi?action=…, /board/prospect-list (see receipts-backend.ts) */
  fetch: (input: string, init?: RequestInit) => Promise<Response>;
  /** window.open(url, target) — a report address (/rvreport…, /rvreceipt…) or the blob URL of the receipt image */
  open: (url: string, target?: string) => unknown;
  /** window.location.href = … : the route of this app */
  navigate: (route: string) => void;
  /** SweetAlert v2 (js/sweetalert/sweetalertv1.min.js) */
  swal: (options: Record<string, unknown>) => Promise<unknown>;
  /** TS_PREF (resources/js/ui_pref.js): what the user chose on the screen, kept across visits */
  pref: { get: (key: string) => string; set: (key: string, value: string) => void };
  /** #{request.contextPath}: where the BFF is ("" here) */
  ctx: string;
  /**
   * attach the customer suggestions (odsProspectSuggest) to the search field. false = what Java does in practice: open_down_select.js is
   * loaded after this script, so the function does not exist yet when the script looks for it (see tools/sync-receipts.mjs)
   */
  suggestCustomers: boolean;`,
  fn: 'startReceipts',
  handlers: [],
  exported: [],
  cleanup: `    // the two boxes the script moved to <body> (out of the transformed .layout-main) go with the screen
    [overlay, detailOverlay].forEach(function (el) { if (el && el.parentNode === document.body) { document.body.removeChild(el); } });
`,
});
const engineText = scaffold.header + scaffold.guard + js.text.replace(/\s+$/, '\n') + scaffold.footer();
// odsProspectSuggest is a global of the shell (core/dom/open-down-select.ts), used as window.odsProspectSuggest
const undeclared = await undeclaredNames(engineText.replace(/^\/\/ @ts-nocheck\n/, ''), []);
if (undeclared.length) throw new Error('receipts engine: names that are not declared (a ReferenceError in strict mode): ' + undeclared.join(', '));
writeFileSync(join(out, 'receipts.engine.ts'), engineText);

/* ================================================================================== stylesheet (written last: the dark port reads the script) */
const pageText = tpl + '\n' + css.text + '\n' + js.text;
const dark = darkPort(read('resources/support/dark_mode.css'), pageText, SCOPE, 1);
const dedent = (s) => s.replace(/^ {12}/gm, '').replace(/\s+$/, '\n');
const SHELL_BOX = `/* the two rules the stylesheet sets on the Java template's boxes (#crm_main_body_page, .layout-main .layout-content) — the Angular shell's content box has the same id */
#crm_main_body_page:has(.sd2-root) { padding: 0 !important; background: #F0F2FF !important; }
`;
const adapted = adaptation({ read, scope: SCOPE, host: 'ts-receipts-view', text: tpl + '\n' + js.text });
// The two boxes the script moves to <body> take their text size and colour from the Java <body> there (13px, #191a1c; dark #E5E7EB) — the
// host element has them (adaptation block), the Angular <body> has other values: give the boxes the host's.
const hostRule = /^ts-receipts-view \{ display: contents; font-size: ([^;]+); color: ([^;]+); \}$/m.exec(adapted);
const hostDark = /^html\[data-theme='dark'\] ts-receipts-view \{ color: ([^;]+); \}$/m.exec(adapted);
if (!hostRule || !hostDark) throw new Error('the host rule of adaptation() was not found — port-kit.mjs changed');
const MOVED_BOXES = `/* the boxes the script appends to <body>: the text defaults of the Java <body> */
.sd2-overlay, .sd2-dt-overlay { font-size: ${hostRule[1]}; color: ${hostRule[2]}; }
html[data-theme='dark'] :is(.sd2-overlay, .sd2-dt-overlay) { color: ${hostDark[1]}; }
/* The page centres its two boxes by "measure and correct" (centerApproveModal / centerDetailModal): it sets transform: none, reads the rectangle
   in the same task and translates by the difference. The shell turns EVERY transition into a 0.01ms one for a user who prefers reduced motion
   (styles/_base.scss) — the read then still sees the old transform and the box is left off centre. Java has no such rule. */
.sd2-dialog, .sd2-dt-box { transition: none !important; }
`;
writeFileSync(
  join(out, 'receipts.scss'),
  `/* Receipt list stylesheet. ${GENERATED}
   sd2_list.css (shared with sales_doc_type_list.xhtml) copied verbatim, except:
     the two rules on #crm_main_body_page / .layout-main .layout-content -> Angular adaptation block
     body[data-theme="dark"] -> html[data-theme='dark']       (the Angular shell puts the theme on <html>; same specificity)
     --fs-adj                -> --ts-fs-adj                   (A A A font scale token of the Angular shell)
   Loaded with ViewEncapsulation.None: the engine writes HTML strings that need global selectors. */

` +
    adapted +
    SHELL_BOX +
    MOVED_BOXES +
    '\n' +
    dedent(css.text) +
    `\n/* ───── dark_mode.css of the Java app, scoped to the page (${dark.kept} rules that can match it, of ${dark.seen} selectors) ───── */\n${dark.css}\n`,
);

console.log(`Receipts synced from ${java}: ${used.size} messages, ${dark.kept} dark rules; markup ${tpl.length} chars, css ${css.text.length}, script ${js.text.length}`);
