#!/usr/bin/env node
/**
 * Regenerates the quick chat (the floating chat box the "แชท" button opens on every page) from the Java original so the
 * two can never drift while both exist:
 *
 *   npm run quick-chat:sync          (Java project = ../triple_sale_main, or set TS_JAVA_ROOT)
 *
 *   Java  web/WEB-INF/pages/quickchat.xhtml  <style>    ->  src/app/layout/quick-chat/quick-chat.scss    (+ Angular adaptation block)
 *   Java  web/WEB-INF/pages/quickchat.xhtml  markup     ->  src/app/layout/quick-chat/quick-chat.html
 *   Java  web/WEB-INF/pages/quickchat.xhtml  <script>   ->  src/app/layout/quick-chat/quick-chat.engine.ts
 *
 * template.xhtml includes quickchat.xhtml once, outside .layout-wrapper, for every signed-in page; here the Shell hosts it
 * (layout/quick-chat/quick-chat.ts). Like the Java box, the chat inside it is the full chat page loaded in an iframe in "embed"
 * mode — here the route /chat-embed (features/chat/chat-embed.ts) instead of a `srcdoc` copy of chatbot.face. The Java files
 * are only READ. The outputs carry a "GENERATED" header — change this script, never the output. A swap() that no longer matches
 * stops the run on purpose: it means the original changed in a place the port depends on.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { between, editor, markupToTemplate, reader } from './lib/port.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const java = resolve(process.env.TS_JAVA_ROOT ?? join(root, '..', 'triple_sale_main'), 'web');
const out = join(root, 'src/app/layout/quick-chat');
mkdirSync(out, { recursive: true });

const read = reader(java);
const FROM = 'web/WEB-INF/pages/quickchat.xhtml';
const GENERATED = `GENERATED by tools/sync-quick-chat.mjs from ${FROM} — do not edit; change the script and run \`npm run quick-chat:sync\`.`;
const xhtml = read('WEB-INF/pages/quickchat.xhtml');

/* ================================================================================== stylesheet */
const css = editor('quickchat.xhtml style', between(xhtml, 'quickchat.xhtml', '<style>', '</style>'));
css.swapAll('body[data-theme="dark"]', "html[data-theme='dark']");
// Java: #chatMenuBtn is a div inside the pinned wrapper, so `position:relative` was harmless. Here #chatMenuBtn IS the rail button, which
// side-rail.ts pins to the bottom edge with position:absolute — an id selector would win over that and drop it under the other items.
css.swap('#chatMenuBtn{position:relative;}', '/* #chatMenuBtn{position:relative;} — dropped: the rail button is pinned (position:absolute) by side-rail.ts and already positions the dot */');

const scssHeader = `/* Quick chat stylesheet. ${GENERATED}
   It is the <style> of the Java file copied verbatim, except:
     body[data-theme="dark"] -> html[data-theme='dark']       (the Angular shell puts the theme on <html>; same specificity)
   Loaded with ViewEncapsulation.None: the button of the side rail (#chatMenuBtn) is outside this component. */

`;
const ADAPTATION = `/* ───── Angular adaptation (not part of the Java file) ──────────────────────────────────
   quickchat.xhtml is included by template.xhtml, so the GLOBAL rules of the Java stylesheet stack reach it. Those that touch this
   markup are repeated here, scoped to it. base.scss (the Angular reset) sets a font / colour / padding / border on form controls
   that the Java page keeps at the browser default, so hand the defaults back for the properties .qc-btn does not set itself. */
.qc-wrap button { font: revert; letter-spacing: revert; padding: revert; }
/* template.xhtml: h1…h10, span, p, button, ul, li, div, a, tr, td { font-family: NotoSansThai } */
.qc-wrap :is(span, button, div) { font-family: NotoSansThai; }
ts-quick-chat-view { display: contents; }
/* ───── end of Angular adaptation ──────────────────────────────────────────────────── */
`;
writeFileSync(join(out, 'quick-chat.scss'), scssHeader + ADAPTATION + '\n' + css.text.replace(/^ {4}/gm, '').replace(/^\n+/, '').replace(/\s+$/, '\n'));

/* ================================================================================== template */
const mFrom = xhtml.indexOf('<div id="qcWrap"');
const mTo = xhtml.indexOf('<script type="text/javascript">', mFrom);
if (mFrom < 0 || mTo < 0) throw new Error('quickchat.xhtml: markup boundaries not found');
let tpl = markupToTemplate(xhtml.slice(mFrom, mTo), 'quickchat.xhtml markup');
tpl = tpl.replace(/^ {4}/gm, '').replace(/\s+$/, '\n');
writeFileSync(
  join(out, 'quick-chat.html'),
  `<!-- ${GENERATED}\n     The markup of the Java file; #{commonBean.msg['k']} -> t('k') · everything else is verbatim -->\n` + tpl,
);

/* ================================================================================== engine */
const scriptRaw = between(xhtml, 'quickchat.xhtml', '/*<![CDATA[*/', '/*]]>*/');
const iifeHead = '(function () {\n';
const iifeFrom = scriptRaw.indexOf(iifeHead);
const iifeTo = scriptRaw.lastIndexOf('})();');
if (iifeFrom < 0 || iifeTo < 0) throw new Error('quickchat.xhtml: IIFE wrapper not found');
const js = editor('quickchat.xhtml script', scriptRaw.slice(iifeFrom + iifeHead.length, iifeTo));

// the page inside the box is the box itself: no overlay inside an overlay
js.swap(
  `if (window.top !== window.self) { return; }`,
  `if (window.top !== window.self) { return { toggle: function () { return false; }, pageChanged: function () {}, destroy: function () {} }; }`,
);
// environment: the URLs and the page the user is on (Java: EL contextPath, location.pathname, location.href)
js.swapBlock(
  `            var CTX = '#{request.contextPath}';`,
  `            var wrap = document.getElementById('qcWrap');`,
  '',
);
js.swap(`function onChatPage() { return /\\/chatbot\\.face$/.test(window.location.pathname); }`, `function onChatPage() { return !!env.onChatPage(); }`);
js.swap(`function goFull() { window.location.href = URL_FULL; }`, `function goFull() { env.goFull(); }`);
// the box loads the chat page in embed mode: a route of the SPA (same origin, so no X-Frame-Options / srcdoc detour);
// it reads the open room (K_ROOM) from sessionStorage itself instead of getting it injected
js.swapBlock(
  `            /* ก้อนที่ฉีดไว้หัวเอกสาร srcdoc`,
  `            /* ★ 10/11/2026 — จำสถานะข้ามหน้าด้วย sessionStorage`,
  `            function load() {
                if (state !== 0) { return; }
                state = 1;
                loadEl.classList.remove('hide');
                frame.addEventListener('load', function () { loadEl.classList.add('hide'); }, {once: true});
                frame.src = env.embedUrl;
                state = 2;
            }

`,
);
// the button's fallback target (a .face URL in Java) is the full chat page
js.swap(`if (!window.cbQuickChat()) { window.location.href = url; }`, `if (!window.cbQuickChat()) { goFull(); }`);
// global listeners are registered through listen() so destroy() can remove them
js.text = js.text.replace(/\bwindow\.addEventListener\(/g, 'listen(window, ');
if (/\b(setInterval|XMLHttpRequest|fetch\()/.test(js.text.replace(/\/\*[\s\S]*?\*\//g, ''))) throw new Error('quickchat.xhtml script: unexpected fetch / timer (add it to destroy())');
if (/#\{/.test(js.text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, ''))) throw new Error('quickchat.xhtml script: EL left over in code');
{
  const rest = js.text.replace(/\/\*[\s\S]*?\*\//g, '').match(/.{0,40}(location\.(href|pathname)|URL_FULL|URL_EMBED|CTX).{0,40}/);
  if (rest) throw new Error('quickchat.xhtml script: a URL read is left: ' + rest[0]);
}

const engineHeader = `// @ts-nocheck
/* eslint-disable */
/**
 * Quick chat engine. ${GENERATED}
 *
 * The script of the Java include, same behaviour line by line: the floating chat box (draggable, resizable, size / position /
 * open state remembered per tab in sessionStorage), the chat page in it, the green dot on the "แชท" button, the
 * window.cbQuickChat* hooks the other pages call, the open-room and "switch to this customer's room" messages.
 * "@ts-nocheck": the source is ES5 written for a browser global scope; typing it would change it, not port it.
 *
 * What changed versus the Java file (all of it lives in tools/sync-quick-chat.mjs):
 *   - the environment is injected (QuickChatEnv): the URL of the chat page in embed mode, "is this the full chat page",
 *     "go to the full chat page" — in Java these were EL (contextPath), location.pathname and location.href;
 *   - the chat page is loaded with iframe.src (the SPA route /chat-embed) instead of fetch + srcdoc; that route restores the
 *     open room from sessionStorage itself (Java injected it into the srcdoc);
 *   - global listeners are removed by the function returned from startQuickChat(); pageChanged() hides the box on the full chat
 *     page and brings it back on the next page: Java did that by reloading the page, the SPA changes page without one.
 */

export interface QuickChatEnv {
  /** URL of the chat page in embed mode (the SPA route /chat-embed, with the base href) */
  embedUrl: string;
  /** true on the full chat page (/chat): the button does not open the box there */
  onChatPage: () => boolean;
  /** the full chat page */
  goFull: () => void;
}

export interface QuickChatHandle {
  /** the "แชท" button: true = handled (box opened / closed) ; false = the button goes to the full chat page */
  toggle: () => boolean;
  /** the route changed: hide the box on the full chat page, bring it back (when it was left open) elsewhere */
  pageChanged: () => void;
  destroy: () => void;
}

export function startQuickChat(env: QuickChatEnv): QuickChatHandle {
            var disposers = [];
            function listen(target, type, fn, opts) {
                target.addEventListener(type, fn, opts);
                disposers.push(function () { target.removeEventListener(type, fn, opts); });
            }
`;
const engineFooter = `
            function pageChanged() {
                var shown = wrap.style.display === 'flex';
                if (onChatPage()) {
                    if (shown) { wrap.style.display = 'none'; mark(false); }
                } else if (ssGet(K_OPEN) === '1' && !shown) {
                    open();
                }
            }

            return {
                toggle: function () { return window.cbQuickChat(); },
                pageChanged: pageChanged,
                destroy: function destroy() {
                    disposers.splice(0).forEach(function (d) { d(); });
                    mark(false);
                    delete window.cbQuickChat;
                    delete window.cbQuickChatGo;
                    delete window.cbQuickChatOpenProspect;
                }
            };
}
`;
writeFileSync(join(out, 'quick-chat.engine.ts'), engineHeader + js.text.replace(/\s+$/, '\n') + engineFooter);

console.log(`Quick chat synced from ${java}`);
