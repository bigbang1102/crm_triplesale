#!/usr/bin/env node
/**
 * Regenerates the DrillDown page ("DrillDown" — the 11 reports T-CS-01 … T-FI-01, route /crm/drilldown/:code) from the Java
 * original so the two can never drift while both exist:
 *
 *   npm run drilldown:sync          (Java project = ../triple_sale_main, or set TS_JAVA_ROOT)
 *
 *   Java  web/pages/drilldown.xhtml            <style> + crm_list.css  ->  src/app/features/drilldown/drilldown.scss   (+ Angular adaptation block)
 *   Java  web/pages/drilldown.xhtml            markup                  ->  src/app/features/drilldown/drilldown.html
 *   Java  web/pages/drilldown.xhtml            <script>                ->  src/app/features/drilldown/drilldown.engine.ts
 *
 * The page links two shared support files: resources/support/crm_list.css (the list-page stylesheet, copied verbatim into the scss
 * as the Java <link> loads it) and resources/support/drag_scroll.{css,js} (already part of the app: styles/_drag-scroll.scss and
 * core/dom/drag-scroll.ts, which the host starts with the selector the Java <script data-targets> names).
 *
 * The Java files are only READ. The outputs carry a "GENERATED" header — change this script (the swap() list / the adaptation
 * block), never the output. A swap() that no longer matches stops the run on purpose: the original changed in a place the port
 * depends on.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { darkPort, editor, markupToTemplate, reader, undeclaredNames } from './lib/port.mjs';
import { adaptation, engineScaffold, splitSection, uiDefines } from './lib/port-kit.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const java = resolve(process.env.TS_JAVA_ROOT ?? join(root, '..', 'triple_sale_main'), 'web');
const out = join(root, 'src/app/features/drilldown');
mkdirSync(out, { recursive: true });

const read = reader(java);
const GENERATED = `GENERATED by tools/sync-drilldown.mjs from web/pages/drilldown.xhtml — do not edit; change the script and run \`npm run drilldown:sync\`.`;
const SCOPE = ':where(ts-drilldown-view)';

const d = uiDefines(read('pages/drilldown.xhtml'), 'drilldown.xhtml');
if (!d.head || !d.content) throw new Error('drilldown.xhtml: ui:define head / content not found');
const head = splitSection(d.head);
const body = splitSection(d.content);

/* ---- what the page links: the support files must be the ones the port knows ---- */
const linked = head.links.map((l) => l.replace(/^#\{request\.contextPath\}\//, '').replace(/\?.*$/, ''));
if (JSON.stringify(linked) !== JSON.stringify(['resources/support/drag_scroll.css', 'resources/support/crm_list.css'])) {
  throw new Error('drilldown.xhtml: the <link> stylesheets changed: ' + linked.join(', '));
}
if (head.externalScripts.length !== 1 || !/resources\/support\/drag_scroll\.js/.test(head.externalScripts[0])) {
  throw new Error('drilldown.xhtml: the <script src> list changed: ' + head.externalScripts.join(', '));
}
if (!/data-targets="\.ct-table-wrap"/.test(d.head)) throw new Error('drilldown.xhtml: drag_scroll.js data-targets changed (the host starts startDragScroll(".ct-table-wrap"))');
if (head.styles.length !== 1) throw new Error(`drilldown.xhtml head: expected 1 <style>, found ${head.styles.length}`);
if (body.styles.length || body.links.length || body.externalScripts.length || body.scripts.length !== 1) throw new Error('drilldown.xhtml content: expected markup + exactly one inline <script>');

/* ================================================================================== markup */
const markup = editor('drilldown.xhtml markup', body.markup.replace(/^\s+/, '').replace(/\s+$/, ''));
// the Facelets comment blocks are gone (splitSection); what is left is the markup of the card and of the column-filter menu
const tpl = markupToTemplate(markup.text, 'drilldown.xhtml markup')
  .replace(/^ {12}/gm, '')
  .replace(/^\n+/, '');
if (!/id="ddHead"/.test(tpl) || !/id="ddFMenu"/.test(tpl)) throw new Error('drilldown.xhtml markup: ddHead / ddFMenu not found');
writeFileSync(
  join(out, 'drilldown.html'),
  `<!-- ${GENERATED}
     The markup of drilldown.xhtml (its <style> and crm_list.css are in drilldown.scss); #{commonBean.msg[…]} -> t('…') · everything else is verbatim -->\n` +
    tpl.replace(/\s+$/, '\n'),
);

/* ================================================================================== engine */
const js = editor('drilldown.xhtml script', body.scripts[0].replace(/^\n/, ''));

/* ---- environment: what Facelets / the session / the URL gave the page ---- */
// the i18n bridge: every message of window.DD_I18N was spliced in by the server, in the language of the session
js.text = js.text.replace(/"#\{commonBean\.msg\['([\w.]+)'\]\}"/g, (_m, k) => `env.t(${JSON.stringify(k)})`);
js.swap(`"#{commonBean.currentLang}"`, `env.lang`);
js.swap(`window.DD_I18N = {`, `var DD_I18N = {`);
js.swap(`var I18N = window.DD_I18N || {};`, `var I18N = DD_I18N || {};`);
js.swap(`var API = "#{request.contextPath}/board/drilldown";`, `var API = env.api;`);
// ?code= of the page address -> the :code of the route
js.swap(
  `var params = new URLSearchParams(window.location.search);
                        var code = params.get('code');`,
  `var code = env.code;`,
);
js.swap(`document.title = 'DrillDown ' + state.code;`, `env.setTitle('DrillDown ' + state.code);`);
js.text = js.text.replace(/(^|[^.\w$])fetch\(/gm, '$1env.fetch(');

/* ---- global listeners, observers and timers are registered through listen() / track() / tmo() so that destroy() can remove them ---- */
js.text = js.text.replace(/\b(document|window)\.addEventListener\(/g, 'listen($1, ');
js.swap(`new ResizeObserver(refreeze).observe(el.scroll);`, `track(new ResizeObserver(refreeze)).observe(el.scroll);`);
js.swap(
  `setTimeout(function () { URL.revokeObjectURL(link.href); }, 1000);`,
  `setTimeout(function () { exportUrls.splice(exportUrls.indexOf(link.href), 1); URL.revokeObjectURL(link.href); }, 1000);`,
);
js.text = js.text.replace(/(^|[^.\w$])setTimeout\(/gm, '$1tmo(');
// a frame callback that fires after the screen was left would measure a detached table
js.swap(`requestAnimationFrame(freezeColumns);`, `requestAnimationFrame(function () { if (!destroyed) { freezeColumns(); } });`);
// the blob URL of the export is revoked a second later; a screen left before that revokes it on destroy
js.swap(
  `link.href = URL.createObjectURL(blob);`,
  `link.href = URL.createObjectURL(blob);
                        exportUrls.push(link.href);`,
);

/* ---- the original must not reach the page address, the document cookies or global state the shell owns ---- */
{
  const code = js.text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '').replace(/\s\/\/[^\n'"]*$/gm, '');
  if (/#\{/.test(code)) throw new Error('drilldown script: EL left over in code: ' + code.match(/.{0,40}#\{.{0,40}/)[0]);
  if (/\b(setInterval|XMLHttpRequest|localStorage|sessionStorage|document\.cookie)\b/.test(code)) throw new Error('drilldown script: unexpected timer / XHR / storage (add it to destroy())');
  const rest = code.match(/.{0,40}\b(window\.location|location\.(href|pathname|reload|search)|window\.open|\.face\b|\.xhtml\b|document\.title|window\.DD_I18N).{0,40}/);
  if (rest) throw new Error('drilldown script: a URL read / Java page link is left: ' + rest[0]);
  const bare = code.match(/(^|[^.\w$'"])fetch\(/m);
  if (bare) throw new Error('drilldown script: a bare fetch call is left: ' + bare[0]);
  if (/window\.\w+\s*=/.test(code)) throw new Error('drilldown script: a window.* export appeared — add it to the scaffold (exported)');
  if (/\bon[a-z]+="/.test(markup.text)) throw new Error('drilldown markup: an inline handler appeared — the engine must publish it (handlers / exported)');
}

const scaffold = engineScaffold({
  header: `
 * DrillDown page engine. ${GENERATED}
 *
 * The page script of the Java screen, same behaviour line by line: the card (report code + row count + Excel/CSV export), the table
 * drawn from the columns / rows the server sends, the frozen left columns, the per-column filter menu (a list of values to tick, or a
 * calendar for date columns), the page buttons, and the loading skeleton / empty / error states.
 *
 * WHY it is imperative DOM code and not Angular components: the Java page is a data-driven DOM application whose HTML is drawn from
 * API data as strings (the columns are not fixed — the service reads them from the response). Porting it 1:1 is what guarantees the
 * screen, texts and states are identical to the production system; the template (drilldown.html) and stylesheet (drilldown.scss) are
 * the Java markup / CSS verbatim and the engine binds to them through the same ids as before.
 * "@ts-nocheck": the source is ES5 written for a browser global scope; typing it would change it, not port it.
 *
 * What changed versus the Java file (all of it lives in tools/sync-drilldown.mjs):
 *   - the environment is injected (DrilldownEnv): the messages and the language (Java: EL), the report code (Java: ?code=), the
 *     servlet URL and fetch, the window title;
 *   - global listeners, the ResizeObserver and timers are removed by the function returned from startDrilldown(), and so are the
 *     blob URLs of an export that was not revoked yet.`,
  envType: 'DrilldownEnv',
  envBody: `  /** commonBean.msg['key'] in the active language */
  t: (key: string) => string;
  /** commonBean.currentLang: 'th' | 'en' (the calendar of the column filter takes its locale from it) */
  lang: string;
  /** the servlet of the page: "#{request.contextPath}/board/drilldown" in Java — the contract base here ("/board/drilldown") */
  api: string;
  /** the report code the page opens: "?code=" of the Java address, ":code" of the route ('' = the default report T-CS-01) */
  code: string;
  /** document.title = … */
  setTitle: (title: string) => void;
  /** the BFF contract of the page: GET <api>?action=data&code=&page=&pageSize= */
  fetch: (input: string, init?: RequestInit) => Promise<Response>;`,
  fn: 'startDrilldown',
  handlers: [],
  exported: [],
  cleanup: `    exportUrls.splice(0).forEach(function (u) { try { URL.revokeObjectURL(u); } catch (e) {} });
`,
});
// exportUrls lives in the engine scope (the page IIFE and destroy() both see it)
const engineGuard = scaffold.guard + `  var exportUrls = [];   /* blob URLs of the CSV exports that are not revoked yet (destroy() revokes them) */\n`;
const engineText = scaffold.header + engineGuard + js.text.replace(/\s+$/, '\n') + scaffold.footer();
const undeclared = await undeclaredNames(engineText.replace(/^\/\/ @ts-nocheck\n/, ''), []);
if (undeclared.length) throw new Error('drilldown engine: names that are not declared (a ReferenceError in strict mode): ' + undeclared.join(', '));
writeFileSync(join(out, 'drilldown.engine.ts'), engineText);

/* ================================================================================== stylesheet (written last: the dark port reads the script) */
const pageCss = editor('drilldown.xhtml style', head.styles[0].replace(/^\n/, ''));
const listCss = editor('crm_list.css', read('resources/support/crm_list.css').replace(/^\n/, ''));
for (const [name, c] of [['drilldown.xhtml', pageCss], ['crm_list.css', listCss]]) {
  c.swapAll('body[data-theme="dark"]', "html[data-theme='dark']");
  c.swapAll('var(--fs-adj,0px)', 'var(--ts-fs-adj,0px)');
  if (/--fs-adj/.test(c.text.replace(/--ts-fs-adj/g, ''))) throw new Error(`${name}: --fs-adj left over`);
}
// the first two rules of crm_list.css style the Java template's elements (#crm_main_body_page, .layout-main .layout-content); the
// Angular shell has the first only — the adaptation block maps both onto it
listCss.swap(
  `            #crm_main_body_page { padding: 0 !important; background: #F0F2FF !important; }
            .layout-main .layout-content { padding: 0 !important; }
`,
  `            /* (Java: #crm_main_body_page / .layout-main .layout-content — see the Angular adaptation block) */
`,
);

const text = tpl + '\n' + js.text;
const adapt =
  adaptation({ read, scope: SCOPE, host: 'ts-drilldown-view', text }) +
  `/* ---- the two rules crm_list.css sets on the Java template's elements (#crm_main_body_page, .layout-main .layout-content) ---- */
#crm_main_body_page:has(.ct-root) { padding: 0 !important; background: #F0F2FF !important; }
`;
const dark = darkPort(read('resources/support/dark_mode.css'), tpl + '\n' + pageCss.text + '\n' + listCss.text + '\n' + js.text, SCOPE, 1);
const DARK_PORT = `\n/* ───── dark_mode.css of the Java app, scoped to the page (${dark.kept} rules that can match it, of ${dark.seen} selectors) ───── */\n${dark.css}\n`;
const dedent = (s) => s.replace(/^ {12}/gm, '').replace(/\s+$/, '\n');
writeFileSync(
  join(out, 'drilldown.scss'),
  `/* DrillDown stylesheet. ${GENERATED}
   resources/support/crm_list.css (linked by the page) + the <style> of drilldown.xhtml, copied verbatim, except:
     body[data-theme="dark"] -> html[data-theme='dark']       (the Angular shell puts the theme on <html>; same specificity)
     --fs-adj                -> --ts-fs-adj                   (A A A font scale token of the Angular shell)
     the first two rules of crm_list.css (Java template elements) -> the Angular adaptation block
   drag_scroll.css is part of the app (styles/_drag-scroll.scss). Loaded with ViewEncapsulation.None: the engine writes HTML strings
   that need global selectors. */

` +
    adapt +
    '\n/* ───── resources/support/crm_list.css ───── */\n' +
    dedent(listCss.text) +
    '\n/* ───── <style> of drilldown.xhtml ───── */\n' +
    dedent(pageCss.text) +
    DARK_PORT,
);

/* ================================================================================== the report registry (data of DrilldownApiService) */
// The 11 report definitions — code, endpoint path, date-range support and the dictionary of column titles — live in the Java
// SERVICE (not in the page); the mock builds its columns from them exactly as the service does, and the live adapter will need the
// same table. Copying it by script keeps it from drifting.
{
  const svcFile = resolve(java, '..', 'src/java/com/ace/manage/content/DrilldownApiService.java');
  // the Java source without its comments (a scan that knows strings: "…" may contain // or /*)
  const stripComments = (src) => {
    let o = '';
    for (let i = 0; i < src.length; ) {
      const c = src[i];
      if (c === '"') {
        let j = i + 1;
        while (j < src.length && src[j] !== '"') j += src[j] === '\\' ? 2 : 1;
        o += src.slice(i, j + 1);
        i = j + 1;
      } else if (c === '/' && src[i + 1] === '/') {
        while (i < src.length && src[i] !== '\n') i++;
      } else if (c === '/' && src[i + 1] === '*') {
        const j = src.indexOf('*/', i + 2);
        i = j < 0 ? src.length : j + 2;
      } else {
        o += c;
        i++;
      }
    }
    return o;
  };
  const svc = stripComments(readFileSync(svcFile, 'utf8').replace(/\r\n/g, '\n'));
  const tables = new Map();
  for (const m of svc.matchAll(/private static final String\[\]\[\] ((?:LABELS|COMPOSITE)_\w+) = \{([\s\S]*?)\n    \};/g)) {
    const rows = [...m[2].matchAll(/\{\s*((?:"[^"\\]*"\s*,?\s*)+)\}/g)].map((r) => [...r[1].matchAll(/"([^"\\]*)"/g)].map((s) => s[1]));
    tables.set(m[1], rows);
  }
  if (/"[^"]*\\[^"]*"/.test([...svc.matchAll(/private static final String\[\]\[\][\s\S]*?\n    \};/g)].map((m) => m[0]).join('\n'))) throw new Error('DrilldownApiService: an escape sequence appeared in a label dictionary');
  const reports = [...svc.matchAll(/put\(map, new ReportDef\("([^"]+)", "([^"]+)", (true|false), (LABELS_\w+)(?:, (COMPOSITE_\w+))?\)\);/g)].map((m) => {
    const labels = tables.get(m[4]);
    if (!labels?.length || labels.some((r) => r.length !== 2)) throw new Error(`DrilldownApiService: ${m[4]} was not understood`);
    const composites = m[5] ? tables.get(m[5]) : [];
    if (!composites || composites.some((r) => r.length < 3)) throw new Error(`DrilldownApiService: ${m[5]} was not understood`);
    return { code: m[1], apiPath: m[2], supportsDateRange: m[3] === 'true', labels, composites };
  });
  if (reports.length !== 11) throw new Error(`DrilldownApiService: expected 11 reports, found ${reports.length}`);
  const hidden = [...(/private static final String\[\] HIDDEN_LABELS = \{([\s\S]*?)\};/.exec(svc)?.[1] ?? '').matchAll(/"([^"\\]*)"/g)].map((m) => m[1]);
  if (hidden.length !== 3) throw new Error(`DrilldownApiService: expected 3 HIDDEN_LABELS, found ${hidden.length}`);
  const q = (s) => JSON.stringify(s);
  writeFileSync(
    join(out, 'drilldown.reports.ts'),
    `/**
 * The report registry of the DrillDown service. GENERATED by tools/sync-drilldown.mjs from
 * src/java/com/ace/manage/content/DrilldownApiService.java (REPORTS, LABELS_*, COMPOSITE_*, HIDDEN_LABELS) — do not edit; change the
 * script and run \`npm run drilldown:sync\`.
 *
 * code = what the user sees and the \`?code=\` of the page · apiPath = the end of GET …/api/v1/drilldown/<apiPath> · labels = [field of
 * the data (compared normalized: letters and digits, lower case), title of the column] in the order of the table header · composites =
 * [virtual column key, source field, …] (the cell is the sources joined by a space).
 */
export interface ReportDef {
  readonly code: string;
  readonly apiPath: string;
  /** false only for tcs01: the service does not take fromdate / todate */
  readonly supportsDateRange: boolean;
  readonly labels: readonly (readonly [string, string])[];
  readonly composites: readonly (readonly string[])[];
}

/** titles of columns that no report shows (the service hides them, in the header, the cells and the export alike) */
export const HIDDEN_LABELS: readonly string[] = ${q(hidden)};

export const REPORTS: readonly ReportDef[] = [
${reports
  .map(
    (r) => `  {
    code: ${q(r.code)},
    apiPath: ${q(r.apiPath)},
    supportsDateRange: ${r.supportsDateRange},
    labels: [
${r.labels.map((l) => `      [${q(l[0])}, ${q(l[1])}],`).join('\n')}
    ],
    composites: [${r.composites.map((c) => `[${c.map(q).join(', ')}]`).join(', ')}],
  },`,
  )
  .join('\n')}
];
`,
  );
}

console.log(`DrillDown synced from ${java}: ${dark.kept} dark rules; markup ${tpl.length} chars, css ${pageCss.text.length + listCss.text.length}, script ${js.text.length}`);
