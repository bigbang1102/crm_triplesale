#!/usr/bin/env node
/**
 * Regenerates the supporting documents hub ("ข้อมูลประกอบ", route /crm/supporting-docs — the table of the seven document families with a
 * search box) from the Java original so the two can never drift while both exist:
 *
 *   npm run supporting-docs:sync          (Java project = ../triple_sale_main, or set TS_JAVA_ROOT)
 *
 *   Java  web/pages/supporting_documents.xhtml  <style> of "head"   ->  src/app/features/supporting-docs/supporting-docs.scss
 *   Java  web/pages/supporting_documents.xhtml  markup of "content" ->  src/app/features/supporting-docs/supporting-docs.html
 *   Java  web/pages/supporting_documents.xhtml  <script>            ->  src/app/features/supporting-docs/supporting-docs.engine.ts
 *
 * The page has no API: the seven rows are in the markup, each behind a feature flag (<ui:fragment rendered="#{commonBean.hasFeature(…)}">
 * -> @if (can('…'))). The Java files are only READ. The outputs carry a "GENERATED" header — change this script, never the output.
 */
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { darkPort, editor, markupToTemplate, reader, undeclaredNames } from './lib/port.mjs';
import { adaptation, engineScaffold, expandIncludes, rewriteJavaLinks, splitSection, uiDefines } from './lib/port-kit.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const javaRoot = resolve(process.env.TS_JAVA_ROOT ?? join(root, '..', 'triple_sale_main'));
const java = join(javaRoot, 'web');
const out = join(root, 'src/app/features/supporting-docs');
mkdirSync(out, { recursive: true });

const read = reader(java);
const GENERATED = `GENERATED by tools/sync-supporting-docs.mjs from web/pages/supporting_documents.xhtml — do not edit; change the script and run \`npm run supporting-docs:sync\`.`;
const SCOPE = ':where(.ct-root)';

/* ================================================================================== the Facelets page */
const defines = uiDefines(read('pages/supporting_documents.xhtml'), 'supporting_documents.xhtml');
if (!defines['head'] || !defines['content']) throw new Error('supporting_documents.xhtml: the head / content sections were not found');
const head = splitSection(defines['head']);
const content = splitSection(expandIncludes(defines['content'], read, 'pages', 'supporting_documents.xhtml'));
if (head.styles.length !== 1 || head.links.length !== 1 || head.externalScripts.length !== 1 || content.styles.length || content.scripts.length !== 1 || content.externalScripts.length) {
  throw new Error('supporting_documents.xhtml: the structure changed (expected in head: 1 <style>, drag_scroll.css, drag_scroll.js; in content: 1 inline <script>)');
}
// head: the drag scroll of the table area — the script tag with data-targets becomes startDragScroll(selector) in the host (core/dom/drag-scroll.ts)
if (!/drag_scroll\.css/.test(head.links[0]) || !/drag_scroll\.js/.test(head.externalScripts[0])) throw new Error('supporting_documents.xhtml: the head links are not drag_scroll.css / drag_scroll.js any more');
const dragTargets = /data-targets="([^"]+)"/.exec(defines['head'])?.[1];
if (dragTargets !== '.ct-table-wrap') throw new Error('supporting_documents.xhtml: drag_scroll data-targets changed: ' + dragTargets);

/* ================================================================================== markup */
// images: web/images/<path> is public/assets/images/<path> (copied byte for byte below); links to other pages are routes of this app
let markup = content.markup.trim();
const IMAGES = [...new Set([...markup.matchAll(/#\{request\.contextPath\}\/images\/([\w./-]+)/g)].map((m) => m[1]))];
markup = rewriteJavaLinks(markup, 'supporting_documents.xhtml markup').replace(/#\{request\.contextPath\}\/images\//g, 'assets/images/');
for (const img of IMAGES) {
  mkdirSync(dirname(join(root, 'public/assets/images', img)), { recursive: true });
  copyFileSync(join(java, 'images', img), join(root, 'public/assets/images', img));
}
const tpl = markupToTemplate(markup, 'supporting_documents.xhtml markup').replace(/\s+$/, '\n');
writeFileSync(
  join(out, 'supporting-docs.html'),
  `<!-- ${GENERATED}
     The markup of supporting_documents.xhtml (its <style> is in supporting-docs.scss): <ui:fragment rendered="#{commonBean.hasFeature('X')}"> -> @if (can('X')),
     links to other pages -> routes of this app, #{request.contextPath}/images/ -> assets/images/ -->\n` + tpl,
);

/* ================================================================================== stylesheet */
const css = editor('supporting_documents.xhtml style', head.styles[0].replace(/^\s*\n/, '').replace(/\s+$/, ''));
css.swapAll('body[data-theme="dark"]', "html[data-theme='dark']");
css.swapAll('var(--fs-adj,0px)', 'var(--ts-fs-adj,0px)');
if (/--fs-adj/.test(css.text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/--ts-fs-adj/g, ''))) throw new Error('supporting_documents css: --fs-adj left over');

/* ================================================================================== engine */
const js = editor('supporting_documents.xhtml script', content.scripts[0].replace(/^\s*\n/, '').replace(/\s+$/, ''));
// the row opens the document list in the same tab: window.open(url, '_self') -> the router (the url is already a route of this app)
js.swap(`function sdOpen(url) { window.open(url, '_self'); }`, `function sdOpen(url) { env.navigate(url); }`);
// the system autocomplete (open_down_select.js) is a global of the shell
js.swap(`if (window.odsAutoComplete) {
                    odsAutoComplete('ldSearchInput',`, `if (window.odsAutoComplete) {
                    window.odsAutoComplete('ldSearchInput',`);
// the script ran while the Java document was still loading — nothing here waits for DOMContentLoaded (the IIFE reads the DOM straight away)

/* ---- inline handlers (onclick="…") of the markup call functions by name ---- */
const HANDLER_CALLS = new Set(
  [...tpl.matchAll(/\bon[a-z]+="([^"]*)"/g)].flatMap((h) => [...h[1].matchAll(/(?<![.\w$])([A-Za-z_]\w*)\s*\(/g)].map((x) => x[1])).filter((n) => !['if', 'function', 'return'].includes(n)),
);
for (const n of HANDLER_CALLS) {
  if (!new RegExp(`(^|\\n)\\s*function ${n}\\b`).test(js.text)) throw new Error(`markup calls ${n}() but the script does not declare it`);
}
const HANDLERS = [...HANDLER_CALLS];

/* ---- nothing may reach the page address, the document cookies or global state the shell owns ---- */
{
  const code = js.text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '').replace(/\s\/\/[^\n'"]*$/gm, '');
  if (/#\{/.test(code)) throw new Error('supporting_documents script: EL left over in code: ' + code.match(/.{0,40}#\{.{0,40}/)[0]);
  if (/\b(setInterval|setTimeout|XMLHttpRequest|fetch|localStorage|sessionStorage|document\.cookie|swal)\b/.test(code)) throw new Error('supporting_documents script: unexpected timer / XHR / fetch / storage / swal (add it to env + destroy())');
  const rest = code.match(/.{0,40}\b(window\.location|location\.(href|pathname|reload)|window\.open|\.face\b|\.xhtml\b).{0,40}/);
  if (rest) throw new Error('supporting_documents script: a URL read / Java page link is left: ' + rest[0]);
}

const scaffold = engineScaffold({
  header: `
 * Supporting documents hub engine. ${GENERATED}
 *
 * The page script of the Java screen, same behaviour line by line: the search box (a magnifier that opens an input, filters the rows by
 * name, offers the names with the system autocomplete) and the row click that opens a document family.
 *
 * "@ts-nocheck": the source is ES5 written for a browser global scope; typing it would change it, not port it.
 *
 * What changed versus the Java file (all of it lives in tools/sync-supporting-docs.mjs):
 *   - the environment is injected (SupportingDocsEnv): opening a family is env.navigate(route) instead of window.open(url, '_self');
 *   - the links are routes of this app (core/navigation/java-links.ts) in the template as well;
 *   - sdOpen is published on window for the inline onclick handlers, and removed again by the function returned from startSupportingDocs().`,
  envType: 'SupportingDocsEnv',
  envBody: `  /** window.open(url, '_self'): go to a route of this app, e.g. /crm/supporting-docs/letter-of-intent */
  navigate: (route: string) => void;`,
  fn: 'startSupportingDocs',
  handlers: HANDLERS,
  exported: HANDLERS,
});
const engineText = scaffold.header + scaffold.guard + js.text.replace(/\s+$/, '\n') + scaffold.footer();
const undeclared = await undeclaredNames(engineText.replace(/^\/\/ @ts-nocheck\n/, ''), []);
if (undeclared.length) throw new Error('supporting_documents engine: names that are not declared (a ReferenceError in strict mode): ' + undeclared.join(', '));
writeFileSync(join(out, 'supporting-docs.engine.ts'), engineText);

/* ================================================================================== stylesheet (written last: the dark port reads the script) */
const pageText = tpl + '\n' + css.text + '\n' + js.text;
const dark = darkPort(read('resources/support/dark_mode.css'), pageText, SCOPE, 1);
const dedent = (s) => s.replace(/^ {12}/gm, '').replace(/\s+$/, '\n');
writeFileSync(
  join(out, 'supporting-docs.scss'),
  `/* Supporting documents hub stylesheet. ${GENERATED}
   The <style> of supporting_documents.xhtml (ui:define "head"), copied verbatim, except:
     body[data-theme="dark"] -> html[data-theme='dark']       (the Angular shell puts the theme on <html>; same specificity)
     --fs-adj                -> --ts-fs-adj                   (A A A font scale token of the Angular shell)
   Loaded with ViewEncapsulation.None. (drag_scroll.css is global: styles/_drag-scroll.scss) */

` +
    adaptation({ read, scope: SCOPE, host: 'ts-supporting-docs-view', text: tpl + '\n' + js.text }) +
    '\n' +
    dedent(css.text) +
    `\n/* ───── dark_mode.css of the Java app, scoped to the page (${dark.kept} rules that can match it, of ${dark.seen} selectors) ───── */\n${dark.css}\n`,
);

console.log(`Supporting docs synced from ${java}: ${HANDLERS.length} handler(s), ${IMAGES.length} image(s), ${dark.kept} dark rules; markup ${tpl.length} chars, css ${css.text.length}, script ${js.text.length}`);
