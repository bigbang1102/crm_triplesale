#!/usr/bin/env node
/**
 * Regenerates the Report page ("รายงาน", route /report — the list of reports and the filter panel of the selected one) from the Java
 * original so the two can never drift while both exist:
 *
 *   npm run report:sync          (Java project = ../triple_sale_main, or set TS_JAVA_ROOT)
 *
 *   Java  web/pages/report.xhtml  <style> of "head"   ->  src/app/features/report/report.scss   (+ Angular adaptation block)
 *   Java  web/pages/report.xhtml  markup of "content" ->  src/app/features/report/report.html
 *   Java  web/pages/report.xhtml  <script>            ->  src/app/features/report/report.engine.ts
 *   Java  web/resources/mock/report_mock.json         ->  src/app/features/report/report.data.generated.ts   (the page's own data file)
 *
 * The Java files are only READ. The outputs carry a "GENERATED" header — change this script (the swap() list), never the output. A swap()
 * that no longer matches stops the run on purpose: the original changed in a place the port depends on.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { darkPort, editor, markupToTemplate, reader, undeclaredNames } from './lib/port.mjs';
import { adaptation, engineScaffold, expandIncludes, splitSection, uiDefines } from './lib/port-kit.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const java = resolve(process.env.TS_JAVA_ROOT ?? join(root, '..', 'triple_sale_main'), 'web');
const out = join(root, 'src/app/features/report');
mkdirSync(out, { recursive: true });

const read = reader(java);
const GENERATED = `GENERATED by tools/sync-report.mjs from web/pages/report.xhtml (+ web/resources/mock/report_mock.json) — do not edit; change the script and run \`npm run report:sync\`.`;
const SCOPE = ':where(.rpt-root)';

/* ================================================================================== the Facelets page */
const defines = uiDefines(read('pages/report.xhtml'), 'report.xhtml');
if (!defines['head'] || !defines['content']) throw new Error('report.xhtml: the head / content sections were not found');
const head = splitSection(defines['head']);
const content = splitSection(expandIncludes(defines['content'], read, 'pages', 'report.xhtml'));
if (head.styles.length !== 1 || head.links.length || content.styles.length || content.scripts.length !== 1 || content.externalScripts.length || head.externalScripts.length) {
  throw new Error('report.xhtml: the structure changed (expected one <style> in head, one inline <script> in content, no links / external scripts)');
}

/* ================================================================================== markup */
const tpl = markupToTemplate(content.markup.trim(), 'report.xhtml markup').replace(/\s+$/, '\n');
writeFileSync(
  join(out, 'report.html'),
  `<!-- ${GENERATED}
     The markup of report.xhtml (its <style> is in report.scss); everything is verbatim, the texts of the page are literal Thai in the original too -->\n` + tpl,
);

/* ================================================================================== stylesheet */
const css = editor('report.xhtml style', head.styles[0].replace(/^\s*\n/, '').replace(/\s+$/, ''));
css.swapAll('body[data-theme="dark"]', "html[data-theme='dark']");
css.swapAll('var(--fs-adj,0px)', 'var(--ts-fs-adj,0px)');
if (/--fs-adj/.test(css.text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/--ts-fs-adj/g, ''))) throw new Error('report css: --fs-adj left over');

/* ================================================================================== engine */
const js = editor('report.xhtml script', content.scripts[0].replace(/^\s*\n/, '').replace(/\s+$/, ''));

/* ---- environment: what Facelets / the session / the browser gave the page ---- */
js.swap(
  `var CTX = (function () { var p = window.location.pathname.split('/'); return p.length > 1 ? '/' + p[1] : ''; })();`,
  `var CTX = env.ctx;`,
);
js.swap(`var RPT_PERM = #{commonBean.reportPermJson};`, `var RPT_PERM = env.initial('reportPermJson');`);
js.text = js.text.replace(/(^|[^.\w$])fetch\(/gm, '$1env.fetch(');
js.swap(`var w = window.open(url, '_blank');`, `var w = env.open(url, '_blank');`);
// the SweetAlert of template.xhtml
js.swap(`if (window.swal) {`, `if (env.swal) {`);
js.swap(`swal({ text: msg, icon: 'info', timer: 3000, buttons: false });`, `env.swal({ text: msg, icon: 'info', timer: 3000, buttons: false });`);
// the script ran while the Java document was still loading: boot() waited for DOMContentLoaded (the engine plays that event itself)
js.swap(`if (document.readyState === 'loading') {`, `if (readyState === 'loading') {`);
js.swap(`document.addEventListener('DOMContentLoaded', boot);`, `onReady(boot);`);

/* ---- nothing may reach the page address, the document cookies or global state the shell owns ---- */
{
  const code = js.text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '').replace(/\s\/\/[^\n'"]*$/gm, '');
  if (/#\{/.test(code)) throw new Error('report script: EL left over in code: ' + code.match(/.{0,40}#\{.{0,40}/)[0]);
  if (/\b(setInterval|XMLHttpRequest|localStorage|sessionStorage|document\.cookie)\b/.test(code)) throw new Error('report script: unexpected timer / XHR / storage (add it to destroy())');
  const rest = code.match(/.{0,40}\b(window\.location|location\.(href|pathname|reload)|window\.open|\.face\b|\.xhtml\b).{0,40}/);
  if (rest) throw new Error('report script: a URL read / Java page link is left: ' + rest[0]);
  const bare = code.match(/(^|[^.\w$'"])(fetch|swal)\(/m);
  if (bare) throw new Error('report script: a bare fetch / swal call is left: ' + bare[0]);
  if (/\bon[a-z]+="/.test(tpl)) throw new Error('report markup: an inline handler appeared — export its function (see sync-dashboard.mjs HANDLERS_EXTRA)');
}

const scaffold = engineScaffold({
  header: `
 * Report page engine. ${GENERATED}
 *
 * The page script of the Java screen, same behaviour line by line: the report list (groups, search, permission filter), the filter
 * panel of the selected report (dd/MM/yyyy date ranges, selects with options from master data, required filters) and the call that
 * opens the report PDF in a new tab.
 *
 * WHY it is imperative DOM code and not Angular components: see engine.ts of the Dashboard — the Java page draws its HTML from data as
 * strings; porting it 1:1 is what guarantees the screen, texts and states are identical to the production system.
 * "@ts-nocheck": the source is ES5 written for a browser global scope; typing it would change it, not port it.
 *
 * What changed versus the Java file (all of it lives in tools/sync-report.mjs):
 *   - the environment is injected (ReportEnv): the context path, fetch, window.open, SweetAlert and the value the server rendered
 *     into the page with EL (commonBean.reportPermJson);
 *   - the script waited for DOMContentLoaded: the engine plays that event itself, after the script ran (see port-kit.mjs);
 *   - listeners / timers added through listen() / tmo() and the response guard are removed by the function returned from startReport().`,
  envType: 'ReportEnv',
  envBody: `  /** #{request.contextPath}: where the data file and the master data are served from ("/triplesale" in Java) */
  ctx: string;
  /** fetch for ctx + '/resources/mock/report_mock.json', the master data (/board/chat-master-data, /board/employees) */
  fetch: (input: string, init?: RequestInit) => Promise<Response>;
  /** window.open(url, '_blank') — null when the browser blocked the new tab */
  open: (url: string, target?: string) => { closed?: boolean } | null;
  /** SweetAlert v2 (js/sweetalert/sweetalertv1.min.js) */
  swal: (options: Record<string, unknown>) => Promise<unknown>;
  /** the JSON values commonBean rendered into the page with EL: 'reportPermJson' = { <report code>: boolean } */
  initial: (name: string) => any;`,
  fn: 'startReport',
  handlers: [],
  exported: [],
});
const engineText = scaffold.header + scaffold.guard + js.text.replace(/\s+$/, '\n') + scaffold.footer();
const undeclared = await undeclaredNames(engineText.replace(/^\/\/ @ts-nocheck\n/, ''), []);
if (undeclared.length) throw new Error('report engine: names that are not declared (a ReferenceError in strict mode): ' + undeclared.join(', '));
writeFileSync(join(out, 'report.engine.ts'), engineText);

/* ================================================================================== stylesheet (written last: the dark port reads the script) */
const pageText = tpl + '\n' + css.text + '\n' + js.text;
const dark = darkPort(read('resources/support/dark_mode.css'), pageText, SCOPE, 1);
const dedent = (s) => s.replace(/^ {12}/gm, '').replace(/\s+$/, '\n');
writeFileSync(
  join(out, 'report.scss'),
  `/* Report page stylesheet. ${GENERATED}
   The <style> of report.xhtml (ui:define "head"), copied verbatim, except:
     body[data-theme="dark"] -> html[data-theme='dark']       (the Angular shell puts the theme on <html>; same specificity)
     --fs-adj                -> --ts-fs-adj                   (A A A font scale token of the Angular shell)
   Loaded with ViewEncapsulation.None: the engine writes HTML strings that need global selectors. */

` +
    adaptation({ read, scope: SCOPE, host: 'ts-report-view', text: tpl + '\n' + js.text }) +
    '\n' +
    dedent(css.text) +
    `\n/* ───── dark_mode.css of the Java app, scoped to the page (${dark.kept} rules that can match it, of ${dark.seen} selectors) ───── */\n${dark.css}\n`,
);

/* ================================================================================== the page's own data file */
const data = JSON.parse(read('resources/mock/report_mock.json'));
if (!data.filterDefs || !Array.isArray(data.groups)) throw new Error('report_mock.json: { filterDefs, groups } expected');
writeFileSync(
  join(out, 'report.data.generated.ts'),
  `/* ${GENERATED}
   The data file of the page (Java: resources/mock/report_mock.json, fetched by the page as RPT_DATA_URL): the report list and the filter
   definitions of each report. Framework-free: the mock backend and the comparison harness load it. */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export const REPORT_DATA: any = ${JSON.stringify(data, null, 2)};
`,
);

console.log(`Report synced from ${java}: ${dark.kept} dark rules; markup ${tpl.length} chars, css ${css.text.length}, script ${js.text.length}, ${data.groups.reduce((n, g) => n + g.reports.length, 0)} reports`);
