// ---- environment (everything the Facelets page got from the URL / the server / the template)
js.swap(`var CTX = (function () { var p = window.location.pathname.split('/'); return p.length > 1 ? '/' + p[1] : ''; })();`, `var CTX = env.ctx;   /* '/triplesale' — apiBase of the BFF */`);
