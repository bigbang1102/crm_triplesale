#!/usr/bin/env node
/**
 * Regenerates the AI Document Translator screen ("AI แปลเอกสาร") from the Java original so the two can never drift while
 * both exist:
 *
 *   npm run ai-translator:sync   (Java project = ../triple_sale_main, or set TS_JAVA_ROOT)
 *
 *   Java  web/pages/ai_translator.xhtml  <style> x2   ->  src/app/features/ai/translator/translator.scss   (+ Angular adaptation block)
 *   Java  web/pages/ai_translator.xhtml  markup       ->  src/app/features/ai/translator/translator.html
 *   Java  web/pages/ai_translator.xhtml  <script>     ->  src/app/features/ai/translator/translator.engine.ts
 *
 * The Java files are only READ. The three generated files carry a "GENERATED" header — change this script (the adaptation
 * block / the swap() list below), never the output. A swap() that no longer matches the Java source stops the run on
 * purpose: it means the original changed in a place the port depends on.
 *
 * Same method as tools/sync-chat.mjs: the page is ~2,900 lines of CSS, markup and DOM logic that the Java team still edits;
 * keeping it 1:1 is what makes "identical to the Java web" checkable.
 */
