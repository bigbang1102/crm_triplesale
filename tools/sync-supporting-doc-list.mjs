/** the family's own tokens replaced by `cfg` (title, roles), so that the seven pages can be compared */
function norm(f) {
  let m = f.markup;
  const swapAll = (find, repl, min = 1) => {
    const n = m.split(find).length - 1;
    if (n < min) throw new Error(`${f.t.listPage}: ${find} found ${n}x (expected ${min}+)`);
    m = m.split(find).join(repl);
  };
  swapAll(`t('${f.t.titleKey}')`, 't(cfg.titleKey)', 1);
  swapAll(`can('${f.t.rolePrefix}_View')`, 'can(cfg.view)');
  // the button registry (core/permissions/access-buttons.ts, PL-<family>-LS-01 … 03): Java asked hasFeature('<prefix>_Create') for "+ เพิ่มใหม่" only; that role is now
  // the one of the code (LS-02). The search icon (LS-01) and the "ดูรายละเอียด" of a row (LS-03) were always shown. The codes are per family: the host puts them in `cfg.codes`.
  swapAll(`can('${f.t.rolePrefix}_Create')`, 'access(cfg.codes.add)');
  const wrapOnce = (re, code, what) => {
    const found = m.match(re) ?? [];
    if (found.length !== 1) throw new Error(`${f.t.listPage}: ${what} found ${found.length}x (expected 1)`);
    m = m.replace(re, (el) => `@if (access(cfg.codes.${code})) {${el}}`);
  };
  wrapOnce(/<img class="ld-search-ic"[^>]*\/>/g, 'search', 'the search icon');
  wrapOnce(/<div class="ct-ctx-item" onclick="window\.sdGo\(this,'detail'\)">[^\n]*?<\/div>/g, 'detail', 'the "ดูรายละเอียด" item of a row');
  // the credit-application list colours the badge of the rows it draws with an older rule (SupportingDocType.legacyStatusBadge): the bean gives the row its class
  if (f.t.legacyStatusBadge) {
    const LEGACY = `${SENTINEL_OPEN}((quotation.status === 'ACTIVE') ? 'status-success' : ((quotation.status === 'WAIT_APPROVE') ? 'status-pending' : 'status-rejected'))${SENTINEL_CLOSE}`;
    swapAll(LEGACY, `${SENTINEL_OPEN}quotation.statusClass${SENTINEL_CLOSE}`);
  }
  const left = [...m.matchAll(/can\('([^']*)'\)/g)].map((x) => x[1]).filter((k) => !/^cfg\./.test(k));
  if (left.length) throw new Error(`${f.t.listPage}: a role the page does not share with the others: ${left.join(', ')}`);
  return m;
}
