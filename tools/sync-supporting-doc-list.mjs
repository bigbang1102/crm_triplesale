/** the content script with the tokens of the family replaced by cfg (the comment names the family in words: dropped) */
function scriptOf(f) {
  let s = f.content.scripts[0];
  const rep = (re, to) => {
    if (!re.test(s)) throw new Error(`${f.t.listPage}: ${re} not found in the content script`);
    s = s.replace(re, to);
  };
  rep(new RegExp(`\\(([^()]*= )?${f.t.formType}\\)`), '(the family)');
  rep(new RegExp(`formType: '${f.t.formType}', subPage: '${f.t.subPage}',`), 'formType: @FORMTYPE@, subPage: @SUBPAGE@,');
  rep(new RegExp(`pid: 1, pageId: 7, act: 7, acts: ${f.t.acts}, subId: ${f.t.subId}, perPage: 20,`), 'pid: 1, pageId: 7, act: 7, acts: @ACTS@, subId: @SUBID@, perPage: 20,');
  return s;
}
