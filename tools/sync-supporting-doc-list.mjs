/** the page of family `t` rendered in template mode */
function renderFamily(t) {
  const file = `pages/${t.listPage}.xhtml`;
  const r = createRenderer({
    mode: 'ng',
    read,
    vars: { sales_documentView: new Dyn('bean'), cfg: new Dyn('cfg'), contractView: null },
    formAction: '#',
    updateTargets: new Set(UPDATE_TARGETS),
    // the page of family N links to ITS form: anything else is a copy that drifted
    linkTarget: (page, params, R) => {
      const want = `sales_document_sub_${t.n}`;
      if (page !== want) throw new Error(`${file}: links to ${page}, expected ${want}`);
      const get = (k) => params.find(([x]) => x === k)?.[1];
      for (const [k, v] of [['pid', '1'], ['page_id', '7'], ['act', '7'], ['acts', String(t.acts)], ['sub_id', String(t.subId)]]) {
        if (get(k) !== v) throw new Error(`${file}: link parameter ${k}=${get(k)}, expected ${v}`);
      }
      const action = get('action_type');
      const id = get('quotation_id');
      return `/crm/supporting-docs/${R.out(new Dyn('cfg.slug'))}/${id === undefined ? 'new' : R.out(id)}${action && action !== 'add' ? `?action_type=${action}` : ''}`;
    },
    // the inline handlers that build a Java address from the row: written once, static, reading the id from the row (an [attr.onclick] binding is refused by Angular)
    rewriteAttr: (el, name, raw) => {
      if (name === 'onclick' && raw === `window.sdCtxToggle('#{quotation.id}',event)`) return 'window.sdCtxToggle(this.nextElementSibling.id.slice(6),event)';
      const m = /^window\.location\.href='sales_document_sub_(\d)\.face\?pid=1&amp;page_id=7&amp;act=7&amp;acts=(\d+)&amp;sub_id=(\d)&amp;action_type=(edit|detail)&amp;quotation_id=#\{quotation\.id\}'$/.exec(raw);
      if (name === 'onclick' && m) {
        if (+m[1] !== t.n || +m[2] !== t.acts || +m[3] !== t.subId) throw new Error(`${file}: a row action of another family (${raw.slice(0, 80)})`);
        return `window.sdGo(this,'${m[4]}')`;
      }
      return raw;
    },
    viewDate: (v) => v,
  });
  const markup = r.renderFile(file, 'content');
  return { t, r, markup, head: r.partsOf(file, 'head'), content: r.partsOf(file, 'content') };
}
