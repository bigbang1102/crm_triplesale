#!/usr/bin/env node
/**
 * Regenerates the dashboard of the menu "แดชบอร์ด" (route /dashboard) from the designer's snapshot of the new design
 * (`dashboard-snapshot.html` in `dashboard-snapshot.zip`, 20/11/2026 — a page saved from a running Angular build of the new dashboard,
 * 6 tabs: ภาพรวม · Lead & การตลาด · Pipeline & ยอดขาย · ทีมขาย · กิจกรรม · แชท). The source code of that build was not handed over,
 * so the page is rebuilt from what the snapshot rendered:
 *
 *   npm run sales-dashboard:sync -- <path of dashboard-snapshot.html>      (or set TS_DASHBOARD_SNAPSHOT)
 *
 *   snapshot <template data-snap-tab="db-tab-*">   ->  src/app/features/sales-dashboard/sales-dashboard.html
 *            (the page head + tab strip of the first tab, then the panel of every tab inside an @switch on the host's `tab()`)
 *   snapshot <style> (rules of the dashboard's components)  ->  src/app/features/sales-dashboard/sales-dashboard.css
 *
 * Angular's emulated encapsulation attributes of the snapshot (`_nghost-ng-c123…` / `_ngcontent-ng-c123…`) become readable ones
 * (`data-h-<component>` / `data-c-<component>`, e.g. `data-c-db-card`) in the markup and in the CSS alike, so the rules keep matching
 * exactly what they matched in the designer's build. The custom elements (`ts-db-card`, `ts-db-frame`, `ts-icon` …) are kept by name
 * because the CSS selects on them; the host compiles them with CUSTOM_ELEMENTS_SCHEMA.
 *
 * The outputs carry a "GENERATED" header — change this script, never the output. The host (`sales-dashboard.ts`) is written by hand.
 *
 * FAST-DEBT(API): the numbers are the ones the snapshot rendered (mock data of the designer's build, period 01/01/2026 – 31/12/2026) — no
 *   backend / mock model behind them yet; the period / salesperson filters and "ปรับแดชบอร์ด" do not recompute anything · BIG · 2026-11-20
 * FAST-DEBT(STD): the CSS is the designer's (fixed colours in the `--db-*` tokens, not `var(--ts-…)`), kept verbatim like the CSS of the
 *   pages generated from Java · BIG · 2026-11-20
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src/app/features/sales-dashboard');
const TABS = ['overview', 'lead', 'pipeline', 'team', 'activity', 'chat'];
const HEADER =
  "GENERATED by tools/sync-sales-dashboard.mjs from the designer's snapshot (dashboard-snapshot.html, 20/11/2026) — " +
  'do not edit: change the script and run `npm run sales-dashboard:sync -- <snapshot>`';

const fail = (message) => {
  console.error(`[sales-dashboard:sync] ${message}`);
  process.exit(1);
};

const snapshotPath = process.argv[2] ?? process.env.TS_DASHBOARD_SNAPSHOT;
if (!snapshotPath || !existsSync(snapshotPath))
  fail('give the path of dashboard-snapshot.html (argument or TS_DASHBOARD_SNAPSHOT)');
const snapshot = readFileSync(snapshotPath, 'utf8');

// ---------- the tabs the snapshot captured ----------
const templates = new Map();
for (const m of snapshot.matchAll(
  /<template data-snap-tab="db-tab-([a-z]+)">([\s\S]*?)<\/template>/g,
))
  templates.set(m[1], m[2]);
for (const tab of TABS) if (!templates.has(tab)) fail(`the snapshot has no tab "${tab}"`);
if (templates.size !== TABS.length) fail(`unexpected tabs: ${[...templates.keys()].join(', ')}`);

// ---------- encapsulation ids -> component names ----------
const names = new Map(); // c123… -> 'db-card'
const remember = (tag, id) => {
  const name = tag.replace(/^ts-/, '');
  if (names.has(id) && names.get(id) !== name)
    fail(`id ${id} belongs to ${names.get(id)} and ${name}`);
  names.set(id, name);
};
const hostTag = /<(ts-sales-dashboard)\b[^>]*?_nghost-ng-(c\d+)=""/.exec(snapshot);
if (!hostTag) fail('no <ts-sales-dashboard> host in the snapshot');
remember(hostTag[1], hostTag[2]);
for (const html of templates.values()) {
  for (const m of html.matchAll(/<(ts-[a-z0-9-]+)\b[^>]*?_nghost-ng-(c\d+)=""/g))
    remember(m[1], m[2]);
}
const nameOf = (id) => names.get(id) ?? fail(`unknown encapsulation id ${id}`);

// ---------- markup ----------
/** comments out, encapsulation attributes renamed, characters Angular's template syntax would read escaped */
function cleanMarkup(html) {
  if (/<(script|style)\b/i.test(html)) fail('a tab contains <script> / <style> — not expected');
  const renamed = html
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/ _ngcontent-ng-(c\d+)=""/g, (_m, id) => ` data-c-${nameOf(id)}=""`)
    .replace(/ _nghost-ng-(c\d+)=""/g, (_m, id) => ` data-h-${nameOf(id)}=""`)
    .replace(/ ng-reflect-[a-z-]+="[^"]*"/g, '')
    .replace(/ routerlink="[^"]*"/g, '');
  if (/_ng(content|host)-/.test(renamed)) fail('an encapsulation attribute was left over');
  // text: { } @ start interpolation / ICU / control flow; attribute values: {{ }} would interpolate
  return renamed.replace(/(<[^>]*>)|([^<]+)/g, (_m, tag, text) =>
    tag
      ? tag.replace(/[{}]/g, (c) => (c === '{' ? '&#123;' : '&#125;'))
      : text.replace(/[{}@]/g, (c) => ({ '{': '&#123;', '}': '&#125;', '@': '&#64;' })[c]),
  );
}

// the panel is <section id="db-panel"> (overview) or the tab's own component <ts-db-…-tab id="db-panel">
const PANEL_START = /<([a-z][a-z0-9-]*)\b[^>]*\bid="db-panel"/;
function split(tab) {
  const html = cleanMarkup(templates.get(tab));
  const found = PANEL_START.exec(html);
  if (!found) fail(`tab ${tab}: no element with id="db-panel"`);
  const close = `</${found[1]}>`;
  const end = html.lastIndexOf(close) + close.length;
  if (html.slice(end).trim() !== '') fail(`tab ${tab}: something follows the panel`);
  return { head: html.slice(0, found.index), panel: html.slice(found.index, end) };
}

const parts = Object.fromEntries(TABS.map((tab) => [tab, split(tab)]));

/** the tab strip of the first capture, driven by the host instead of the capture's state */
function bindHead(head) {
  let tabs = 0;
  let bound = head.replace(
    /<button([^>]*?) id="db-tab-([a-z]+)" aria-selected="(?:true|false)" tabindex="-?\d">/g,
    (_m, attrs, tab) => {
      tabs++;
      return (
        `<button${attrs} id="db-tab-${tab}" [attr.aria-selected]="tab() === '${tab}'" ` +
        `[attr.tabindex]="tab() === '${tab}' ? 0 : -1" (click)="select('${tab}')" (keydown)="onTabKey($event)">`
      );
    },
  );
  if (tabs !== TABS.length) fail(`expected ${TABS.length} tab buttons in the head, found ${tabs}`);
  for (const cls of ['btn ghost cbtn', 'btn ghost fbtn']) {
    const before = bound;
    bound = bound.replace(`class="${cls}"`, `class="${cls}" (click)="notReady()"`);
    if (bound === before) fail(`no button "${cls}" in the head`);
  }
  return bound;
}

// every capture shows the same head apart from which tab is selected
const normalHead = (head) => head.replace(/ aria-selected="(true|false)" tabindex="-?\d"/g, '');
for (const tab of TABS) {
  if (normalHead(parts[tab].head) !== normalHead(parts.overview.head))
    console.warn(`[sales-dashboard:sync] the head of tab ${tab} differs`);
}

const template = [
  `<!-- ${HEADER} -->`,
  bindHead(parts.overview.head),
  '@switch (tab()) {',
  ...TABS.flatMap((tab) => [`@case ('${tab}') {`, parts[tab].panel, '}']),
  '}',
  '',
].join('\n');

// ---------- CSS ----------
const css =
  /<style>([\s\S]*?)<\/style>/.exec(snapshot.slice(0, snapshot.indexOf('</head>')))?.[1] ??
  fail('no <style> in the head');

/** top-level blocks of a stylesheet (braces inside strings ignored) */
function blocks(text) {
  const found = [];
  let depth = 0;
  let quote = '';
  let from = 0;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quote) {
      if (c === '\\') i++;
      else if (c === quote) quote = '';
    } else if (c === '"' || c === "'") quote = c;
    else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) {
      found.push(text.slice(from, i + 1).trim());
      from = i + 1;
    }
  }
  return found;
}

const ids = [...names.keys()];
const touches = (rule) => ids.some((id) => rule.includes(`-ng-${id}]`));
const kept = [];
for (const block of blocks(css)) {
  if (/^@(media|supports|container)\b/.test(block)) {
    const open = block.indexOf('{');
    const inner = blocks(block.slice(open + 1, -1)).filter(touches);
    if (inner.length)
      kept.push(`${block.slice(0, open).trim()} {\n${inner.map((r) => `  ${r}`).join('\n')}\n}`);
  } else if (!block.startsWith('@') && touches(block)) kept.push(block);
}
const keptText = kept.join('\n');
const keyframes = blocks(css).filter((b) => {
  const name = /^@(?:-webkit-)?keyframes\s+([\w-]+)/.exec(b)?.[1];
  return name && new RegExp(`\\b${name}\\b`).test(keptText);
});
const renamedCss = [...kept, ...keyframes]
  .join('\n')
  .replace(/\[_nghost-ng-(c\d+)\]/g, (_m, id) => `[data-h-${nameOf(id)}]`)
  .replace(/\[_ngcontent-ng-(c\d+)\]/g, (_m, id) => `[data-c-${nameOf(id)}]`);
if (/_ng(content|host)-/.test(renamedCss))
  fail('an encapsulation selector was left over in the CSS');

// ---------- responsive charts ----------
// The snapshot draws its charts at a fixed plot height and stretches the SVGs with preserveAspectRatio="none", which also
// stretches the strokes; these rules (appended, same specificity as the snapshot's so they win by order) make the plots follow
// the width of their card.
const RESPONSIVE_CHARTS = `
/* responsive charts (added by sync-sales-dashboard.mjs) */
ts-db-card, ts-db-frame, .sec > * { min-width: 0; }
.plot[data-c-db-line-chart], .plot[data-c-db-multi-line] { height: clamp(150px, 20vw, var(--plot-h, 220px)); }
.vb-plot[data-c-db-bar-chart], .plot[data-c-db-pair-bars] { height: clamp(140px, 18vw, var(--plot-h, 200px)); }
.vb-b[data-c-db-bar-chart] { max-width: none; }
/* a frame holding a single card fills its width (the snapshot reserves --vis-in slots even when only one card is in it) */
.fr-track[data-c-db-frame]:not(:has(> :nth-child(2))) { grid-auto-columns: 100%; }
svg[data-c-db-line-chart], svg[data-c-db-multi-line], svg[data-c-db-trend-card] { max-width: 100%; }
svg[data-c-db-line-chart] :is(path, polyline, line), svg[data-c-db-multi-line] :is(path, polyline, line), svg[data-c-db-trend-card] :is(path, polyline, line) { vector-effect: non-scaling-stroke; }
svg[data-c-db-geo-map] { display: block; width: 100%; height: auto; max-width: 100%; }
.ring[data-c-db-donut] { width: min(100%, clamp(150px, 18vw, 210px)); }
@media (max-width: 900px) {
  .vb-plot[data-c-db-bar-chart], .plot[data-c-db-pair-bars], .vb-x[data-c-db-bar-chart] { gap: 4px; }
  .vb-b[data-c-db-bar-chart] { width: 80%; }
}
@media (max-width: 560px) {
  .vb-v[data-c-db-bar-chart] { font-size: 10px; }
  .vb-x[data-c-db-bar-chart] span[data-c-db-bar-chart] { font-size: 10px; }
  .lg-r[data-c-db-donut] { grid-template-columns: 10px minmax(0px, 1fr) 44px; }
  .lg-v[data-c-db-donut] { display: none; }
  .hb-row[data-c-db-hbar-list], .hb-row.has-pct[data-c-db-hbar-list] { grid-template-columns: minmax(64px, 34%) minmax(0px, 1fr) auto; }
  .hb-p[data-c-db-hbar-list] { display: none; }
}`;

// ---------- write ----------
mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'sales-dashboard.html'), template, 'utf8');
writeFileSync(join(out, 'sales-dashboard.css'), `/* ${HEADER} */\n${renamedCss}\n`, 'utf8');
console.log(
  `[sales-dashboard:sync] components ${names.size} · html ${(template.length / 1024).toFixed(0)} KB · css rules ${kept.length}` +
    ` + keyframes ${keyframes.length} (${(renamedCss.length / 1024).toFixed(0)} KB)`,
);
