#!/usr/bin/env node
/**
 * Regenerates the Lead detail page ("รายละเอียด Lead", route /crm/opportunities/:opportunityId) from the Java original so the two can never drift
 * while both exist:
 *
 *   npm run opportunity-detail:sync        (Java project = ../triple_sale_main, or set TS_JAVA_ROOT)
 *
 *   Java  web/pages/lead_detail.xhtml                 markup    ->  src/app/features/opportunity-detail/opportunity-detail.html   (+ the markup of every modal)
 *   Java  web/css/lead_detail.css, lead_detail_modal.css, the <style> of the modals
 *                                                     ->  src/app/features/opportunity-detail/opportunity-detail.scss (+ opportunity-detail-modal.scss)
 *   Java  the 12 <script> blocks (page + 11 modals)    ->  src/app/features/opportunity-detail/opportunity-detail.engine.ts
 *   Java  web/resources/js/attach_file_types.js        ->  public/assets/java-js/attach_file_types.js   (byte for byte)
 *   Java  web/images/** (the ones the page names)      ->  public/assets/images/**             (byte for byte)
 *
 * The page is the biggest of the system (7.9k lines, a 457 KB script), so the generator is built in LAYERS, each one a section below:
 *   1. sources      the Facelets structure: ui:define, ui:include expansion (the modals), split into markup / <style> / <script>
 *   2. markup       Facelets markup -> Angular template (messages, the one EL value, image paths, the one link)
 *   3. css          the page stylesheets + the stylesheets of the modals, theme / font-step / image-path swaps, dark_mode.css port
 *   4. scripts      EL -> env.*, one list of swaps for the environment (fetch / navigation / storage / timers / listeners)
 *   5. engine       the page script + the modal scripts as ONE function startOpportunityDetail(env) that returns destroy()
 *   6. assets       images / helper script the page names
 *
 * The Java files are only READ. The outputs carry a "GENERATED" header — change this script (the swap() lists / the adaptation block),
 * never the output. A swap() that no longer matches stops the run on purpose: the original changed in a place the port depends on.
 *
 * components/work_modal.xhtml (the shared appointment / task modal, ui:param page=lead_detail) comes from the shared generator
 * tools/lib/work-modal.mjs (workModalPieces): its markup, <style> blocks and script are put where Facelets includes the file.
 */
