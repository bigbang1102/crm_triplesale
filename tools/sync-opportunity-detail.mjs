  const missing = new Set();
  for (const n of names) {
    // every folder that has the file: the page names a folder in one string and the file in another ('../images/lead/' + 'fi_tag_note_gray.svg')
    const dirs = DIRS.filter((d) => existsSync(join(java, 'images', d, n)));
    if (!dirs.length) {
      missing.add(n);
      continue;
    }
    for (const dir of dirs) {
      const dest = join(root, 'public/assets/images', dir);
      mkdirSync(dest, { recursive: true });
      copyFileSync(join(java, 'images', dir, n), join(dest, n));
      copied++;
    }
  }
  // a name that is not a file of web/images/ is something else (resources/…, an icon font) — list the ones that look like images of the page
  const looksLikeImage = [...missing].filter((n) => /^(fi_|image_|default_avatar|external-link|Calendar)/.test(n));
