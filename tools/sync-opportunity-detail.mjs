function applySwaps(name, text) {
  for (const s of SWAPS) {
    if (s.where !== '*' && s.where !== name) continue;
    try {
      if (s.kind === 'one') text = swapIn(text, `${name}: ${s.why}`, s.find, s.repl);
      else if (s.kind === 'all') text = swapAllIn(text, `${name}: ${s.why}`, s.find, s.repl, s.count);
      else {
        let n = 0;
        text = text.replace(s.re, (...a) => (n++, typeof s.repl === 'function' ? s.repl(...a) : s.repl.replace(/\$(\d)/g, (_m, d) => a[Number(d)] ?? '')));
        (s.counted ??= {})[name] = n;
      }
    } catch (e) {
      throw e;
    }
  }
  return text;
}
function checkRegexCounts() {
  for (const s of SWAPS) {
    if (s.kind !== 're' || s.count == null) continue;
    const total = Object.values(s.counted ?? {}).reduce((a, b) => a + b, 0);
    if (total !== s.count) throw new Error(`swap "${s.why}": found ${total}x, expected ${s.count}x`);
  }
  for (const s of SWAPS) {
    if (s.kind === 're' && !Object.values(s.counted ?? {}).some((n) => n > 0)) throw new Error(`swap "${s.why}": NOT FOUND — the original changed`);
    if ((s.kind === 'one' || s.kind === 'all') && s.where === '*') continue;
  }
}

/** messages: placeholders -> env.t('k') spliced into the string literal that holds them */
async function spliceMessages(name, code) {
  const ts = (await import('typescript')).default;
  const sf = ts.createSourceFile(`${name}.js`, code, ts.ScriptTarget.ES2022, true, ts.ScriptKind.JS);
  if (sf.parseDiagnostics.length) {
    const d = sf.parseDiagnostics[0];
    const line = code.slice(0, d.start).split('\n').length;
    throw new Error(`${name}: the script does not parse (line ${line}): ${ts.flattenDiagnosticMessageText(d.messageText, '\n')}`);
  }
  const edits = [];
  const visit = (n) => {
    if ((ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n)) && /@@[\w.]+@@/.test(n.getText(sf))) {
      const raw = n.getText(sf);
      const q = raw[0];
      const inner = raw.slice(1, -1);
      const parts = inner.split(/@@([\w.]+)@@/); // [text, key, text, key, text …]
      const terms = [];
      parts.forEach((p, i) => {
        if (i % 2) terms.push(`env.t(${JSON.stringify(p)})`);
        else if (p !== '') terms.push(q + p + q);
      });
      const only = terms.length === 1 && parts.length === 3 && parts[0] === '' && parts[2] === '';
      edits.push({ from: n.getStart(sf), to: n.getEnd(), text: only ? terms[0] : `(${terms.length === 1 ? "'' + " + terms[0] : terms.join(' + ')})` });
      return;
    }
    ts.forEachChild(n, visit);
  };
  visit(sf);
  let outText = code;
  for (const e of edits.sort((a, b) => b.from - a.from)) outText = outText.slice(0, e.from) + e.text + outText.slice(e.to);
  return { text: outText, count: edits.length };
}

