#!/usr/bin/env node
/**
 * Regenerates the receipt form ("ใบรับเงิน", route /sales/receipts/new) from the Java original so the two can never drift while both
 * exist:
 *
 *   npm run receipt-form:sync          (Java project = ../triple_sale_main, or set TS_JAVA_ROOT)
 *
 *   Java  web/pages/sales_doc_rv.xhtml  <style> of "head"   ->  src/app/features/receipts/receipt-form.scss   (+ Angular adaptation block)
 *   Java  web/pages/sales_doc_rv.xhtml  markup of "content" ->  src/app/features/receipts/receipt-form.html
 *   Java  web/pages/sales_doc_rv.xhtml  <script>            ->  src/app/features/receipts/receipt-form.engine.ts
 *   Java  web/images/icon/{fi_file-o,fi_download,default_avatar}.svg  ->  public/assets/images/icon/   (byte for byte)
 *
 * The pieces every page of the menu group "งานขาย" shares (taking the Facelets page apart, the tab strip, EL inside JS strings) are in
 * tools/lib/sales-doc.mjs. The Java files are only READ. The outputs carry a "GENERATED" header — change this script (the swap() list),
 * never the output. A swap() that no longer matches stops the run on purpose: the original changed in a place the port depends on.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { javaLinkToRoute } from '../src/app/core/navigation/java-links.ts'; // (Node strips the types; the file has no Angular imports)
import { darkPort, editor, markupToTemplate, reader, undeclaredNames } from './lib/port.mjs';
import { adaptation, engineScaffold, ruleBody } from './lib/port-kit.mjs';
import { checkMessages, checkSaleTabs, elToEnv, msgKey, salesPage, stripIife } from './lib/sales-doc.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const javaRoot = resolve(process.env.TS_JAVA_ROOT ?? join(root, '..', 'triple_sale_main'));
const java = join(javaRoot, 'web');
const out = join(root, 'src/app/features/receipts');
mkdirSync(out, { recursive: true });

const read = reader(java);
const FILE = 'pages/sales_doc_rv.xhtml';
const GENERATED = `GENERATED by tools/sync-receipt-form.mjs from web/pages/sales_doc_rv.xhtml — do not edit; change the script and run \`npm run receipt-form:sync\`.`;
// the item picker panel is built by the script and appended to <body> (position: fixed under the toggle), so the global rules of the Java
// stylesheet stack must reach it there too: the scope is the host element AND that panel
const SCOPE = ':where(ts-receipt-form-view, .rv-item-panel)';
const th = JSON.parse(readFileSync(join(root, 'public/assets/i18n/th.json'), 'utf8'));
const en = JSON.parse(readFileSync(join(root, 'public/assets/i18n/en.json'), 'utf8'));

/* ================================================================================== the Facelets page */
const page = salesPage(read, FILE);
if (page.styles.length) throw new Error(`${FILE}: the content has an inline <style> (not expected)`);
if (page.headStyles.length !== 1) throw new Error(`${FILE}: expected exactly one <style> in the head, found ${page.headStyles.length}`);
const expectLinks = ['#{request.contextPath}/resources/support/drag_scroll.css?v=20260911a'];
if (JSON.stringify(page.headLinks) !== JSON.stringify(expectLinks)) throw new Error(`${FILE}: the stylesheets of the head changed: ${page.headLinks.join(' ')}`);
// drag_scroll.css is global in the Angular shell (styles/_drag-scroll.scss); drag_scroll.js is core/dom/drag-scroll.ts — the host starts it for these targets
if (page.headScripts.length !== 1 || !/resources\/support\/drag_scroll\.js/.test(page.headScripts[0].src) || page.headScripts[0].targets !== '.rv-table-wrap') {
  throw new Error(`${FILE}: the head scripts changed: ${JSON.stringify(page.headScripts)}`);
}
if (page.tabs.active !== 'rv') throw new Error(`${FILE}: the active tab is no longer "rv": ${page.tabs.active}`);
for (const n of checkSaleTabs(page.tabs, readFileSync(join(root, 'src/app/core/navigation/nav.config.ts'), 'utf8'), th)) console.warn('  ! top bar (shared file nav.config.ts, see INTEGRATION.md): ' + n);

/* ================================================================================== markup */
const markup = editor('sales_doc_rv.xhtml markup', page.markup.replace(/^\s+/, '').replace(/\s+$/, ''));
// the link back to the list is the route of this app (core/navigation/java-links.ts)
const back = javaLinkToRoute('sales_doc_rv_list.xhtml?navbar_menu=navbar_menu_sale');
if (back !== '/sales/receipts') throw new Error('java-links.ts: sales_doc_rv_list no longer maps to /sales/receipts: ' + back);
markup.swap('href="sales_doc_rv_list.xhtml?navbar_menu=navbar_menu_sale"', `href="${back}"`);
let tpl = markupToTemplate(markup.text, 'sales_doc_rv.xhtml markup');
tpl = tpl.replace(/^ {8}/gm, '').replace(/^\n+/, '');
writeFileSync(
  join(out, 'receipt-form.html'),
  `<!-- ${GENERATED}
     The markup of sales_doc_rv.xhtml (its stylesheet is receipt-form.scss); #{commonBean.msg[…]} -> t('…') · hasFeature(…) -> can('…') ·
     the link back to the list is its route · everything else is verbatim -->\n` + tpl.replace(/\s+$/, '\n'),
);
// byte-identical copies of the images the page shows (the mirror layout: web/images/<path> -> public/assets/images/<path>)
mkdirSync(join(root, 'public/assets/images/icon'), { recursive: true });
for (const f of ['fi_file-o.svg', 'fi_download.svg', 'default_avatar.svg']) copyFileSync(join(java, 'images/icon', f), join(root, 'public/assets/images/icon', f));

/* ================================================================================== stylesheet */
const css = editor('sales_doc_rv.xhtml style', page.headStyles[0].replace(/^\s*\n/, '').replace(/\s+$/, ''));
// the first two rules style elements of the Java template; the Angular shell has the same box: #crm_main_body_page
css.swap(
  `            #crm_main_body_page { padding: 0 !important; background: #F0F2FF !important; }
            .layout-main .layout-content { padding: 0 !important; }
`,
  `            /* (Java: #crm_main_body_page / .layout-main .layout-content — see the Angular adaptation block) */
`,
);
css.swapAll('body[data-theme="dark"]', "html[data-theme='dark']");
css.swapAll('var(--fs-adj,0px)', 'var(--ts-fs-adj,0px)');
if (/--fs-adj/.test(css.text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/--ts-fs-adj/g, ''))) throw new Error('sales_doc_rv.xhtml style: --fs-adj left over');

/* ================================================================================== engine */
const js = editor('sales_doc_rv.xhtml script', stripIife(page.pageScript, 'sales_doc_rv.xhtml script').replace(/^\n/, ''));

/* ---- environment: what Facelets / the URL / the browser gave the page ---- */
// the SweetAlert of template.xhtml (the real library, see the host)
{
  const before = js.text;
  js.text = js.text.replace(/if \(window\.swal\) \{\s*swal\((\{[^}]*\})\);\s*\}/, 'env.swal($1);');
  if (js.text === before) throw new Error('sales_doc_rv.xhtml script: toast() changed');
}
// the query string of the page address: ?leadId= · ?activityGroupId= · ?listMaterialId=
if ((js.text.match(/\blocation\.search\b/g) ?? []).length !== 3) throw new Error('sales_doc_rv.xhtml script: expected 3 reads of location.search');
js.text = js.text.replace(/\blocation\.search\b/g, 'env.search');
// images: web/images/<path> is assets/images/<path> here
js.swap(`var RV_AVATAR_DEF = '#{request.contextPath}/images/icon/default_avatar.svg';`, `var RV_AVATAR_DEF = 'assets/images/icon/default_avatar.svg';`);
if ((js.text.match(/\.\.\/images\/icon\//g) ?? []).length !== 2) throw new Error('sales_doc_rv.xhtml script: expected 2 images below ../images/icon/');
js.text = js.text.replace(/\.\.\/images\/icon\//g, 'assets/images/icon/');
// every message and the context path inside a string literal (found with the TypeScript parser)
const used = new Set();
js.text = await elToEnv(js.text, 'sales_doc_rv.xhtml script', (expr) => {
  const k = msgKey(expr);
  if (k) {
    used.add(k);
    return `env.t(${JSON.stringify(k)})`;
  }
  if (expr === 'request.contextPath') return 'env.ctx';
  throw new Error(`sales_doc_rv.xhtml script: EL not understood: #{${expr}}`);
});
checkMessages(used, th, en, 'sales_doc_rv.xhtml script');
js.text = js.text.replace(/var\(--fs-adj,0px\)/g, 'var(--ts-fs-adj,0px)');

/* ---- the BFF: the page called '../rvapi' / '../board/…' (relative to /pages/); the engine asks the host for '/rvapi' (below the context path) ---- */
js.swap(`var API = '../rvapi';`, `var API = '/rvapi';`);
if ((js.text.match(/'\.\.\/board\//g) ?? []).length !== 2) throw new Error('sales_doc_rv.xhtml script: expected 2 addresses below ../board/');
js.text = js.text.replace(/'\.\.\/board\//g, "'/board/");
js.text = js.text.replace(/(^|[^.\w$])fetch\(/gm, '$1env.fetch(');
// swal(…) -> env.swal(…) (confirmations, warnings: the real library)
js.text = js.text.replace(/(^|[^.\w$])swal\(/gm, '$1env.swal(');
// the way back to the list: location.href = 'sales_doc_rv_list.xhtml?…' -> the route of this app
js.swap(`window.location.href = 'sales_doc_rv_list.xhtml?navbar_menu=navbar_menu_sale';`, `env.navigate(${JSON.stringify(back)});`);

/* ---- global listeners and timers are registered through listen() / tmo() so that destroy() can remove them ---- */
js.text = js.text.replace(/\b(document|window)\.addEventListener\(/g, 'listen($1, ');
js.text = js.text.replace(/(^|[^.\w$])setTimeout\(/gm, '$1tmo(');

/* ---- nothing may reach the page address, the document cookies or global state the shell owns ---- */
{
  const code = js.text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '').replace(/\s\/\/[^\n'"]*$/gm, '');
  if (/#\{/.test(code)) throw new Error('receipt-form script: EL left over in code: ' + code.match(/.{0,40}#\{.{0,40}/)[0]);
  if (/\b(setInterval|XMLHttpRequest|localStorage|sessionStorage|document\.cookie|TS_PREF)\b/.test(code)) throw new Error('receipt-form script: unexpected timer / XHR / storage (add it to destroy() / the host)');
  const rest = code.match(/.{0,40}\b(window\.location|location\.(href|pathname|reload|search)|window\.open|\.face\b|\.xhtml\b).{0,40}/);
  if (rest) throw new Error('receipt-form script: a URL read / Java page link is left: ' + rest[0]);
  const bare = code.match(/(^|[^.\w$'"])(fetch|swal)\(/m);
  if (bare) throw new Error('receipt-form script: a bare fetch / swal call is left: ' + bare[0]);
  if (/\bon[a-z]+="/.test(tpl)) throw new Error('receipt-form markup: an inline handler appeared — export its function (see sync-dashboard.mjs HANDLERS_EXTRA)');
}

const scaffold = engineScaffold({
  header: `
 * Receipt form engine. ${GENERATED}
 *
 * The page script of the Java screen, same behaviour line by line: the customer picker (leads, with the prefill from a lead:
 * ?leadId= · ?activityGroupId= · ?listMaterialId=), the header fields, the line table with its item picker and the VAT / withholding
 * maths, the payment panel with the numpad dialog, the attachments tab (file types from the master data), the save pipeline
 * (validate → confirm → POST create → the result box) and the currency / branch masters.
 *
 * WHY it is imperative DOM code and not Angular components: the Java page draws its HTML from data as strings. Porting it 1:1 is what
 * guarantees the screen, texts and states are identical to the production system.
 * "@ts-nocheck": the source is ES5 written for a browser global scope; typing it would change it, not port it.
 *
 * What changed versus the Java file (all of it lives in tools/sync-receipt-form.mjs):
 *   - the environment is injected (ReceiptFormEnv): messages, permissions, fetch (the BFF contract of receipts-backend.ts), the query string
 *     of the address, navigation to the list, SweetAlert, the context path — in Java these were EL, the URL and globals;
 *   - the strip of tabs that sales_doc_tabs.xhtml injects into the Java top bar is drawn by the Angular shell (nav.config.ts);
 *   - the addresses '../rvapi…' / '../board/…' are '/rvapi…' / '/board/…' (below the context path); the images are below assets/images/;
 *   - global listeners and timers added through listen() / tmo(), the item picker panel the script appends to <body>, the object URLs of the
 *     attached files and the response guard are removed by the function returned from startReceiptForm().`,
  envType: 'ReceiptFormEnv',
  envBody: `  /** commonBean.msg['key'] in the active language */
  t: (key: string) => string;
  /** commonBean.hasFeature('A,B') of the signed-in user (OR of the keys) */
  can: (features: string) => boolean;
  /** the BFF contract of the page: /rvapi?action=…, /board/lead, /board/prospect, /board/prospect-list (see receipts-backend.ts) */
  fetch: (input: string, init?: RequestInit) => Promise<Response>;
  /** window.location.search of the page: "?leadId=…&activityGroupId=…&listMaterialId=…" (or "") */
  search: string;
  /** window.location.href = … : the route of this app */
  navigate: (route: string) => void;
  /** SweetAlert v2 (js/sweetalert/sweetalertv1.min.js) */
  swal: (options: Record<string, unknown>) => Promise<any>;
  /** #{request.contextPath}: where the BFF is ("" here) */
  ctx: string;`,
  fn: 'startReceiptForm',
  handlers: [],
  exported: [],
  cleanup: `    // what the script put outside its own DOM: the item picker panel on <body>, the object URLs of the attached files
    if (rvItemPanel && rvItemPanel.parentNode) { rvItemPanel.parentNode.removeChild(rvItemPanel); }
    attFiles.splice(0).forEach(function (f) { if (f && f.url) { try { URL.revokeObjectURL(f.url); } catch (e) { /* done already */ } } });
`,
});
const engineText = scaffold.header + scaffold.guard + js.text.replace(/\s+$/, '\n') + scaffold.footer();
const undeclared = await undeclaredNames(engineText.replace(/^\/\/ @ts-nocheck\n/, ''), []);
if (undeclared.length) throw new Error('receipt-form engine: names that are not declared (a ReferenceError in strict mode): ' + undeclared.join(', '));
writeFileSync(join(out, 'receipt-form.engine.ts'), engineText);

/* ================================================================================== stylesheet (written last: the dark port reads the script) */
const pageText = tpl + '\n' + css.text + '\n' + js.text;
const dark = darkPort(read('resources/support/dark_mode.css'), pageText, SCOPE, 1);
const dedent = (s) => s.replace(/^ {12}/gm, '').replace(/\s+$/, '\n');
const SHELL_BOX = `/* the two rules the stylesheet sets on the Java template's boxes (#crm_main_body_page, .layout-main .layout-content) — the Angular shell's content box has the same id */
#crm_main_body_page:has(.rv-root) { padding: 0 !important; background: #F0F2FF !important; }
`;
const adapted = adaptation({ read, scope: SCOPE, host: 'ts-receipt-form-view', text: tpl + '\n' + js.text });
// The item panel the script appends to <body> takes its text size and colour from the Java <body> there (13px, #191a1c; dark #E5E7EB) — the
// host element has them (adaptation block), the Angular <body> has other values: give the panel the host's.
const hostRule = /^ts-receipt-form-view \{ display: contents; font-size: ([^;]+); color: ([^;]+); \}$/m.exec(adapted);
const hostDark = /^html\[data-theme='dark'\] ts-receipt-form-view \{ color: ([^;]+); \}$/m.exec(adapted);
if (!hostRule || !hostDark) throw new Error('the host rule of adaptation() was not found — port-kit.mjs changed');
// project_root.css: \`[type="text"] { padding: 10px !important }\` reaches every text input of a Java page; the Angular shell limits it to
// ts-shell and the ods lists (styles/_base.scss), so the search field of the panel on <body> needs it too (same specificity as the original)
const TEXT_INPUT = ruleBody(read('css/project_root.css'), 'project_root.css', '[type="text"]');
const MOVED_BOXES = `/* the panel the script appends to <body>: the text defaults of the Java <body> */
.rv-item-panel { font-size: ${hostRule[1]}; color: ${hostRule[2]}; }
html[data-theme='dark'] .rv-item-panel { color: ${hostDark[1]}; }
/* project_root.css  [type="text"] — the search field of the panel is outside ts-shell, where the shell applies this rule */
:where(.rv-item-panel) [type="text"] { ${TEXT_INPUT} }
`;
writeFileSync(
  join(out, 'receipt-form.scss'),
  `/* Receipt form stylesheet. ${GENERATED}
   The <style> of sales_doc_rv.xhtml (ui:define "head"), copied verbatim, except:
     the two rules on #crm_main_body_page / .layout-main .layout-content -> Angular adaptation block
     body[data-theme="dark"] -> html[data-theme='dark']       (the Angular shell puts the theme on <html>; same specificity)
     --fs-adj                -> --ts-fs-adj                   (A A A font scale token of the Angular shell)
   Loaded with ViewEncapsulation.None: the engine writes HTML strings that need global selectors. */

` +
    adapted +
    SHELL_BOX +
    MOVED_BOXES +
    '\n' +
    dedent(css.text) +
    `\n/* ───── dark_mode.css of the Java app, scoped to the page (${dark.kept} rules that can match it, of ${dark.seen} selectors) ───── */\n${dark.css}\n`,
);

console.log(`Receipt form synced from ${java}: ${used.size} messages, ${dark.kept} dark rules; markup ${tpl.length} chars, css ${css.text.length}, script ${js.text.length}`);
