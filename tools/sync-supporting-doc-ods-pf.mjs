#!/usr/bin/env node
/**
 * Regenerates the PrimeFaces part of the Java "open down select" script for the supporting-document screens:
 *
 *   npm run supporting-doc-ods-pf:sync          (Java project = ../triple_sale_main, or set TS_JAVA_ROOT)
 *
 *   Java  web/resources/js/open_down_select.js   ->  src/app/shared/primefaces/ods-pf.ts
 *
 * Why: the Java template loads open_down_select.js on every page, and besides its own drop-down / calendar it RE-SKINS and PATCHES the PrimeFaces widgets
 * of the page — the select panel always opens below its box (position: fixed) and closes on scroll, the datepicker gets the month / year drop-downs and the
 * design's colours, a PrimeFaces select without a filter gets a search box. The shell's port of that script (core/dom/open-down-select.ts, generated by
 * sync-java-dom.mjs) leaves exactly these parts out ("no PrimeFaces widgets in Angular"); the supporting-document screens have them, so they get them
 * here, taken from the same file: the CSS of the widgets (+ its dark rules), the helpers (pfTrack / odsPfHideOpen / pfWrapShowHide), odsPatchPF,
 * odsPfSearch, odsEnhancePfNav / odsEnhancePfYear. `window.odsEnhance` (the month select becomes an ODS drop-down) is the shell's own.
 * Output carries a "GENERATED" header — change this script, never the output.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const javaRoot = resolve(process.env.TS_JAVA_ROOT ?? join(root, '..', 'triple_sale_main'));
const src = readFileSync(join(javaRoot, 'web/resources/js/open_down_select.js'), 'utf8').replace(/\r\n/g, '\n');

/** the text from `header` to the end of the `{ … }` block that follows it (strings and comments skipped) */
function block(header, what = header) {
  const at = src.indexOf(header);
  if (at < 0) throw new Error(`open_down_select.js: ${what} not found — the original changed`);
  if (src.indexOf(header, at + 1) >= 0) throw new Error(`open_down_select.js: ${what} is ambiguous`);
  let i = src.indexOf('{', at + header.length - 1);
  const open = i;
  let depth = 0;
  for (; i < src.length; i++) {
    const c = src[i];
    if (c === '"' || c === "'") {
      for (i++; i < src.length && src[i] !== c; i++) if (src[i] === '\\') i++;
    } else if (c === '/' && src[i + 1] === '*') i = src.indexOf('*/', i) + 1;
    else if (c === '/' && src[i + 1] === '/') i = src.indexOf('\n', i);
    else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) break;
  }
  if (depth) throw new Error(`open_down_select.js: unbalanced block after ${what}`);
  void open;
  return src.slice(at, i + 1);
}

/* ---- the CSS: the pieces of the string of the script that name the PrimeFaces widgets, from the calendar re-skin to the end of the string */
const cssFrom = src.indexOf('/* ═ reskin ปฏิทิน PrimeFaces (p:calendar / p:datePicker) ให้เข้าชุดดีไซน์ ═ */');
const cssTo = src.indexOf('function injectCss()');
if (cssFrom < 0 || cssTo < 0) throw new Error('open_down_select.js: the CSS of the PrimeFaces widgets was not found');
const pieces = [...src.slice(cssFrom, cssTo).matchAll(/\+\s*("(?:[^"\\]|\\.)*")/g)].map((m) => new Function(`return ${m[1]}`)());
// (every piece of the range: a rule is written over several `+ "…"` lines, the continuation lines name no widget — a filter per piece would cut rules in two)
const pfCss = pieces;
const filterCss = [...src.matchAll(/\+\s*("(?:[^"\\]|\\.)*ods-pf-filter(?:[^"\\]|\\.)*")/g)].map((m) => new Function(`return ${m[1]}`)());
// the pieces between the calendar re-skin and the end also hold ODS's own dark rules; the datepicker title buttons (`.ui-datepicker-title .ods-btn`) are PrimeFaces' side
if (pfCss.length < 30 || !pfCss.some((p) => /\.ui-selectonemenu\{/.test(p)) || !pfCss.some((p) => /\.ui-datepicker\{/.test(p))) throw new Error(`open_down_select.js: the CSS of the PrimeFaces widgets was not found (${pfCss.length} pieces)`);
if ((css0 => css0.split('{').length === css0.split('}').length)(pfCss.join('')) === false) throw new Error('open_down_select.js: the CSS of the PrimeFaces widgets is not balanced');
const css = [...filterCss, ...pfCss]
  .join('')
  .replace(/body\[data-theme=dark\]/g, "html[data-theme='dark']")
  .replace(/--fs-adj/g, '--ts-fs-adj');
if (/#\{|body\[data-theme/.test(css)) throw new Error('the CSS of the PrimeFaces widgets: a theme selector / EL left over');

/* ---- the code */
const helpers = block('    var pfOpen = [];', 'pfOpen');
void helpers;
const pfOpenDecl = `    var pfOpen = [];
${src.slice(src.indexOf('    function pfTrack(w)'), src.indexOf('    function pfTrack(w)') + src.slice(src.indexOf('    function pfTrack(w)')).indexOf('\n'))}`;
const FUNCS = [
  block('    function pfUntrack(w)', 'pfUntrack'),
  block('    function odsPfHideOpen()', 'odsPfHideOpen'),
  block('    function pfWrapShowHide(proto)', 'pfWrapShowHide'),
  block('    var pfPatched = false;\n    function odsPatchPF()', 'odsPatchPF').replace('    var pfPatched = false;\n', ''),
  block('    function odsPfSearch(widget)', 'odsPfSearch'),
  block('    function odsEnhancePfYear(inp)', 'odsEnhancePfYear'),
  block('    window.odsEnhancePfNav = function (root)', 'odsEnhancePfNav'),
];
const pfTrackLine = '    function pfTrack(w) { if (pfOpen.indexOf(w) === -1) { pfOpen.push(w); } }';
if (!src.includes(pfTrackLine)) throw new Error('open_down_select.js: pfTrack changed');
const SCROLL_KEEP = '.ods-list,.ui-selectonemenu-panel,.ui-selectcheckboxmenu-panel,.ui-autocomplete-panel,.ld2-prod-dd';
if (!src.includes('var SCROLL_KEEP_SEL = ".ods-list,.ui-selectonemenu-panel,.ui-selectcheckboxmenu-panel,"\n        + ".ui-autocomplete-panel,.ld2-prod-dd";')) throw new Error('open_down_select.js: SCROLL_KEEP_SEL changed');

let code = [pfOpenDecl.split('\n')[0], pfTrackLine, ...FUNCS].join('\n\n');
// what the script's closure had around these parts: injectCss() (its own <style>), odsText(), closeAll(), odsAutoId
code = code.replace(/\binjectCss\(\)/g, 'injectPfCss()').replace(/odsText\("search"\)/g, 'odsText("search")');
code = code.replace('window.odsEnhancePfNav = function (root)', 'var odsEnhancePfNav = function (root)');
code = code.replace(/window\.odsEnhance\(/g, 'window.odsEnhance(');
if (!/odsAutoId/.test(code) || !/closeAll\(\)/.test(code)) throw new Error('the PrimeFaces parts no longer use odsAutoId / closeAll: re-read the original');
// the panel of a select must not leave the screen: Java kept at least 140px for the list and 64px under the box, but the panel also has its search box (~50px) and
// borders, so under a box near the bottom of the screen it ran past the edge. Here the room under the box is measured with the panel's own chrome, and when it is too
// small (and there is more above) the panel opens ABOVE the box. (Not in Java.)
{
  const re = /var room = Math\.max\(140, window\.innerHeight - r\.bottom - 64\);\s*var w = \(this\.itemsWrapper && this\.itemsWrapper\.length\) \? this\.itemsWrapper : this\.panel\.find\("\.ui-selectonemenu-items-wrapper"\);\s*if \(w && w\.length\) \{ w\.css\("max-height", room \+ "px"\); \}/;
  if (!re.test(code)) throw new Error('open_down_select.js changed — the room of the select panel');
  code = code.replace(re, () => `var w = (this.itemsWrapper && this.itemsWrapper.length) ? this.itemsWrapper : this.panel.find(".ui-selectonemenu-items-wrapper");
              if (w && w.length) {
                  w.css("max-height", "none");
                  var chrome = Math.max(0, panel.offsetHeight - w[0].offsetHeight);
                  var below = window.innerHeight - r.bottom - 12, above = r.top - 12;
                  var want = Math.min(w[0].scrollHeight, 320);
                  var up = (below - chrome < Math.min(want, 200)) && above > below;
                  var room = Math.max(96, (up ? above : below) - chrome - 4);
                  w.css("max-height", Math.min(320, room) + "px");
                  if (up) { panel.style.top = Math.max(8, Math.round(r.top - 4 - panel.offsetHeight)) + "px"; }
              }`);
}
code = code.replace(/(^|\n)    /g, '$1  ');

const out = `// @ts-nocheck
/* eslint-disable */
/**
 * The PrimeFaces part of open_down_select.js. GENERATED by tools/sync-supporting-doc-ods-pf.mjs from web/resources/js/open_down_select.js — do not edit; change
 * the script and run \`npm run supporting-doc-ods-pf:sync\`.
 *
 * The Java script re-skins and patches the PrimeFaces widgets of every page it is loaded on; the shell's port leaves that out (no PrimeFaces widgets
 * elsewhere in the app), the supporting-document screens start it here: the select panel opens below its box and closes on scroll, the datepicker has the
 * month / year drop-downs and the design's colours, the colours of the select. Same code as Java (ES5, hence "@ts-nocheck"); what changed:
 *   - injectCss() writes its own <style id="odsPfCss"> (the shell's ODS has its own);
 *   - the window / document listeners (resize, scroll, the observer for a calendar drawn later) are added by startOdsPf() and removed by its destroy();
 *   - body[data-theme=dark] is html[data-theme='dark'], --fs-adj is --ts-fs-adj;
 *   - odsText("search") is env.search; closeAll() is the one of the shell's ODS lists (.ods-list.open / .ods-btn.open).
 */

const PF_CSS = ${JSON.stringify(css)};

export interface OdsPfEnv {
  /** the placeholder of the search box of a select without a filter (label.ods.search) */
  search: string;
}

// the patches go on the prototypes of the widgets once for the page's life (odsPatchPF guards itself with this)
let pfPatched = false;

export function startOdsPf(env: OdsPfEnv): () => void {
  var disposers: (() => void)[] = [];
  var odsAutoId = 0;
  function odsText(key) { return key === 'search' ? env.search : ''; }
  function injectPfCss() {
    if (document.getElementById('odsPfCss')) { return; }
    var st = document.createElement('style');
    st.id = 'odsPfCss';
    st.textContent = PF_CSS;
    document.head.appendChild(st);
  }
  function closeAll() {
    Array.prototype.forEach.call(document.querySelectorAll('.ods-list.open'), function (l) { l.classList.remove('open'); });
    Array.prototype.forEach.call(document.querySelectorAll('.ods-btn.open'), function (b) { b.classList.remove('open'); });
  }
${code}

  function closeAllViewportAnchored() { closeAll(); odsPfHideOpen(); }
  var SCROLL_KEEP_SEL = '${SCROLL_KEEP}';
  function onScroll(e) {
    if (e.target && e.target.closest && e.target.closest(SCROLL_KEEP_SEL)) { return; }
    closeAllViewportAnchored();
  }
  window.addEventListener('resize', closeAllViewportAnchored);
  window.addEventListener('scroll', onScroll, true);
  disposers.push(function () { window.removeEventListener('resize', closeAllViewportAnchored); window.removeEventListener('scroll', onScroll, true); });

  // boot(): the style, the patches, the calendars that are there; and the ones drawn later (the datepicker header is built by PrimeFaces when it opens)
  injectPfCss();
  odsPatchPF();
  odsEnhancePfNav(document);
  var pend = null;
  var observer = new MutationObserver(function (muts) {
    for (var i = 0; i < muts.length; i++) {
      var add = muts[i].addedNodes;
      for (var j = 0; j < add.length; j++) {
        var n = add[j];
        if (n.nodeType === 1 && (n.tagName === 'SELECT' || n.tagName === 'INPUT' || (n.querySelector && n.querySelector('select,input')))) {
          if (!pend) { pend = setTimeout(function () { pend = null; odsEnhancePfNav(document); }, 80); }
          return;
        }
      }
    }
  });
  observer.observe(document.body, { childList: true, subtree: true });
  disposers.push(function () { observer.disconnect(); if (pend) { clearTimeout(pend); } });

  return function destroy() {
    disposers.splice(0).forEach(function (d) { d(); });
    var st = document.getElementById('odsPfCss');
    if (st) { st.remove(); }
  };
}
`;
writeFileSync(join(root, 'src/app/shared/primefaces/ods-pf.ts'), out);
console.log(`ODS PrimeFaces part synced from ${join(javaRoot, 'web/resources/js/open_down_select.js')}: ${pfCss.length + filterCss.length} CSS pieces (${css.length} bytes), ${FUNCS.length + 1} functions`);
