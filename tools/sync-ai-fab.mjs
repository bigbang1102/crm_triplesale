js.text = js.text.replace(/(^|[^.\w$])setTimeout\(/gm, '$1tmo(');
if (/\b(setInterval|XMLHttpRequest|localStorage\.clear)\b/.test(js.text)) throw new Error('ai_menu.xhtml script: unexpected timer / XHR (add it to destroy())');
if (/#\{/.test(js.text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, ''))) throw new Error('ai_menu.xhtml script: EL left over in code');
