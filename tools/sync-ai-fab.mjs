#!/usr/bin/env node
/**
 * Regenerates the floating AI button (speed-dial + "สอบถามการใช้งาน" help assistant) from the Java original so the two
 * can never drift while both exist:
 *
 *   npm run ai-fab:sync          (Java project = ../triple_sale_main, or set TS_JAVA_ROOT)
 *
 *   Java  web/WEB-INF/pages/ai_menu.xhtml  <style>    ->  src/app/layout/ai-fab/ai-fab.scss    (+ Angular adaptation block)
 *   Java  web/WEB-INF/pages/ai_menu.xhtml  markup     ->  src/app/layout/ai-fab/ai-fab.html
 *   Java  web/WEB-INF/pages/ai_menu.xhtml  <script>   ->  src/app/layout/ai-fab/ai-fab.engine.ts
 *   Java  web/resources/mock/ai_menu.json             ->  public/assets/ai-menu.json            (the menu items)
 *
 * template.xhtml includes ai_menu.xhtml once, outside .layout-wrapper, for every signed-in page; here the Shell hosts it
 * (layout/ai-fab/ai-fab.ts). The Java files are only READ. The outputs carry a "GENERATED" header — change this script,
 * never the output. A swap() that no longer matches stops the run on purpose.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { between, darkPort, editor, markupToTemplate, reader } from './lib/port.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const java = resolve(process.env.TS_JAVA_ROOT ?? join(root, '..', 'triple_sale_main'), 'web');
const out = join(root, 'src/app/layout/ai-fab');
mkdirSync(out, { recursive: true });

const read = reader(java);
const FROM = 'web/WEB-INF/pages/ai_menu.xhtml';
const GENERATED = `GENERATED by tools/sync-ai-fab.mjs from ${FROM} — do not edit; change the script and run \`npm run ai-fab:sync\`.`;
const xhtml = read('WEB-INF/pages/ai_menu.xhtml');
const SCOPE = ':where(.ai-fab-root, .ai-fab-toast, .ai-help)';

/* ================================================================================== stylesheet */
const css = editor('ai_menu.xhtml style', between(xhtml, 'ai_menu.xhtml', '<style>', '</style>'));
css.swapAll('body[data-theme="dark"]', "html[data-theme='dark']");
css.swapAll('var(--fs-adj,0px)', 'var(--ts-fs-adj,0px)');
