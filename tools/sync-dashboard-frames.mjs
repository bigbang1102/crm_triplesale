#!/usr/bin/env node
/**
 * Regenerates the two iframe documents of the Dashboard from the Java originals:
 *
 *   npm run dashboard:sync          (runs sync-dashboard.mjs and this one; Java project = ../triple_sale_main or TS_JAVA_ROOT)
 *
 *   Java  web/pages/dashboard_calendar_frame.xhtml  ->  src/app/features/dashboard/frames/calendar-frame.generated.ts   (tab ปฏิทินงาน)
 *   Java  web/pages/dashboard_kpi_frame.xhtml       ->  src/app/features/dashboard/frames/kpi-frame.generated.ts        (tab KPI-EventMovement)
 *   Java  web/resources/js/{input_guard,no_autofill}.js  ->  public/assets/js/frames/   (the frames load them like the Java page did)
 *
 * In Java the page fetched each frame as HTML text (JSF rendered its #{…} values on the server) and put it into the iframe's
 * `srcdoc`. Each output module therefore exports one function that returns that same text: the document verbatim, the EL
 * values passed in. The script inside the frame runs unchanged — the only edits are the ones the Angular shell needs:
 *   - the theme is read from <html data-theme> of the parent and from localStorage "ts.theme" (Java: <body>, "app-theme");
 *   - the resource URLs (input_guard.js / no_autofill.js) point to public/assets/js/frames/;
 *   - a `fetch` bridge at the top of <head> sends the frame's API calls (the dashboard service and the /dashboard BFF paths)
 *     through the parent page (window.parent.__tsDashFetch): the mock backend in dev, the bearer-token client in live mode.
 *
 * The Java files are only READ. A swap() that no longer matches stops the run on purpose.
 */
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { editor, reader } from './lib/port.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const javaRoot = resolve(process.env.TS_JAVA_ROOT ?? join(root, '..', 'triple_sale_main'), 'web');
const out = join(root, 'src/app/features/dashboard/frames');
const assets = join(root, 'public/assets/js/frames');
mkdirSync(out, { recursive: true });
mkdirSync(assets, { recursive: true });
const read = reader(javaRoot);

/** scripts the frames load (Java: <script src="#{request.contextPath}/resources/js/…">) */
for (const f of ['input_guard.js', 'no_autofill.js']) copyFileSync(join(javaRoot, 'resources/js', f), join(assets, f));

const GENERATED = (from) => `GENERATED by tools/sync-dashboard-frames.mjs from web/pages/${from} — do not edit; change the script and run \`npm run dashboard:sync\`.`;

/** the fetch bridge (see the header). `gold` is a JS expression: the API base (calendar) or the placeholder the engine fills (kpi) */
const bridge = (gold) => `
  <script>
  /* Angular shell: this document's API calls go through the parent page (mock backend / bearer token) */
  (function () {
    var G = ${gold};
    var P = window.parent;
    var raw = window.fetch ? window.fetch.bind(window) : null;
    function mine(u) { return typeof u === 'string' && (u.indexOf(G) === 0 || u.indexOf('/dashboard/') === 0); }
    window.fetch = function (input, init) {
      var u = typeof input === 'string' ? input : ((input && input.url) || '');
      try { if (mine(u) && P && typeof P.__tsDashFetch === 'function') { return P.__tsDashFetch(u, init); } } catch (e) { /* cross-origin parent: use the network */ }
      return raw(input, init);
    };
  })();
  </script>`;

/**
 * One frame: swap the shell edits, then cut the document at every EL value so the module can put them back
 *   values: { 'el expression': ['name of the value', 'how it is written (raw | js | json)'] }
 */
function frame({ file, exportName, interfaceName, swaps, el, goldExpr, valuesDoc }) {
  const doc = editor(file, read(`pages/${file}`));
  doc.swap('<?xml version="1.0" encoding="UTF-8" ?>\n', '');
  doc.swap('<html xmlns="http://www.w3.org/1999/xhtml" lang="th">', '<html lang="th">');
  doc.swap(/<meta charset="UTF-8" \/>/.exec(doc.text)[0], '<meta charset="UTF-8" />' + bridge(goldExpr));
  for (const [a, b] of swaps) doc.swap(a, b);

  // cut at each EL value
  let rest = doc.text;
  const parts = [];
  const used = new Set();
  const re = /#\{([^}]+)\}|@@([A-Za-z]+)@@/g;
  let last = 0;
  for (const m of rest.matchAll(re)) {
    const def = el[m[1] ?? '@' + m[2]];
    if (!def) throw new Error(`${file}: unexpected EL ${m[0]} (add it to the generator)`);
    parts.push(JSON.stringify(rest.slice(last, m.index)));
    parts.push(`${def.how}(v.${def.name})`);
    used.add(def.name);
    last = m.index + m[0].length;
  }
  parts.push(JSON.stringify(rest.slice(last)));
  for (const [expr, def] of Object.entries(el)) if (!used.has(def.name)) throw new Error(`${file}: the EL #{${expr}} is no longer in the original`);

  const fields = [...new Set(Object.values(el).map((d) => d.name))];
  const ts = `// @ts-nocheck
/* eslint-disable */
/**
 * ${GENERATED(file)}
 *
 * ${valuesDoc}
 */

/** a JSON value written into a <script> element or a JS expression: "<" can never close the element */
const json = (s: string): string => String(s ?? '').replace(/</g, '\\\\u003c');
/** a text written into a '…' JS string */
const js = (s: string): string => String(s ?? '').replace(/[\\\\'\\r\\n<]/g, (c) => '\\\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
/** a plain text */
const raw = (s: string): string => String(s ?? '');

export interface ${interfaceName} {
${fields.map((f) => `  ${f}: string;`).join('\n')}
}

export function ${exportName}(v: ${interfaceName}): string {
  return [
${parts.map((p) => `    ${p},`).join('\n')}
  ].join('');
}
`;
  writeFileSync(join(out, file.replace('dashboard_', '').replace('_frame.xhtml', '-frame.generated.ts')), ts);
  return { fields: fields.length, chars: doc.text.length };
}

const THEME = [
  ['return window.parent.document.body;', 'return window.parent.document.documentElement;'],
  [`localStorage.getItem('app-theme')`, `localStorage.getItem('ts.theme')`],
];

const cal = frame({
  file: 'dashboard_calendar_frame.xhtml',
  exportName: 'calendarFrameHtml',
  interfaceName: 'CalendarFrameValues',
  goldExpr: `'@@goldApi@@'`,
  swaps: [
    ...THEME,
    [`<script src="#{request.contextPath}/resources/js/input_guard.js?v=20260826a"></script>`, `<script src="/assets/js/frames/input_guard.js?v=20260826a"></script>`],
  ],
  el: {
    'calendarDashboardView.calendarDataJson': { name: 'calendarDataJson', how: 'json' },
    'sessionScope.ss_branch_code': { name: 'ggwBranch', how: 'js' },
    'request.contextPath': { name: 'ctx', how: 'js' },
    '@goldApi': { name: 'goldApi', how: 'js' },
    'calendarDashboardView.calendarApiUrl': { name: 'calendarApiUrl', how: 'raw' },
    'calendarDashboardView.employeeCode': { name: 'employeeCode', how: 'raw' },
    'calendarDashboardView.myTaskListJson': { name: 'myTaskListJson', how: 'json' },
    'calendarDashboardView.calendarTaskCreateUrl': { name: 'calendarTaskCreateUrl', how: 'raw' },
    'calendarDashboardView.myCalendarListJson': { name: 'myCalendarListJson', how: 'json' },
    'calendarDashboardView.myTaskCalendarListJson': { name: 'myTaskCalendarListJson', how: 'json' },
  },
  valuesDoc: `The values are what CalendarDashboardView (the Java bean) rendered into the page: the calendar events of the month, the
 * calendar / task API addresses, the signed-in employee and the lists of the sidebar. \`ctx\` = #{request.contextPath}.`,
});

const kpi = frame({
  file: 'dashboard_kpi_frame.xhtml',
  exportName: 'kpiFrameHtml',
  interfaceName: 'KpiFrameValues',
  // the dashboard fills __GOLDAPI__ / __GGW_BRANCH__ in this text when it puts it into the iframe (dashboard.engine.ts)
  goldExpr: `'__GOLDAPI__'`,
  swaps: [
    ...THEME,
    [`<script src="#{request.contextPath}/resources/js/no_autofill.js?v=20260825b"></script>`, `<script src="/assets/js/frames/no_autofill.js?v=20260825b"></script>`],
    [`<script src="#{request.contextPath}/resources/js/input_guard.js?v=20260826a"></script>`, `<script src="/assets/js/frames/input_guard.js?v=20260826a"></script>`],
  ],
  el: {
    'calendarDashboardView.kpiListDataJson': { name: 'kpiListDataJson', how: 'json' },
  },
  valuesDoc: `The value is what CalendarDashboardView.getKpiListDataJson() rendered: { columns, statusOptions, records, total, masters }.
 * "__GOLDAPI__" and "__GGW_BRANCH__" stay in the text: the dashboard replaces them when it puts the document into the iframe.`,
});

console.log(`Dashboard frames synced from ${javaRoot}: calendar ${cal.chars} chars / ${cal.fields} values, kpi ${kpi.chars} chars / ${kpi.fields} value`);
