const noEl = (text, what) => {
  const m = text.replace(/\/\*[\s\S]*?\*\//g, '').match(/.{0,50}#\{.{0,50}/);
  if (m) throw new Error(`${what}: EL left over: ${m[0]}`);
};
/** a syntax error in generated code stops the run (the TypeScript parser, no type check) */
async function syntaxCheck(code, what) {
  const ts = (await import('typescript')).default;
  const r = ts.transpileModule(code, { reportDiagnostics: true, compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } });
  if (r.diagnostics?.length) {
    const d = r.diagnostics[0];
    const line = code.slice(0, d.start ?? 0).split('\n').length;
    throw new Error(`${what}: syntax error line ${line}: ${ts.flattenDiagnosticMessageText(d.messageText, '\n')}`);
  }
}

