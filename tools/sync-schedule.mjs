    // Java wrote the text into a '…' string / an attribute as it was: a quote, a backslash or a line break would break the page there too
    if (/['"\\\n\r]/.test(v)) throw new Error(`message ${k} (${lang}) contains a character that is not safe inside the page source: ${JSON.stringify(v)}`);
