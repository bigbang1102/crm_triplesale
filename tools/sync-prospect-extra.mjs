#!/usr/bin/env node
/**
 * Regenerates the "ข้อมูลเพิ่มเติม" tab of the prospect detail page from the GENERATED prospect form (run `npm run prospect-form:sync` first):
 *
 *   npm run prospect-extra:sync
 *
 *   features/prospects/form/prospect-form.html    (the pane `form:ctPane2` = #ld2TabExtra: sub-tabs CS · PLS · LS · LE · CRM · ข้อมูลเพิ่มเติม · survey)
 *   features/prospects/form/prospect-form.engine.ts (the IIFE of that tab: GET /board/prospect?id= → fill · ld2SaveCs() → POST /board/prospect/save)
 *   features/prospects/form/prospect-form.scss    (the ld2 block: .ld2-* rules)
 *     ->  features/prospects/detail/extra/prospect-extra.{html,scss,engine.ts}
 *
 * Why derived from the generated form and not from the Java file again: the form's generator already holds every swap of the port (env.fetch, env.t,
 * env.session, the Angular template syntax, the dark-mode CSS); the tab is the same markup and the same script, so the two can never drift — change
 * tools/sync-prospect-form.mjs (or this file), never the outputs. The pieces this file changes are listed in CHANGES below.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { engineScaffold } from './lib/port-kit.mjs';
import { undeclaredNames } from './lib/port.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const form = join(root, 'src/app/features/prospects/form');
const out = join(root, 'src/app/features/prospects/detail/extra');
mkdirSync(out, { recursive: true });
const GENERATED = 'GENERATED by tools/sync-prospect-extra.mjs from the generated prospect form (prospect-form.{html,engine.ts,scss}) — do not edit; change the generator and run `npm run prospect-extra:sync`';
const HOST = 'ts-prospect-extra';

function between(text, start, end, what) {
  const a = text.indexOf(start);
  if (a < 0) throw new Error(`prospect-extra: ${what}: start marker not found: ${start}`);
  const b = text.indexOf(end, a + start.length);
  if (b < 0) throw new Error(`prospect-extra: ${what}: end marker not found: ${end}`);
  return [a, b];
}
function replaceOnce(text, from, to, what) {
  const n = text.split(from).length - 1;
  if (n !== 1) throw new Error(`prospect-extra: ${what}: expected 1 occurrence, found ${n}: ${from}`);
  return text.replace(from, () => to);
}

/* ================================================================================================ markup */
const formHtml = readFileSync(join(form, 'prospect-form.html'), 'utf8');
{
  const [a, b] = between(formHtml, '<div id="form:ctPane2"', '<div id="form:ctPane3"', 'pane');
  let pane = formHtml.slice(a, b).trimEnd();
  // the wrapper of the pane (`ct-pane`, hidden until its tab is open) goes: the detail page shows the pane when its tab is open
  pane = pane.replace(/^<div id="form:ctPane2"[^>]*>/, '').replace(/<\/div>\s*$/, '');
  // CHANGES (1): the lock of the view mode — the detail page edits this tab (the button under the form saves it)
  pane = replaceOnce(pane, ` [attr.class]="((bean.action_type === 'view') ? 'ld2-locked' : '')"`, '', 'lock class');
  // CHANGES (2): the provinces of the LS block come from the host (the form's bean is not here)
  pane = replaceOnce(pane, '@for (ls_province of bean.listProvinceBean;', '@for (ls_province of provinces();', 'provinces');
  if (/\bbean\.|\bcan\(|\baccess\(|\bupd\(|\bsnap\(|\bvd\(/.test(pane)) throw new Error('prospect-extra: the pane reads something of the form host that this file does not give');
  writeFileSync(
    join(out, 'prospect-extra.html'),
    `<!-- ${GENERATED}
     The pane "ข้อมูลเพิ่มเติม" (#ld2TabExtra) of contracts_master_data.xhtml as the form renders it. The host gives: t(), provinces() — see prospect-extra-view.ts -->
${pane.trim()}
`,
  );
}

/* ================================================================================================ engine */
const formEngine = readFileSync(join(form, 'prospect-form.engine.ts'), 'utf8');
let body;
{
  const MARK = '/* ═══ แท็บ "ข้อมูลเพิ่มเติม"';
  const [m] = between(formEngine, MARK, 'initExtraTab', 'extra script');
  const start = formEngine.lastIndexOf('(function () {', m);
  const END = `if (readyState === 'loading') { onReady(initExtraTab); } else { initExtraTab(); }`;
  const [e] = between(formEngine, END, '})();', 'extra script end');
  const close = formEngine.indexOf('})();', e) + '})();'.length;
  body = formEngine.slice(start, close);
  // CHANGES (3): none in the script — the host sets `_ctActionType` to 'edit', so ld2ApplyViewLock() (the form's view-mode lock) does nothing
}
const header = ` Prospect extra-info engine. ${GENERATED}
 *
 * The script of the "ข้อมูลเพิ่มเติม" tab of contracts_master_data.xhtml (lead_detail's ld2…), same code as the form's engine: GET /board/prospect?id= fills the
 * fields, \`window.ld2SaveCs()\` posts them to /board/prospect/save (the host's button under the form calls it). The tab is editable (the form locked it in view mode).`;
const envBody = `  /** commonBean.msg['key'] in the active language */
  t: (key: string) => string;
  /** the id of the prospect (the script reads it as window._contractId) */
  contractId: string;
  /** the browser's own requests (/board/prospect · /board/prospect/save · /board/employees) */
  fetch: (input: string, init?: RequestInit) => Promise<Response>;
  /** sessionStorage (the sub-tab that was open) */
  session: { getItem(k: string): string | null; setItem(k: string, v: string): void; removeItem(k: string): void };`;
const scaffold = engineScaffold({
  header,
  envType: 'ProspectExtraEnv',
  envBody,
  fn: 'startProspectExtra',
  handlers: [],
  exported: ['ld2SaveCs', '_contractId', '_ctActionType', '_ldProspectData', '_ldProspectId'],
});
const ENGINE_BODY = `  /* the globals the script reads: the id of the record; the mode is not 'view', so nothing is locked */
  window._contractId = env.contractId;
  window._ctActionType = 'edit';

  ${body.replace(/\n/g, '\n  ')}
`;
const engineText = scaffold.header + scaffold.guard + ENGINE_BODY + '\n' + scaffold.footer();
const undeclared = await undeclaredNames(engineText.replace(/^\/\/ @ts-nocheck\n/, ''), ['jQuery', 'PrimeFaces', 'PF', 'TsPhone']);
if (undeclared.length) throw new Error(`prospect-extra engine: names that are not declared (a ReferenceError in strict mode): ${undeclared.join(', ')}`);
writeFileSync(join(out, 'prospect-extra.engine.ts'), engineText);

/* ================================================================================================ styles */
const formScss = readFileSync(join(form, 'prospect-form.scss'), 'utf8');
{
  const [a, b] = between(formScss, '/* ═══ ld2 extra-tab styles', '/* ───── dark_mode.css of the Java app', 'ld2 styles');
  // the block starts inside a comment line: take from the start of that line
  const from = formScss.lastIndexOf('\n', a) + 1;
  const css = formScss.slice(from, b).trimEnd();
  if (/#form\b/.test(css)) throw new Error('prospect-extra: the ld2 block names #form — this file does not know how to scope it');
  writeFileSync(
    join(out, 'prospect-extra.scss'),
    `/* ${GENERATED} */
/* the Java page's base: the form controls keep the browser's own look unless a rule below says otherwise (prospect-form.scss does the same for its host) */
:where(${HOST}) :is(button, input, select, textarea) { font: revert; letter-spacing: revert; color: revert; }
:where(${HOST}) button { padding: revert; border: revert; background: revert; cursor: revert; text-align: revert; }
${HOST} { display: block; font-size: 13px; color: #191a1c; }
html[data-theme='dark'] ${HOST} { color: #E5E7EB; }

${css}
`,
  );
}
console.log('prospect-extra synced: features/prospects/detail/extra/prospect-extra.{html,engine.ts,scss}');
