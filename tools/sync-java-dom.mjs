/** a small editor for one script: swap() = exactly one occurrence, anything else stops the run */
function editor(name, text) {
  const fail = (kind, what) => {
    throw new Error(`${name} changed — ${kind}: ${what.slice(0, 110)}`);
  };
  return {
    get text() {
      return text;
    },
    swap(find, repl) {
      const i = text.indexOf(find);
      if (i < 0) fail('NOT FOUND', find);
      if (text.indexOf(find, i + 1) >= 0) fail('AMBIGUOUS', find);
      text = text.slice(0, i) + repl + text.slice(i + find.length);
    },
    swapBlock(from, to, repl) {
      const i = text.indexOf(from);
      if (i < 0) fail('NOT FOUND', from);
      const j = text.indexOf(to, i);
      if (j < 0) fail('END NOT FOUND', to);
      text = text.slice(0, i) + repl + text.slice(j);
    },
    /** everything from `from` to the end */
    swapTail(from, repl) {
      const i = text.indexOf(from);
      if (i < 0) fail('NOT FOUND', from);
      text = text.slice(0, i) + repl;
    },
    /** every occurrence (at least one, and exactly `count` when given) */
    swapAll(find, repl, count) {
      const n = text.split(find).length - 1;
      if (n < 1) fail('NOT FOUND', find);
      if (count !== undefined && n !== count) fail(`FOUND ${n}x, expected ${count}x`, find);
      text = text.split(find).join(repl);
    },
  };
}

/** the part of the script between its IIFE wrapper */
function inner(src, open, close) {
  const i = src.indexOf(open);
  const j = src.lastIndexOf(close);
  if (i < 0 || j < 0) throw new Error('IIFE wrapper not found: ' + open);
  return src.slice(i + open.length, j);
}

