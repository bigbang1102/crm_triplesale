/** insert `: any` after every untyped `var` declarator (not for-in/of heads) and after the `)` of functions without a return type */
function annotateUntyped(code) {
  const HEAD = 'function __w() {\n';
  const wrapped = HEAD + code + '\n}';
  const offset = HEAD.length;
  const sf = ts.createSourceFile('ai_hub.ts', wrapped, ts.ScriptTarget.ES2022, true, ts.ScriptKind.TS);
  const inserts = [];
  const visit = (node) => {
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && !node.type) {
      const list = node.parent;
      const head = list.parent;
      const isLoopHead = (ts.isForInStatement(head) || ts.isForOfStatement(head)) && head.initializer === list;
      if (!isLoopHead && !ts.isCatchClause(head)) inserts.push([node.name.end, ': any']);
    }
    // `{a: 'x', b: 'y'}[key]` -> `(<any>{...})[key]`  (a lookup table indexed by a runtime string)
    if (ts.isElementAccessExpression(node) && ts.isObjectLiteralExpression(node.expression)) {
      inserts.push([node.expression.getStart(sf), '(<any>'], [node.expression.end, ')']);
    }
    if ((ts.isFunctionDeclaration(node) || ts.isFunctionExpression(node)) && !node.type && node.body && node.name?.text !== '__w') {
      const close = node.body.getFullStart();
      const text = wrapped.slice(0, close);
      inserts.push([text.lastIndexOf(')') + 1, ': any']);
    }
    ts.forEachChild(node, visit);
  };
  ts.forEachChild(sf, (n) => ts.forEachChild(n, visit));
  let out = wrapped;
  for (const [pos, text] of inserts.sort((a, b) => b[0] - a[0])) out = out.slice(0, pos) + text + out.slice(pos);
  return out.slice(offset, out.lastIndexOf('\n}'));
}

