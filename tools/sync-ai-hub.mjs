/** replace exactly one occurrence, fail loudly otherwise */
function swap(find, repl) {
  const i = body.indexOf(find);
  if (i < 0) throw new Error('ai_hub.js changed — NOT FOUND: ' + find.slice(0, 90));
  if (body.indexOf(find, i + 1) >= 0) throw new Error('ai_hub.js changed — AMBIGUOUS: ' + find.slice(0, 90));
  body = body.slice(0, i) + repl + body.slice(i + find.length);
}
/** replace the block that starts at `from` and ends right before `to` */
function swapBlock(from, to, repl) {
  const i = body.indexOf(from);
  if (i < 0) throw new Error('ai_hub.js changed — NOT FOUND: ' + from.slice(0, 90));
  const j = body.indexOf(to, i);
  if (j < 0) throw new Error('ai_hub.js changed — END NOT FOUND: ' + to.slice(0, 90));
  body = body.slice(0, i) + repl + body.slice(j);
}

